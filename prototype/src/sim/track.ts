import { Vector3 } from 'three';
import { Rng } from '../core/rng';
import { fbm1, fbm2, noise1 } from '../core/noise';
import { clamp, clamp01, lerp, smoothstep } from '../core/mathx';
import { SURFACES, canopyPressure } from './tuning';

export type SurfaceId = keyof typeof SURFACES;

export interface TrackSample {
  s: number;
  pos: Vector3;
  fwd: Vector3;
  side: Vector3;
  up: Vector3;
  width: number;
  bank: number;
  curvature: number;
  surface: SurfaceId;
  pressure: number;
}

export type FeatureType = 'boulders' | 'shelf' | 'log' | 'choke' | 'mud' | 'creek';

export interface TrackFeature {
  type: FeatureType;
  s0: number;
  s1: number;
  /** Lateral placement (m) of the feature centre, NaN for full-width. */
  lateral: number;
  seed: number;
  /** Set once the world has dressed this feature with props. */
  dressed?: boolean;
}

export interface TrackQuery {
  s: number;
  lateral: number;
  centreY: number;
  bank: number;
  width: number;
  curvature: number;
  surface: SurfaceId;
}

const STEP = 1.5;
const GRID_CELL = 24;

/**
 * Procedural natural corridor.
 *
 * The path is generated by integrating a curvature field (layered value noise)
 * rather than by placing lane nodes, which is what keeps it from reading as a
 * set of parallel lines: heading, elevation, width, banking and surface all
 * drift continuously, and the drivable band is a variable-width ribbon carved
 * through uneven terrain.
 */
export class Track {
  readonly seed: number;
  samples: TrackSample[] = [];
  features: TrackFeature[] = [];
  totalLength = 0;

  private heading = 0;
  private px = 0;
  private pz = 0;
  private py = 0;
  private grid = new Map<string, number[]>();
  private rng: Rng;

  constructor(seed = 20261122) {
    this.seed = seed;
    this.rng = new Rng(seed);
    this.ensureLength(2600);
  }

  // ---------------------------------------------------------------- generation

  ensureLength(target: number): void {
    while (this.totalLength < target) {
      this.generateStep();
    }
  }

  private generateStep(): void {
    const s = this.totalLength;

    // --- curvature: three octaves so the trail has sweepers and kinks
    const curv =
      0.0062 * noise1(s * 0.0031, 11) +
      0.0031 * noise1(s * 0.0118 + 31, 23) +
      0.0014 * noise1(s * 0.041 + 77, 37);
    this.heading += curv * STEP;

    // --- elevation
    const slope = 0.019 * noise1(s * 0.00108 + 3, 41) + 0.008 * noise1(s * 0.0043 + 19, 53);
    this.py += slope * STEP;

    // --- advance
    this.px += Math.sin(this.heading) * STEP;
    this.pz += Math.cos(this.heading) * STEP;

    const pressure = canopyPressure(s);
    const width = clamp(lerp(18, 8, pressure) + 3.0 * noise1(s * 0.0062 + 5, 67), 7, 20);
    // the outside of a bend is the higher edge, so the bank opposes the turn
    const bank = clamp(-curv * 1300, -0.055, 0.055);

    const fwd = new Vector3(Math.sin(this.heading), 0, Math.cos(this.heading));
    const side = new Vector3(fwd.z, 0, -fwd.x);
    const up = new Vector3().crossVectors(fwd, side).normalize();

    const sample: TrackSample = {
      s,
      pos: new Vector3(this.px, this.py, this.pz),
      fwd,
      side,
      up,
      width,
      bank,
      curvature: curv,
      surface: this.surfaceFieldAt(s),
      pressure,
    };

    this.samples.push(sample);
    this.totalLength = s + STEP;
    this.insertIntoGrid(this.samples.length - 1);

    if (this.samples.length % 90 === 0) this.maybeFeature(s);
  }

  private surfaceFieldAt(s: number): SurfaceId {
    const m = fbm1(s * 0.0165, 3, 21);
    if (m > 0.44) return 'mud';
    if (m < -0.4) return 'gravel';
    const l = fbm1(s * 0.052, 2, 55);
    if (l > 0.34) return 'leaves';
    if (m > 0.2 && l < -0.45) return 'rock';
    return 'dirt';
  }

  private maybeFeature(s: number): void {
    const r = this.rng;
    const roll = r.float();
    if (roll < 0.22) {
      this.features.push({ type: 'boulders', s0: s + 12, s1: s + 12, lateral: r.range(-5, 5), seed: r.int(1, 1e6) });
    } else if (roll < 0.42) {
      this.features.push({ type: 'shelf', s0: s + 20, s1: s + 22, lateral: NaN, seed: r.int(1, 1e6) });
    } else if (roll < 0.55) {
      this.features.push({ type: 'log', s0: s + 25, s1: s + 25, lateral: r.range(-4, 4), seed: r.int(1, 1e6) });
    } else if (roll < 0.66) {
      this.features.push({ type: 'choke', s0: s + 30, s1: s + 30, lateral: 0, seed: r.int(1, 1e6) });
    } else if (roll < 0.8) {
      this.features.push({ type: 'mud', s0: s + 35, s1: s + 55, lateral: NaN, seed: r.int(1, 1e6) });
    } else if (roll < 0.9) {
      this.features.push({ type: 'creek', s0: s + 40, s1: s + 48, lateral: NaN, seed: r.int(1, 1e6) });
    }
  }

  // ------------------------------------------------------------------- grid

  private cellKey(x: number, z: number): string {
    return `${Math.floor(x / GRID_CELL)},${Math.floor(z / GRID_CELL)}`;
  }

  private insertIntoGrid(index: number): void {
    const p = this.samples[index].pos;
    const key = this.cellKey(p.x, p.z);
    const bucket = this.grid.get(key);
    if (bucket) bucket.push(index);
    else this.grid.set(key, [index]);
  }

  // ------------------------------------------------------------------ query

  /** Nearest point on the corridor centreline. */
  nearest(x: number, z: number): TrackQuery {
    const cx = Math.floor(x / GRID_CELL);
    const cz = Math.floor(z / GRID_CELL);
    let best = -1;
    let bestD = Infinity;

    for (let dx = -1; dx <= 1; dx++) {
      for (let dz = -1; dz <= 1; dz++) {
        const bucket = this.grid.get(`${cx + dx},${cz + dz}`);
        if (!bucket) continue;
        for (const i of bucket) {
          const p = this.samples[i].pos;
          const d = (p.x - x) * (p.x - x) + (p.z - z) * (p.z - z);
          if (d < bestD) {
            bestD = d;
            best = i;
          }
        }
      }
    }

    if (best < 0) {
      // Fallback: coarse linear scan.
      for (let i = 0; i < this.samples.length; i += 25) {
        const p = this.samples[i].pos;
        const d = (p.x - x) * (p.x - x) + (p.z - z) * (p.z - z);
        if (d < bestD) {
          bestD = d;
          best = i;
        }
      }
    }

    // Refine against the two adjacent segments.
    let s = this.samples[best].s;
    let lateral = 0;
    let centreY = this.samples[best].pos.y;
    let bank = this.samples[best].bank;
    let width = this.samples[best].width;
    let curvature = this.samples[best].curvature;
    let surface = this.samples[best].surface;

    let refined = false;
    for (const seg of [best - 1, best]) {
      if (seg < 0 || seg + 1 >= this.samples.length) continue;
      const a = this.samples[seg];
      const b = this.samples[seg + 1];
      const abx = b.pos.x - a.pos.x;
      const abz = b.pos.z - a.pos.z;
      const len2 = abx * abx + abz * abz;
      if (len2 < 1e-6) continue;
      let t = ((x - a.pos.x) * abx + (z - a.pos.z) * abz) / len2;
      t = clamp01(t);
      const px = a.pos.x + abx * t;
      const pz = a.pos.z + abz * t;
      const dx = x - px;
      const dz = z - pz;
      const d = Math.hypot(dx, dz);
      if (!refined || d < bestD) {
        refined = true;
        bestD = d;
        s = lerp(a.s, b.s, t);
        const dirX = abx / Math.sqrt(len2);
        const dirZ = abz / Math.sqrt(len2);
        lateral = dx * dirZ - dz * dirX; // right-hand side is positive
        centreY = lerp(a.pos.y, b.pos.y, t);
        bank = lerp(a.bank, b.bank, t);
        width = lerp(a.width, b.width, t);
        curvature = lerp(a.curvature, b.curvature, t);
        surface = t < 0.5 ? a.surface : b.surface;
      }
    }

    return { s, lateral, centreY, bank, width, curvature, surface };
  }

  /** Interpolated frame at an arc-length position. */
  sampleAt(s: number): TrackSample {
    const i = clamp(Math.floor(s / STEP), 0, this.samples.length - 1);
    const a = this.samples[i];
    const b = this.samples[Math.min(i + 1, this.samples.length - 1)];
    const t = clamp01((s - a.s) / STEP);
    const fwd = a.fwd.clone().lerp(b.fwd, t).normalize();
    const side = new Vector3(fwd.z, 0, -fwd.x);
    const up = new Vector3().crossVectors(fwd, side).normalize();
    return {
      s,
      pos: a.pos.clone().lerp(b.pos, t),
      fwd,
      side,
      up,
      width: lerp(a.width, b.width, t),
      bank: lerp(a.bank, b.bank, t),
      curvature: lerp(a.curvature, b.curvature, t),
      surface: t < 0.5 ? a.surface : b.surface,
      pressure: lerp(a.pressure, b.pressure, t),
    };
  }

  /** World position of a point on the corridor floor. */
  pointAt(s: number, lateral: number, out = new Vector3()): Vector3 {
    const smp = this.sampleAt(s);
    out.copy(smp.pos)
      .addScaledVector(smp.side, lateral)
      .addScaledVector(smp.up, Math.tan(smp.bank) * lateral);
    return out;
  }

  /** Terrain height at an arbitrary world XZ (road ribbon + surrounding ground). */
  heightAt(x: number, z: number): number {
    const q = this.nearest(x, z);
    return this.heightFromQuery(x, z, q);
  }

  /**
   * Height from an already-resolved track query. The renderer uses this to
   * build the corridor ribbon without paying for a nearest-point search.
   */
  heightFromQuery(x: number, z: number, q: TrackQuery): number {
    const absLat = Math.abs(q.lateral);
    let h = q.centreY + Math.tan(q.bank) * q.lateral;

    // The trail is cut below the surrounding ground and the bank rises steeply
    // just past the edge: the corridor is held by the terrain, not by an
    // invisible wall, so the line always has to be driven rather than drifted.
    const outside = smoothstep(q.width * 0.88, q.width + 2.2, absLat);
    if (outside > 0) {
      const rough = fbm2(x * 0.017, z * 0.017, 3, 7);
      const detail = fbm2(x * 0.07, z * 0.07, 2, 13);
      h += outside * (1.5 + rough * 2.6 + detail * 0.5);
    }

    // micro relief on the driving surface keeps the suspension alive
    h += (fbm2(x * 0.22, z * 0.22, 2, 3) * 0.026) * (1 - outside * 0.6);

    // root shelves: raised ridges across the trail
    for (const f of this.featuresNear(q.s)) {
      if (f.type !== 'shelf') continue;
      const mid = (f.s0 + f.s1) * 0.5;
      const half = Math.max(0.5, (f.s1 - f.s0) * 0.5);
      const d = Math.abs(q.s - mid);
      if (d < half + 1.5) {
        const bump = Math.cos((d / (half + 1.5)) * Math.PI) * 0.42;
        h += Math.max(0, bump) * (1 - outside);
      }
    }

    return h;
  }

  /** Approximate ground normal. */
  normalAt(x: number, z: number, out = new Vector3()): Vector3 {
    const e = 0.6;
    const hL = this.heightAt(x - e, z);
    const hR = this.heightAt(x + e, z);
    const hD = this.heightAt(x, z - e);
    const hU = this.heightAt(x, z + e);
    out.set(hL - hR, 2 * e, hD - hU).normalize();
    return out;
  }

  /** Surface material under a world position. */
  surfaceAt(x: number, z: number): SurfaceId {
    const q = this.nearest(x, z);
    if (Math.abs(q.lateral) > q.width) return 'brush';
    for (const f of this.featuresNear(q.s)) {
      if (f.type === 'mud' && q.s >= f.s0 && q.s <= f.s1) return 'mud';
      if (f.type === 'creek' && q.s >= f.s0 && q.s <= f.s1) return 'water';
    }
    return q.surface;
  }

  featuresNear(s: number): TrackFeature[] {
    const out: TrackFeature[] = [];
    for (const f of this.features) {
      if (f.s0 - 60 <= s && s <= f.s1 + 60) out.push(f);
      if (f.s0 > s + 60) break;
    }
    return out;
  }

  /** Surface properties at a world position. */
  surfaceProps(x: number, z: number) {
    const id = this.surfaceAt(x, z);
    return SURFACES[id];
  }
}
