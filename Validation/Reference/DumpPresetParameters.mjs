// 🧩 The prototype's own answer to "what are this preset's settings": ConstructPresetParameters(identity) for each of the 18 presets, spelled as TOML.
//    The native catalogue (GasPresetLibrary.h) is generated from presets.js and SceneSpecification.js; this file is what it is compared against, by
//    PyroVolumeValidation, with the prototype's own code doing the arithmetic (InitialParameters, then the preset's readings, on top).
//
//    node Validation/Reference/DumpPresetParameters.mjs > Validation/Reference/PresetParameters.toml
import { PRESETS } from "../../Experimental/Fluid/src/presets.js";
import { ConstructPresetParameters, InitialParameters } from "../../Experimental/Fluid/src/SceneSpecification.js";

const Spell = (Reading) => {
  if (typeof Reading === "boolean") return Reading ? "true" : "false";
  if (typeof Reading === "string") return JSON.stringify(Reading);
  if (typeof Reading === "number" && Number.isFinite(Reading)) return String(Reading);
  throw new Error(`a setting that is neither a number, a switch nor a word: ${Reading}`);
};

const Lines = [
  "# Generated by Validation/Reference/DumpPresetParameters.mjs from Experimental/Fluid: ConstructPresetParameters for each preset.",
  "# Do not edit; PyroVolumeValidation compares GasPresetLibrary.h against it.",
  "",
];
const Table = (Title, Parameters) => {
  Lines.push(`[${Title}]`);
  for (const Key of Object.keys(Parameters).sort()) Lines.push(`${Key} = ${Spell(Parameters[Key])}`);
  Lines.push("");
};
// [initial]: what the editor opens on, and what every scene file and every preset is read on top of (the native GasSettings defaults).
Table("initial", InitialParameters);
for (const Identity of Object.keys(PRESETS)) Table(Identity, ConstructPresetParameters(Identity));
process.stdout.write(Lines.join("\n"));
