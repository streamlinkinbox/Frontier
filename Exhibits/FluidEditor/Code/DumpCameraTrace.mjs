// 🧩 The prototype's camera, driven through a scripted sequence by its own code (camera.js OrbitCamera, BoundsProjection.js ProjectBounds), with the camera's
//    state written after every step. PyroVolumeValidation replays the same sequence on the native PyroOrbitCamera and compares every number: the orbit, pan
//    and zoom rates and limits, the easing toward the aim, the ray through the volume's box and the projected bounds.
//
//    node Exhibits/FluidEditor/Code/DumpCameraTrace.mjs > Exhibits/FluidEditor/Reference/CameraTrace.toml
import { OrbitCamera } from "../../../Experimental/Fluid/src/camera.js";
import { ProjectBounds } from "../../../Experimental/Fluid/src/BoundsProjection.js";

const Camera = new OrbitCamera();
const Lines = [
  "# Generated by Exhibits/FluidEditor/Code/DumpCameraTrace.mjs from Experimental/Fluid/src/camera.js: the prototype's camera after each step of a script.",
  "# Do not edit; PyroVolumeValidation replays the script on the native camera and compares.",
  "",
];
const Spell = (Reading) => {
  if (typeof Reading === "number" && Number.isFinite(Reading)) return String(Reading);
  throw new Error(`not a finite number: ${Reading}`);
};
const List = (Readings) => `[${Readings.map(Spell).join(", ")}]`;
const Box = { Minimum: [-0.925, -0.6, -0.925], Maximum: [0.925, 1.5, 0.925] };

const Step = (Op, Arguments, Extra = []) => {
  Lines.push("[[step]]");
  Lines.push(`op = "${Op}"`);
  Lines.push(`arguments = ${List(Arguments)}`);
  Lines.push(`theta = ${Spell(Camera.theta)}`);
  Lines.push(`phi = ${Spell(Camera.phi)}`);
  Lines.push(`distance = ${Spell(Camera.distance)}`);
  Lines.push(`target = ${List(Camera.target)}`);
  Lines.push(`aim_theta = ${Spell(Camera.targetTheta)}`);
  Lines.push(`aim_phi = ${Spell(Camera.targetPhi)}`);
  Lines.push(`aim_distance = ${Spell(Camera.targetDistance)}`);
  Lines.push(`aim_centre = ${List(Camera.targetCenter)}`);
  Lines.push(`position = ${List(Camera.position)}`);
  Lines.push(`forward = ${List(Camera.forward)}`);
  Lines.push(`right = ${List(Camera.right)}`);
  Lines.push(`up = ${List(Camera.up)}`);
  for (const Line of Extra) Lines.push(Line);
  Lines.push("");
};

const Orbit = (X, Y) => { Camera.orbit(X, Y); Step("orbit", [X, Y]); };
const Pan = (X, Y) => { Camera.pan(X, Y); Step("pan", [X, Y]); };
const Zoom = (Delta) => { Camera.zoom(Delta); Step("zoom", [Delta]); };
const Update = (Dt) => { Camera.update(Dt); Step("update", [Dt]); };
const Reset = () => { Camera.reset(); Step("reset", []); };
const Aim = (Theta, Phi) => { Camera.targetTheta = Theta; Camera.targetPhi = Phi; Step("aim", [Theta, Phi]); };
const Focus = (Width, Height) => {
  Camera.reset();
  Camera.targetDistance = Math.min(9.5, Math.max(Width, Height) * 2.3);
  Step("focus", [Width, Height]);
};
// 📝 The camera set down inside a box (the near plane clips its edges): target, aim and distance at once.
const Place = (Centre, Distance) => {
  Camera.target = [...Centre];
  Camera.targetCenter = [...Centre];
  Camera.distance = Distance;
  Camera.targetDistance = Distance;
  Camera.update(1);
  Step("place", [...Centre, Distance]);
};
const Ray = (X, Y, Minimum, Maximum) => {
  const Hit = Camera.raycastVolumeUVW(X, Y, Minimum, Maximum);
  Step("ray", [X, Y, ...Minimum, ...Maximum], [`hit = ${Hit ? List(Hit) : "[]"}`]);
};
const Project = (Width, Height, Minimum, Maximum) => {
  const Segments = ProjectBounds(Camera, { boxMin: Minimum, boxMax: Maximum }, Width, Height);
  Step("project", [Width, Height, ...Minimum, ...Maximum], [`segments = [${Segments.map(List).join(", ")}]`]);
};

Step("start", []);
Update(1);
Orbit(120, 40);
for (let Count = 0; Count < 5; ++Count) Update(0.016);
Update(0.1);
Orbit(-3000, -3000);
Update(1);
Orbit(0, 100000);
Update(1);
Orbit(-85, 12);
Update(0.5);
Zoom(100);
Update(0.05);
Zoom(-100);
Zoom(-100);
Update(0.2);
for (let Count = 0; Count < 30; ++Count) Zoom(100);
Update(1);
for (let Count = 0; Count < 80; ++Count) Zoom(-100);
Update(1);
Zoom(37.5);
Update(1);
Pan(35, -22);
Update(0.2);
Pan(0, 100000);
Update(1);
Pan(-60, 9);
Update(1);
Reset();
Update(0.3);
Update(1);
Aim(Math.PI / 2, Math.PI / 2);
Update(1);
Aim(0, 0.03);
Update(1);
Focus(2.6, 2.95);
Update(1);
Focus(1.85, 2.1);
Update(1);
for (const [X, Y] of [[0, 0], [0.1, 0.05], [0.25, -0.1], [-0.15, -0.2], [0.05, 0.3], [-0.6, 0.45], [0.9, 0.9]]) Ray(X, Y, Box.Minimum, Box.Maximum);
Ray(0, 0, [49.075, -0.6, -0.925], [50.925, 1.5, 0.925]);
Orbit(210, -35);
Update(1);
for (const [X, Y] of [[0, 0], [0.2, 0.1], [0.4, 0.3], [-0.1, -0.3]]) Ray(X, Y, Box.Minimum, Box.Maximum);
Project(1280, 720, Box.Minimum, Box.Maximum);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Zoom(-100);
Update(1);
Project(1280, 720, [-0.925, -0.6, -0.925], [0.925, 1.5, 0.925]);
Place([0, 0.5, 0], 0.4);
Project(1280, 720, [-3, -3, -3], [3, 3, 3]);
process.stdout.write(Lines.join("\n"));
