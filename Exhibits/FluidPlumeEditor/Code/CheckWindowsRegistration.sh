#!/bin/bash
# 🧩 A type-check, on a host that is not Windows, of the lines in Experimental/Frontier/Native/WindowsFrontier.cpp that register the Particle editor's and
#    the Smoke & fire editor's viewport presenters. WindowsFrontier.cpp includes <windows.h> and cannot be compiled here, so this is not a build of the
#    application: it copies those lines byte for byte (the declarations they use, the retire lambda, both registrations) into a scratch translation unit
#    that includes the same engine headers, and asks the compiler to check it (-fsyntax-only, with the flags of FluidPlumeEditorCapture's own
#    compile). Nothing is linked and nothing runs. A mistake in a member name, a type or a signature of the plume lines fails it; Windows-only code
#    around them is not covered.
#
#      Exhibits/FluidPlumeEditor/Code/CheckWindowsRegistration.sh <build folder>
#
#    The build folder is a configured one (ninja -t commands needs it); FluidPlumeEditorCapture must have been configured, not necessarily built.
set -euo pipefail
BUILD="$(cd "${1:?usage: CheckWindowsRegistration.sh <build folder>}" && pwd)"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
CHECK="$BUILD/windows-registration-check"
mkdir -p "$CHECK"

python3 - "$ROOT/Experimental/Frontier/Native/WindowsFrontier.cpp" "$CHECK/WindowsRegistrationCheck.cpp" <<'PY'
import sys

source, target = sys.argv[1], sys.argv[2]
lines = open(source, encoding='utf-8').read().split('\n')


def find(text, start=0):
    for index in range(start, len(lines)):
        if text in lines[index]:
            return index
    raise SystemExit('not found in WindowsFrontier.cpp: ' + text)


def find_exact(text, start):
    for index in range(start, len(lines)):
        if lines[index].strip() == text:
            return index
    raise SystemExit('not found in WindowsFrontier.cpp: ' + text)


owner = find('std::unique_ptr<Everest::EverestWorkspace> EverestSpace;')
first = find('Frontier::VulkanPresentation *Presentation = nullptr;')
retire = find('const auto RetireSceneView = [&]()', first)
retire_end = find_exact('};', retire)
particle = find('RegisterParticleViewportPresenter(', retire_end)
plume = find('RegisterPlumeViewportPresenter(', particle)
plume_end = find_exact('});', plume)
declarations = [lines[owner]] + lines[first:retire_end + 1]
registrations = lines[particle:plume_end + 1]
if 'PlumeView' not in '\n'.join(declarations) or 'PlumeExtension' not in '\n'.join(registrations):
    raise SystemExit('the plume lines are not where the check expects them')

head = '''// Scratch, generated by CheckWindowsRegistration.sh: lines of WindowsFrontier.cpp, byte for byte, against the real headers.
#include "Engine/Diagnostics/DiagnosticJournal.h"
#include "Engine/Interface/VulkanPresentation.h"
#include "EverestWorkspace.h"
#include "Frontier/Extensions/Rendering/RenderingExtension.h"
#include "Frontier/Extensions/Particle/ParticleExtension.h"
#include "Frontier/Extensions/Plume/PlumeExtension.h"
#include "Frontier/Extensions/Interface/ViewportTexture.h"
#include "Engine/Interface/InspectorRuntime.h"
#include <exception>
#include <filesystem>
#include <memory>
#include <string>
int main()
{
'''
tail = '''
    (void)SceneViewJournalEntries;
    RetireSceneView();
    return 0;
}
'''
body = '\n'.join(declarations) + '''
    const auto ResolveBesideExecutable = [](const std::filesystem::path &Relative) { return Relative; };
    {
''' + '\n'.join(registrations) + '\n    }'
open(target, 'w', encoding='utf-8').write(head + body + tail)
print('wrote %s: %d declaration lines, %d registration lines' % (target, len(declarations), len(registrations)))
PY

# the flags are those of the capture's own compile of its source, with the dependency bookkeeping and the output dropped
COMPILE="$(cd "$BUILD" && ninja -t commands FluidPlumeEditorCapture | grep 'FluidPlumeEditorCapture.cpp.o' | head -1)"
FLAGS="$(printf '%s' "$COMPILE" | sed -e 's/^[^ ]* //' -e 's/ -MD .*$//' -e 's/ -g / /')"
cd "$CHECK"
if eval "c++ -fsyntax-only -Wall -Wextra $FLAGS WindowsRegistrationCheck.cpp"; then
    echo "WindowsFrontier.cpp's Particle and Smoke & fire registrations type-check against the real headers (syntax only; not compiled to an object, not linked, not run)"
else
    echo "FAILED: the registration lines of WindowsFrontier.cpp do not type-check" >&2
    exit 1
fi
