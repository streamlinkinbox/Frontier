// 🧩 The approved prototype's numbers for the C++ port: the default field and the catalogue's readings at thousands of points,
//    written as TOML for ForceFieldCatalogueValidation.
//
//     node Exhibits/ForceFieldEditor/Code/ExportCatalogueReference.mjs
//
// 📝 Points cluster around every source (inside, at the edge and past its reach, near the ground and aloft) and spread over
//    the 100 km view; times cross the blast window and the trigger; cell spans run from a metre to 8 km so the level of
//    detail is covered. Positions are the prototype's field axes (X east, Y up, Z south).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const Root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => ({}) }) };
{
    const Source = readFileSync(join(Root, 'Experimental/ForceFieldEditor/ForceFieldCatalogue.js'), 'utf8');
    (0, eval)(Source + '\n;globalThis.ForceFieldCatalogue = ForceFieldCatalogue;');
}
const F = globalThis.ForceFieldCatalogue;

let Seed = 20261103;
const Random = () => ((Seed = (Seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const Number17 = Reading => (Number.isInteger(Reading) ? Reading.toFixed(1) : Reading.toPrecision(17));
const Triple = Values => `[${Array.from(Values, Number17).join(', ')}]`;

const Scene = F.ConstructDefaultField();
const Storm = Scene.Sources.find(Source => Source.Name === 'Storm outflow');
Storm.TriggeredAt = 15;

const Lines = ['# Generated by Exhibits/ForceFieldEditor/Code/ExportCatalogueReference.mjs from ForceFieldCatalogue.js; do not edit.', ''];
const W = Scene.Wind;
Lines.push('[wind]', `enabled = ${W.Enabled}`, `bearing = ${Number17(W.Bearing)}`, `speed = ${Number17(W.Speed)}`,
           `gust_strength = ${Number17(W.GustStrength)}`, `gust_frequency = ${Number17(W.GustFrequency)}`, `shear = ${Number17(W.Shear)}`,
           `veer = ${Number17(W.Veer)}`, `turbulence = ${Number17(W.Turbulence)}`, `turbulence_scale = ${Number17(W.TurbulenceScale)}`,
           `seed = ${W.Seed}`, `ground_height = ${Number17(W.GroundHeight)}`, `mesoscale_scale = ${Number17(W.MesoscaleScale)}`,
           `mesoscale_strength = ${Number17(W.MesoscaleStrength)}`, '');
Lines.push('[field]', `enabled = ${Scene.Field.Enabled}`, `include_turbulence = ${Scene.Field.IncludeTurbulence}`, '');

const Keys = ['Strength', 'InnerRadius', 'CollarRadius', 'Inflow', 'Updraft', 'Height', 'Spin', 'TrackBearing', 'TrackSpeed', 'FrontSpeed',
              'CrestDepth', 'HalfWidth', 'Bearing', 'Downdraft', 'RingRadius', 'Length', 'Lift', 'RadiusY', 'Drift', 'Expansion', 'Thickness',
              'InitialRadius', 'Circulation', 'Speed', 'Swirl', 'Swallow', 'Radius', 'HalfX', 'HalfZ', 'Begins', 'Lasts', 'Repeats', 'RampIn',
              'RampOut'];
for (const Source of Scene.Sources)
{
    Lines.push('[[sources]]', `type = "${Source.Type}"`, `name = "${Source.Name}"`, `enabled = ${Source.Enabled}`, `centre = ${Triple(Source.Centre)}`,
               `reach = "${Source.Reach}"`, `falloff = "${Source.Falloff}"`, `activation = "${Source.Activation}"`,
               `triggered_at = ${Number17(Source.TriggeredAt ?? -1)}`, `acts = [${Source.Acts.map(Key => `"${Key}"`).join(', ')}]`);
    for (const Key of Keys) if (typeof Source[Key] === 'number') Lines.push(`${Key.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase()} = ${Number17(Source[Key])}`);
    Lines.push('');
}

// 📝 Sample points: around each source and across the view.
const Points = [];
for (const Source of Scene.Sources)
{
    const Reach = Source.Type === 'GustFront' ? Source.HalfWidth : Source.Reach === 'Box' ? Math.max(Source.HalfX, Source.HalfZ, (Source.Length || 0) * 1.5, 60)
                  : Source.Reach === 'Everywhere' ? 2000 : Source.Radius;
    for (let Trial = 0; Trial < 46; ++Trial)
    {
        const Angle = Random() * Math.PI * 2, Distance = Reach * 1.4 * Math.pow(Random(), 0.7);
        const Heights = [0, 0.4, 2, 6, 12, 30, 80, 200, 500, 1200, 4000];
        const Height = Source.Centre[1] + Heights[Math.floor(Random() * Heights.length)] * (Random() < 0.15 ? -0.02 : 1);
        Points.push([Source.Centre[0] + Math.cos(Angle) * Distance, Math.max(0, Height), Source.Centre[2] + Math.sin(Angle) * Distance]);
    }
}
for (let Trial = 0; Trial < 160; ++Trial)
    Points.push([(Random() - 0.5) * 100000, Math.pow(Random(), 3) * 6000, (Random() - 0.5) * 100000]);

const Times = [0, 7.5, 18.25, 33, 61.5, 95];
const Cells = [0, 0.5, 4, 64, 1024, 8192];
const Contributions = ['Flow', 'Accelerate', 'Damp'];
let Count = 0;
for (const [Index, Point] of Points.entries())
{
    const Time = Times[Index % Times.length], Cell = Cells[Math.floor(Index / Times.length) % Cells.length];
    const Prepared = F.Prepare(Scene, Time);
    for (const Contribution of Contributions)
    {
        const Out = new Float64Array(3);
        F.EvaluatePrepared(Scene, Prepared, Contribution, Point[0], Point[1], Point[2], Cell, Out, null);
        if (Contribution !== 'Flow' && Out[0] === 0 && Out[1] === 0 && Out[2] === 0 && Random() < 0.85) continue;
        Lines.push('[[samples]]', `contribution = "${Contribution}"`, 'solo = -1', `time = ${Number17(Time)}`, `cell = ${Number17(Cell)}`,
                   `point = ${Triple(Point)}`, `value = ${Triple(Out)}`, '');
        ++Count;
    }
}
// 📝 Solo: the wind alone, and each source alone at a point inside it.
for (const [Index, Source] of Scene.Sources.entries())
{
    const Type = F.TypeById[Source.Type];
    const Time = 18.25, Point = [Source.Centre[0] + 13.7, Source.Centre[1] + 3.1, Source.Centre[2] - 9.3];
    const Out = new Float64Array(3);
    F.EvaluatePrepared(Scene, F.Prepare(Scene, Time), Type.Contribution, Point[0], Point[1], Point[2], 2, Out, Source.Token);
    Lines.push('[[samples]]', `contribution = "${Type.Contribution}"`, `solo = ${Index}`, `time = ${Number17(Time)}`, 'cell = 2.0',
               `point = ${Triple(Point)}`, `value = ${Triple(Out)}`, '');
    const Wind = new Float64Array(3);
    F.EvaluatePrepared(Scene, F.Prepare(Scene, Time), 'Flow', Point[0], Point[1], Point[2], 2, Wind, 'Wind');
    Lines.push('[[samples]]', 'contribution = "Flow"', 'solo = -2', `time = ${Number17(Time)}`, 'cell = 2.0', `point = ${Triple(Point)}`,
               `value = ${Triple(Wind)}`, '');
    Count += 2;
}
// 📝 Activation, centre and profile per source at a few times.
for (const [Index, Source] of Scene.Sources.entries())
{
    for (const Time of [0, 9, 18.25, 47])
    {
        const Activation = F.ResolveActivation(Source, Time);
        const Centre = F.ResolveCentre(Source, Scene.Wind, Activation.Age);
        Lines.push('[[activations]]', `source = ${Index}`, `time = ${Number17(Time)}`, `envelope = ${Number17(Activation.Envelope)}`,
                   `age = ${Number17(Activation.Age)}`, `status = "${Activation.Status}"`, `centre = ${Triple(Centre)}`, '');
    }
    const Profile = F.ResolveProfile(Scene, Source, 10);
    Lines.push('[[profiles]]', `source = ${Index}`, `reach = ${Number17(Profile.Reach)}`,
               `distance = ${Triple(Profile.Points.map(Point => Point[0]))}`, `magnitude = ${Triple(Profile.Points.map(Point => Point[1]))}`, '');
}
const Budget = F.ResolveBudget(Scene);
Lines.push('[budget]', `baked = ${Budget.Baked.length}`, `live = ${Budget.Live.length}`, `damp = ${Budget.Damp.length}`,
           `cascade_bytes = ${Budget.CascadeBytes}`, `total_bytes = ${Budget.TotalBytes}`,
           `cells = ${Triple(Budget.Levels.map(Level => Level.Cell))}`, `extents = ${Triple(Budget.Levels.map(Level => Level.Extent))}`, '');

mkdirSync(join(Root, 'Exhibits/ForceFieldEditor/Results'), { recursive: true });
writeFileSync(join(Root, 'Exhibits/ForceFieldEditor/Results/CatalogueReference.toml'), Lines.join('\n'));
console.log(`${Scene.Sources.length} sources, ${Count} samples, ${Scene.Sources.length * 4} activations, ${Scene.Sources.length} profiles`);
