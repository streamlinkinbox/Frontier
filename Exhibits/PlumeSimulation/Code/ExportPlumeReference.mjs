// 📝 AdvanceOnset over a script in 64 step phases: entry in 0.0166666 s steps (three of them fall 2e-7 s short of the 0.05 s the onset asks for), the hysteresis
//    zone ending in a step above the release power, a quiet run of four 0.02 s steps (0.08 s exactly), a slip below the minimum, a mixed run, and a last quiet
//    run; every seventh step of the mixed phases has no time and every 53rd no contact.
{
    const Projection = new PlumeSourceProjection();
    const Onset = { RequestSeconds: 0.0, QuietSeconds: 0.0, Active: false };
    const Rng = Mulberry32(0x0A5E7001);
    const Steps = 640, Inputs = [], Out = { Active: [], Request: [], Quiet: [] };
    for (let Step = 0; Step < Steps; ++Step)
    {
        const Phase = Step % 64;
        const Power = Phase < 12 ? 330 + 80 * Rng() : Phase < 19 ? 90 + 80 * Rng() : Phase === 19 ? 150 : Phase < 28 ? 20 + 40 * Rng() : Phase < 48 ? 330 + 80 * Rng()
                    : Phase < 56 ? 400 * Rng() : 20 + 40 * Rng();
        const Slip = (Phase >= 40 && Phase < 48 ? 0.1 : 0.45) + 0.3 * Rng();
        const Contact = Step % 53 !== 0;
        const Seconds = (Phase < 12) ? 0.0166666 : Phase < 20 ? 0.01 : (Phase < 28 || Phase >= 56) ? 0.02 : (Step % 7 === 0 ? 0 : 0.01);
        Inputs.push(Power, Slip, Contact ? 1 : 0, Seconds);
        Out.Active.push(Projection.AdvanceOnset(Onset, Power, Slip, Contact, Seconds));
        Out.Request.push(Onset.RequestSeconds);
        Out.Quiet.push(Onset.QuietSeconds);
    }
    Emit();
    Emit("[Onset]");
    Emit(`Steps = ${Steps}`);
    Emit(`InputHash = "${HashDoubles(Inputs)}"`);
    Emit(`Active = ${Flags(Out.Active)}`);
    Emit(`RequestSeconds = ${List(Out.Request)}`);
    Emit(`QuietSeconds = ${List(Out.Quiet)}`);
}

// 📝 Project with exhausts, afterfire, bursts, two ignited tyres and all four ember and light kinds; the first bursts overflow the queue of four.
const DirectSteps = 240;
const DirectInputs = (Step) =>
{
    const Heading = [1, 0, 0];
    const Wheel = (Index) =>
    {
        const Contact = [2.0 + 1.3 * Index, 0.8 - 1.6 * (Index & 1), 0.0];
        return {
            InContact: Step % 61 > 4, SlidingPower: 2500 + 9000 * Index * Ramp(Step, 10, 60), SlipSpeed: 0.2 + 2.5 * Ramp(Step, 5, 50),
            ContactPoint: Contact, ContactVelocity: [3 + 0.5 * Index, 0.25 * Tri(Step, 40), 0], HubPosition: [Contact[0], Contact[1], 0.34],
            Thermal: { Ignited: Index < 2 && Step >= 40 && Step < 200, CombustionPower: 6000 + 5000 * Index, SurfaceTemperature: 320 + 3 * Step },
            Burst: Step % 90 < 6, Radius: Index === 3 ? 0 : 0.33, Longitudinal: Index === 2 ? undefined : [Heading[0], 0.05 * Index, 0], SurfaceSpeed: 5 + 4 * Index - 0.04 * Step
        };
    };
    return {
        Telemetry: { Position: [2, 0, 0.5], Velocity: [3.0, 0.2 * Tri(Step, 80), 0.0],
                     Exhausts: [{ Position: [-1.9, 0.5, 0.35], Direction: [-1, 0.1, 0.05] }, { Position: [-1.9, -0.5, 0.35], Direction: [-1, -0.1, 0.05] }, { Position: [0, 0, 0], Direction: [-1, 0, 0] }],
                     AfterfireSeconds: Step < 150 ? 0.5 : 0, Wheels: [0, 1, 2, 3].map(Wheel) },
        Options: { Afterfire: Step % 200 < 150, EmissionRate: 1.25, SmokeYield: 1.0, HeatYield: 0.8, SootYield: 1.1, FireLight: 1.3, Embers: 0.9 },
        Seconds: 1 / 60
    };
};
const QueueBursts = (Projection, Step) =>
{
    if ([10, 30, 31, 32, 33, 34].includes(Step))
    {
        Projection.QueueBurst({ Position: [0.5 * Step, 0.1, 0.3], Radius: 0.3 + 0.01 * Step, Velocity: [0, 0.5, 1.5], Smoke: 4, Heat: 30, Flame: Step === 31 ? 6 : 0, Soot: 2, Seconds: 0.05 + 0.01 * (Step % 7) });
    }
};
{
    const FlattenDirect = (Inputs) =>
    {
        const { Telemetry, Options } = Inputs;
        const Values = [Inputs.Seconds, ...Telemetry.Position, ...Telemetry.Velocity, Telemetry.AfterfireSeconds, Options.Afterfire ? 1 : 0, Options.EmissionRate, Options.SmokeYield,
                        Options.HeatYield, Options.SootYield, Options.FireLight, Options.Embers];
        for (const Exhaust of Telemetry.Exhausts) Values.push(...Exhaust.Position, ...Exhaust.Direction);
        for (const Wheel of Telemetry.Wheels)
        {
            Values.push(Wheel.InContact ? 1 : 0, Wheel.SlidingPower, Wheel.SlipSpeed, ...Wheel.ContactPoint, ...Wheel.ContactVelocity, ...Wheel.HubPosition, Wheel.Thermal.Ignited ? 1 : 0,
                        Wheel.Thermal.CombustionPower, Wheel.Thermal.SurfaceTemperature, Wheel.Burst ? 1 : 0, Wheel.Radius, Wheel.Longitudinal ? 1 : 0, ...(Wheel.Longitudinal ?? [0, 0, 0]), Wheel.SurfaceSpeed);
        }
        return Values;
    };
    const Projection = new PlumeSourceProjection();
    const Out = { Count: [], ActiveTyres: [], Popping: [], Hash: [], Seed: [], Lights: [], Embers: [], Bursts: [], Elapsed: [] };
    const Inputs = [];
    const RecordsHash = () => Fnv1a64(new Uint8Array(Projection.Records.buffer));
    for (let Step = 0; Step < DirectSteps; ++Step)
    {
        QueueBursts(Projection, Step);
        const Refresh = DirectInputs(Step);
        Inputs.push(...FlattenDirect(Refresh));
        Projection.Project(Refresh.Telemetry, Refresh.Seconds, Refresh.Options);
        Out.Count.push(Projection.Count);
        Out.ActiveTyres.push(Projection.ActiveTyres);
        Out.Popping.push(Projection.Popping);
        Out.Hash.push(RecordsHash());
        Out.Seed.push(Projection.Seed >>> 0);
        Out.Lights.push(Projection.Lights.map((Light) => [...Light.Position, Light.Radius, ...Light.Radiance]));
        Out.Embers.push(Projection.Embers.map((Ember) => [...Ember.Position, ...Ember.Velocity, Ember.Rate, Ember.Temperature, Ember.Spread, Ember.Lift, Ember.Gravity, Ember.Life]));
        Out.Bursts.push(Projection.Bursts.map((Burst) => Burst.Remaining));
        Out.Elapsed.push(Projection.Elapsed);
    }
    Emit();
    Emit("[Direct]");
    Emit(`Steps = ${DirectSteps}`);
    Emit(`InputHash = "${HashDoubles(Inputs)}"`);
    Emit(`Count = ${Ints(Out.Count)}`);
    Emit(`ActiveTyres = ${Ints(Out.ActiveTyres)}`);
    Emit(`Popping = ${Flags(Out.Popping)}`);
    Emit(`RecordsHash = ${Strings(Out.Hash)}`);
    Emit(`Seed = ${Ints(Out.Seed)}`);
    Emit(`Elapsed = ${List(Out.Elapsed)}`);
    // 📝 Lights, embers and bursts, flattened with their counts: a list per step of numbers, in the order the projection left them.
    Emit(`LightCount = ${Ints(Out.Lights.map((Entry) => Entry.length))}`);
    Emit(`LightValues = ${List(Out.Lights.flat(2))}`);
    Emit(`EmberCount = ${Ints(Out.Embers.map((Entry) => Entry.length))}`);
    Emit(`EmberValues = ${List(Out.Embers.flat(2))}`);
    Emit(`BurstCount = ${Ints(Out.Bursts.map((Entry) => Entry.length))}`);
    Emit(`BurstValues = ${List(Out.Bursts.flat())}`);
    // 📝 ResolveBounds on the last step, and on an empty projection.
    const Bounds = Projection.ResolveBounds();
    Emit(`BoundsMinimum = ${List(Bounds.Minimum)}`);
    Emit(`BoundsMaximum = ${List(Bounds.Maximum)}`);
    const Empty = new PlumeSourceProjection().ResolveBounds();
    Emit(`EmptyBoundsFinite = ${Flags([Empty.Minimum.every(Number.isFinite), Empty.Maximum.every(Number.isFinite)])}`);
}

