// 📝 Fade: the burnout's first 60 refreshes, 840 of silence at 16 Hz — the plume's twelve seconds of decay end exactly on a refresh (191 × 1/16 s and
//    four of 1/64 s, the step clock holding a partial step when residency stops) — and the burnout's script again, so residency stops and restarts.
function FadeInputs(Step, Noise)
{
    const Refresh = BurnoutInputs(Step % 300, Noise);
    Refresh.Seconds = (Step >= 251 && Step <= 254) ? 1 / 64 : 0.0625;
    Refresh.Gas = ConstructGas({ Preset: "Tyre smoke", Overrides: {} });
    Refresh.Enabled = true;
    if (Step >= 60 && Step < 900)
    {
        Refresh.Readings.forEach((Reading) => { Reading.SlidingPower = 0; });
        Refresh.Thermal.Wheels.forEach((Heat) => { Heat.Ignited = false; });
        Refresh.Emissions.forEach((Emission) => { Emission.Active = false; });
    }
    return Refresh;
}

function ExportSequence(Section, Steps, Seed, Make, Grade)
{
    const Space = new SmokeSequence(Exchange, null, Grade);
    const Rng = Mulberry32(Seed);
    const Out = {
        Count: [], ActiveTyres: [], Hash: [], Lights: [], Embers: [], Resident: [], StepPending: [], State: [], Accumulator: [], Quiet: [], Ordinal: [], Elapsed: [],
        StepsTaken: [], Origin: [], Prior: [], RecordHash: [], FireLightHash: [], FireLightCount: [], Sources: [], Ticks: [], Relocations: [], FireIntensity: [], FirePosition: [],
        Sweeps: [], RecordWords: []
    };
    const Inputs = [];
    for (let Step = 0; Step < Steps; ++Step)
    {
        const Noise = Array.from({ length: 8 }, () => Rng());
        const Refresh = Make(Step, Noise);
        Inputs.push(...FlattenBurnout(Refresh));
        Space.Advance(Refresh.Seconds, { Enabled: Refresh.Enabled, Vehicle: Refresh.Vehicle, Light: { Direction: LightDirection }, Gas: Refresh.Gas,
                                       Readings: Refresh.Readings, Thermal: Refresh.Thermal, Emissions: Refresh.Emissions });
        Out.Count.push(Space.Sources.Count);
        Out.ActiveTyres.push(Space.Sources.ActiveTyres);
        Out.Hash.push(Fnv1a64(new Uint8Array(Space.Sources.Records.buffer)));
        Out.Lights.push(Space.Sources.Lights.map((Light) => [...Light.Position, Light.Radius, ...Light.Radiance]));
        Out.Embers.push(Space.Sources.Embers.map((Ember) => [...Ember.Position, ...Ember.Velocity, Ember.Rate, Ember.Temperature, Ember.Spread, Ember.Lift, Ember.Gravity, Ember.Life]));
        Out.Resident.push(Space.Resident);
        Out.StepPending.push(Space.StepPending);
        Out.State.push(Space.State);
        Out.Accumulator.push(Space.Accumulator);
        Out.Quiet.push(Space.QuietSeconds);
        Out.Ordinal.push(Space.StepOrdinal);
        Out.Elapsed.push(Space.ElapsedSeconds);
        Out.StepsTaken.push(Space.StepsTaken);
        Out.Origin.push(...Space.Origin);
        Out.Prior.push(...Space.PriorOrigin);
        Out.RecordHash.push(Fnv1a64(new Uint8Array(Space.RecordBytes)));
        Out.FireLightHash.push(Fnv1a64(new Uint8Array(Space.FireLightBytes)));
        Out.FireLightCount.push(Space.FireLightCount);
        Out.Sources.push(Space.Metrics.Sources);
        Out.Ticks.push(Space.Metrics.Ticks);
        Out.Relocations.push(Space.Metrics.Relocations);
        Out.FireIntensity.push(Space.FireLight.Intensity);
        Out.FirePosition.push(...Space.FireLight.Position);
        Out.Sweeps.push(Space.Configuration.PressureSweeps);
        if (Step % 60 === 59 && Space.StepPending) Out.RecordWords.push(...new Uint32Array(Space.RecordBytes));
        // 📝 What RecordTransport leaves behind after a step is recorded on the device: the parity flips, the step is counted.
        if (Space.StepPending)
        {
            Space.State = 1 - Space.State;
            Space.StepPending = false;
            Space.StepsTaken++;
        }
    }
    Emit();
    Emit(`[${Section}]`);
    Emit(`Steps = ${Steps}`);
    Emit(`InputHash = "${HashDoubles(Inputs)}"`);
    Emit(`Count = ${Ints(Out.Count)}`);
    Emit(`ActiveTyres = ${Ints(Out.ActiveTyres)}`);
    Emit(`RecordsHash = ${Strings(Out.Hash)}`);
    Emit(`LightCount = ${Ints(Out.Lights.map((Entry) => Entry.length))}`);
    Emit(`LightValues = ${List(Out.Lights.flat(2))}`);
    Emit(`EmberCount = ${Ints(Out.Embers.map((Entry) => Entry.length))}`);
    Emit(`EmberValues = ${List(Out.Embers.flat(2))}`);
    Emit(`Resident = ${Flags(Out.Resident)}`);
    Emit(`StepPending = ${Flags(Out.StepPending)}`);
    Emit(`State = ${Ints(Out.State)}`);
    Emit(`Accumulator = ${List(Out.Accumulator)}`);
    Emit(`QuietSeconds = ${List(Out.Quiet)}`);
    Emit(`StepOrdinal = ${Ints(Out.Ordinal)}`);
    Emit(`ElapsedSeconds = ${List(Out.Elapsed)}`);
    Emit(`StepsTaken = ${Ints(Out.StepsTaken)}`);
    Emit(`Origin = ${Ints(Out.Origin)}`);
    Emit(`PriorOrigin = ${Ints(Out.Prior)}`);
    Emit(`RecordHash = ${Strings(Out.RecordHash)}`);
    Emit(`FireLightHash = ${Strings(Out.FireLightHash)}`);
    Emit(`FireLightCount = ${Ints(Out.FireLightCount)}`);
    Emit(`MetricSources = ${Ints(Out.Sources)}`);
    Emit(`MetricTicks = ${Ints(Out.Ticks)}`);
    Emit(`MetricRelocations = ${Ints(Out.Relocations)}`);
    Emit(`FireIntensity = ${List(Out.FireIntensity)}`);
    Emit(`FirePosition = ${List(Out.FirePosition)}`);
    Emit(`PressureSweeps = ${Ints(Out.Sweeps)}`);
    Emit(`RecordWords = ${Ints(Out.RecordWords)}`);
    // 📝 Clear().
    Space.Clear();
    Emit(`ClearedResident = ${Flags([Space.Resident])}`);
    Emit(`ClearedIntensity = ${Float(Space.FireLight.Intensity)}`);
    Emit(`ClearedPrior = ${Ints(Space.PriorOrigin)}`);
}

ExportSequence("Burnout", BurnoutSteps, 0x51ED270B, BurnoutInputs, "high");
ExportSequence("Fade", FadeSteps, 0xFADE0001, FadeInputs, "medium");

// 📝 The host's debug channel: Settings.Inspection 10 sets the record's debug word. SmokeSequence.Advance never passes it, so Schedule is called directly.
{
    const Space = new SmokeSequence(Exchange, null, "low");
    const Rng = Mulberry32(0x1A5BEC71);
    let Refresh = null, Inputs = [];
    for (let Step = 60; Step < 68; ++Step)
    {
        Refresh = BurnoutInputs(Step, Array.from({ length: 8 }, () => Rng()));
        Inputs.push(...FlattenBurnout(Refresh));
        Space.Advance(Refresh.Seconds, { Enabled: true, Vehicle: Refresh.Vehicle, Light: { Direction: LightDirection }, Gas: Refresh.Gas, Readings: Refresh.Readings, Thermal: Refresh.Thermal, Emissions: Refresh.Emissions });
    }
    const Words = [];
    for (const Variant of [{ Inspection: 10 }, { Inspection: 0 }, { Inspection: 7 }, { PlumeDissipation: 0.99, PlumeCooling: 0.99 }])
    {
        const Settings = Object.assign(MapPlumeSettings(Refresh.Gas, true), Variant);
        Space.Schedule(1 / 60, 1 / 60, Refresh.Vehicle.Position, Space.Sources, Settings, LightDirection);
        Words.push(...new Uint32Array(Space.RecordBytes));
    }
    Emit();
    Emit("[Inspection]");
    Emit(`InputHash = "${HashDoubles(Inputs)}"`);
    Emit(`RecordWords = ${Ints(Words)}`);
}

