// 📝 Everything the step fed in, in a fixed order, as doubles, for the input hash.
function FlattenBurnout(Inputs)
{
    const Values = [Inputs.Seconds, ...Inputs.Vehicle.Position, ...Inputs.Vehicle.LinearVelocity, ...Inputs.Vehicle.Orientation, Inputs.Enabled ? 1 : 0];
    Inputs.Vehicle.Wheels.forEach((Wheel, Index) =>
    {
        const Reading = Inputs.Readings[Index], Heat = Inputs.Thermal.Wheels[Index];
        Values.push(Wheel.Steer, Wheel.Radius, Wheel.Spin, Reading.ContactFraction, Reading.OnDebris ? 1 : 0, Reading.Shredded ? 1 : 0, Reading.SlidingPower,
                    Reading.SlipSpeed, ...Reading.ContactPoint, ...Reading.ContactVelocity, ...Reading.HubPosition,
                    Heat.Ignited ? 1 : 0, Heat.CombustionPower, Heat.Surface, Heat.Burst ? 1 : 0);
    });
    for (const Emission of Inputs.Emissions)
    {
        Values.push(Emission.Active ? 1 : 0, ...Emission.Position, Emission.Radius, ...Emission.Velocity, Emission.SmokeRate, Emission.HeatRate, Emission.FlameRate, Emission.SootRate);
    }
    Values.push(...Object.keys(GasParameterCatalogue).map((Key) => Inputs.Gas[Key]));
    return Values;
}

