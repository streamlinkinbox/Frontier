void CheckPresets(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Presets"].as_table();
    const auto         Names = ReadStrings(Table["Names"]);
    const auto&        Presets = QueryGasPresets();
    Expect(Names.size() == Presets.size(), "six presets");
    for (size_t Index = 0; Index < std::min(Names.size(), Presets.size()); ++Index)
    {
        const toml::table& Entry = *Table["P" + std::to_string(Index)].as_table();
        const GasPreset&   Preset = Presets[Index];
        Expect(Preset.Name == Names[Index], "preset " + Names[Index] + " name");
        const auto Keys = ReadStrings(Entry["OverrideKeys"]);
        const auto Values = ReadNumbers(Entry["OverrideValues"]);
        Expect(Keys.size() == Preset.Count, Names[Index] + " has " + std::to_string(Preset.Count) + " overrides, the reference " + std::to_string(Keys.size()));
        for (size_t Override = 0; Override < std::min(Keys.size(), Preset.Count); ++Override)
        {
            Expect(Preset.Values[Override].Key == Keys[Override] && Preset.Values[Override].Value == Values[Override], Names[Index] + " override " + Keys[Override]);
        }
        const GasParameters Gas = ApplyGasPreset(Preset);
        ExpectNumbers(FlattenGas(Gas), ReadNumbers(Entry["Gas"]), Names[Index] + " gas");
        ExpectNumbers(FlattenSettings(MapPlumeSettings(Gas, true)), ReadNumbers(Entry["Settings"]), Names[Index] + " settings");
        ExpectNumbers(FlattenSettings(MapPlumeSettings(Gas, false)), ReadNumbers(Entry["SettingsOff"]), Names[Index] + " settings, disabled");
    }
}

void CheckMapping(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Mapping"].as_table();
    const size_t       Count = static_cast<size_t>(Table["Count"].value<int64_t>().value_or(0));
    const toml::array& GasRows      = *Table["Gas"].as_array();
    const toml::array& SettingsRows = *Table["Settings"].as_array();
    Expect(GasRows.size() == Count && SettingsRows.size() == Count, "forty gas sets");
    for (size_t Index = 0; Index < std::min({Count, GasRows.size(), SettingsRows.size()}); ++Index)
    {
        const GasParameters Set = GasFromValues(ReadNumbers(toml::node_view<const toml::node>(GasRows[Index])));
        ExpectNumbers(FlattenSettings(MapPlumeSettings(Set, Index % 3 != 0)), ReadNumbers(toml::node_view<const toml::node>(SettingsRows[Index])),
                      "MapPlumeSettings of gas set " + std::to_string(Index));
    }
}

void CheckDetail(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Detail"].as_table();
    const std::vector<uint8_t> Texels = PlumeSchedule::ConstructDetail();
    Expect(Texels.size() == static_cast<size_t>(Table["Bytes"].value<int64_t>().value_or(-1)), "the detail volume's size");
    Expect(HashBytes(Texels) == Table["Hash"].value<std::string>().value_or(""), "the detail volume's hash (" + HashBytes(Texels) + ")");
    const auto Probes = ReadIntegers(Table["Probes"]);
    const auto Probed = ReadIntegers(Table["ProbeTexels"]);
    bool       Same   = Probed.size() == Probes.size() * 4;
    for (size_t Index = 0; Same && Index < Probes.size(); ++Index)
    {
        for (size_t Channel = 0; Channel < 4; ++Channel)
        {
            Same = Same && Texels[static_cast<size_t>(Probes[Index]) * 4 + Channel] == Probed[Index * 4 + Channel];
        }
    }
    Expect(Same, "eleven probed texels");
}

void CheckFireLights(const toml::table& Reference)
{
    const toml::table& Table = *Reference["FireLights"].as_table();
    const auto         Cases = ReadIntegers(Table["Cases"]);
    const toml::array& Words = *Table["Words"].as_array();
    PlumeSchedule      Schedule(QueryPlumeGrades()[1]);
    for (size_t Index = 0; Index < Cases.size(); ++Index)
    {
        const size_t Count = static_cast<size_t>(Cases[Index]);
        std::vector<PlumeFireLight> Lights;
        for (size_t Light = 0; Light < Count; ++Light)
        {
            Lights.push_back({{1.5 * Light + 0.25, -2.0 + Light, 0.5 + 0.125 * Light}, 0.25 + 0.05 * Light, {4 - 0.5 * Light, 1.7 - 0.2 * Light, 0.6}});
        }
        Schedule.AssignFireLights(Lights);
        const auto Expected = ReadIntegers(toml::node_view<const toml::node>(Words[Index]));
        std::vector<uint32_t> Actual(Schedule.QueryFireLightBytes().size() / 4);
        std::memcpy(Actual.data(), Schedule.QueryFireLightBytes().data(), Schedule.QueryFireLightBytes().size());
        bool Same = Expected.size() == Actual.size();
        for (size_t Word = 0; Same && Word < Actual.size(); ++Word)
        {
            Same = static_cast<int64_t>(Actual[Word]) == Expected[Word];
        }
        Expect(Same, "the fire-light record of " + std::to_string(Count) + " lights, word for word");
        Expect(Schedule.QueryFireLightCount() == std::min<size_t>(Count, FireLightLimit), "the fire-light count of " + std::to_string(Count) + " lights");
    }
}

void CheckDescription(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Description"].as_table();
    const auto         Names = ReadStrings(Table["Names"]);
    const toml::array& Rows = *Table["Rows"].as_array();
    for (size_t Index = 0; Index < Names.size(); ++Index)
    {
        SmokeSequence Sequence(Names[Index]);
        const PlumeDescription D = Sequence.QuerySchedule().QueryDescription();
        const auto Row = ReadStrings(toml::node_view<const toml::node>(Rows[Index]));
        const double Edge = D.EdgeThermo;
        const std::string Thermo   = std::to_string(D.Thermo[0]) + "×" + std::to_string(D.Thermo[1]) + "×" + std::to_string(D.Thermo[2]) + " @ " + FixedZero(Edge * 100) + " cm";
        const std::string Velocity = std::to_string(D.Velocity[0]) + "×" + std::to_string(D.Velocity[1]) + "×" + std::to_string(D.Velocity[2]) + " @ " + FixedZero(D.EdgeVelocity * 100) + " cm";
        const std::string Span     = FixedZero(D.Span[0]) + " × " + FixedZero(D.Span[1]) + " × " + FixedZero(D.Span[2]) + " m";
        Expect(Thermo == Row[0] && Velocity == Row[1] && Span == Row[2], "the " + Names[Index] + " description's extents: " + Thermo + ", " + Velocity + ", " + Span);
        Expect(std::to_string(D.Cells) == Row[3] && std::to_string(D.Bytes) == Row[4], "the " + Names[Index] + " description's cells and bytes");
        Expect(D.Grade == Row[5] && std::to_string(D.Sweeps) == Row[6] && std::to_string(D.Samples) == Row[7], "the " + Names[Index] + " description's grade, sweeps and samples");
    }
}

