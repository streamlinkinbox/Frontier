// 📝 Equal to 1e-12 relative; exact matches are counted so the report says how many doubles needed the tolerance.
bool Near(double Left, double Right, double Tolerance = 1.0e-12)
{
    ++Doubles;
    if (Left == Right)
    {
        ++Exact;
        return true;
    }
    return std::abs(Left - Right) <= Tolerance * std::max(1.0, std::max(std::abs(Left), std::abs(Right)));
}

uint64_t Fnv1a64(const unsigned char* Bytes, size_t Count)
{
    uint64_t Hash = 0xcbf29ce484222325ull;
    for (size_t Index = 0; Index < Count; ++Index)
    {
        Hash ^= Bytes[Index];
        Hash *= 0x100000001b3ull;
    }
    return Hash;
}

std::string HexOf(uint64_t Value)
{
    char Text[17];
    std::snprintf(Text, sizeof(Text), "%016llx", static_cast<unsigned long long>(Value));
    return Text;
}

std::string HashDoubles(const std::vector<double>& Values)
{
    return HexOf(Fnv1a64(reinterpret_cast<const unsigned char*>(Values.data()), Values.size() * sizeof(double)));
}

template <typename Container>
std::string HashBytes(const Container& Bytes)
{
    return HexOf(Fnv1a64(reinterpret_cast<const unsigned char*>(Bytes.data()), Bytes.size() * sizeof(typename Container::value_type)));
}

// 📝 Compares two lists of doubles to the tolerance; reports the first mismatch only.
void ExpectNumbers(const std::vector<double>& Actual, const std::vector<double>& Reference, const std::string& Label)
{
    Expect(Actual.size() == Reference.size(), Label + ": " + std::to_string(Actual.size()) + " values, the reference has " + std::to_string(Reference.size()));
    const size_t Count = std::min(Actual.size(), Reference.size());
    for (size_t Index = 0; Index < Count; ++Index)
    {
        if (!Near(Actual[Index], Reference[Index]))
        {
            Expect(false, Label + "[" + std::to_string(Index) + "]: " + std::to_string(Actual[Index]) + " against " + std::to_string(Reference[Index]));
            return;
        }
    }
    Expect(true, Label);
}

