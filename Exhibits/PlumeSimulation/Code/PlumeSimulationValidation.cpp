void CheckOnset(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Onset"].as_table();
    PlumeSourceProjection Projection;
    SmokeOnset            Onset;
    Mulberry32            Rng(0x0A5E7001u);
    const int             Steps = static_cast<int>(Table["Steps"].value<int64_t>().value_or(0));
    const auto            Active = ReadFlags(Table["Active"]);
    const auto            Request = ReadNumbers(Table["RequestSeconds"]), Quiet = ReadNumbers(Table["QuietSeconds"]);
    std::vector<double>   Inputs;
    std::vector<bool>     ActiveOut;
    std::vector<double>   RequestOut, QuietOut;
    for (int Step = 0; Step < Steps; ++Step)
    {
        const int    Phase = Step % 64;
        const double Power = Phase < 12 ? 330 + 80 * Rng() : Phase < 19 ? 90 + 80 * Rng() : Phase == 19 ? 150.0 : Phase < 28 ? 20 + 40 * Rng() : Phase < 48 ? 330 + 80 * Rng()
                           : Phase < 56 ? 400 * Rng() : 20 + 40 * Rng();
        const double Slip = (Phase >= 40 && Phase < 48 ? 0.1 : 0.45) + 0.3 * Rng();
        const bool   Contact = Step % 53 != 0;
        const double Seconds = (Phase < 12) ? 0.0166666 : Phase < 20 ? 0.01 : (Phase < 28 || Phase >= 56) ? 0.02 : (Step % 7 == 0 ? 0.0 : 0.01);
        Inputs.insert(Inputs.end(), {Power, Slip, Contact ? 1.0 : 0.0, Seconds});
        ActiveOut.push_back(Projection.AdvanceOnset(Onset, Power, Slip, Contact, Seconds));
        RequestOut.push_back(Onset.RequestSeconds);
        QuietOut.push_back(Onset.QuietSeconds);
    }
    Expect(HashDoubles(Inputs) == Table["InputHash"].value<std::string>().value_or(""), "the onset script's inputs equal the exporter's");
    Expect(ActiveOut == Active, "the onset's Active over " + std::to_string(Steps) + " steps (" + std::to_string(std::count(ActiveOut.begin(), ActiveOut.end(), true)) + " active)");
    ExpectNumbers(RequestOut, Request, "onset RequestSeconds");
    ExpectNumbers(QuietOut, Quiet, "onset QuietSeconds");
}

// 📝 One list of numbers per step, stored flat with a count per step: compares the step's slice.
bool SliceNear(const std::vector<double>& Values, size_t& Offset, size_t Count, const std::vector<double>& Actual)
{
    if (Actual.size() != Count || Offset + Count > Values.size())
    {
        return false;
    }
    bool Same = true;
    for (size_t Index = 0; Index < Count; ++Index)
    {
        Same = Near(Actual[Index], Values[Offset + Index]) && Same;
    }
    Offset += Count;
    return Same;
}

std::vector<double> FlattenLights(const std::vector<PlumeFireLight>& Lights)
{
    std::vector<double> Values;
    for (const PlumeFireLight& Light : Lights)
    {
        Values.insert(Values.end(), {Light.Position[0], Light.Position[1], Light.Position[2], Light.Radius, Light.Radiance[0], Light.Radiance[1], Light.Radiance[2]});
    }
    return Values;
}

std::vector<double> FlattenEmbers(const std::vector<FluidDynamics::PlumeEmber>& Embers)
{
    std::vector<double> Values;
    for (const FluidDynamics::PlumeEmber& Ember : Embers)
    {
        Values.insert(Values.end(), {Ember.Position[0], Ember.Position[1], Ember.Position[2], Ember.Velocity[0], Ember.Velocity[1], Ember.Velocity[2], Ember.Rate,
                                     Ember.Temperature, Ember.Spread, Ember.Lift, Ember.Gravity, Ember.Life});
    }
    return Values;
}

void CheckDirect(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Direct"].as_table();
    const int          Steps = static_cast<int>(Table["Steps"].value<int64_t>().value_or(0));
    const auto         Count = ReadIntegers(Table["Count"]), ActiveTyres = ReadIntegers(Table["ActiveTyres"]), Seed = ReadIntegers(Table["Seed"]);
    const auto         Popping = ReadFlags(Table["Popping"]);
    const auto         Hashes = ReadStrings(Table["RecordsHash"]);
    const auto         Elapsed = ReadNumbers(Table["Elapsed"]);
    const auto         LightCount = ReadIntegers(Table["LightCount"]), EmberCount = ReadIntegers(Table["EmberCount"]), BurstCount = ReadIntegers(Table["BurstCount"]);
    const auto         LightValues = ReadNumbers(Table["LightValues"]), EmberValues = ReadNumbers(Table["EmberValues"]), BurstValues = ReadNumbers(Table["BurstValues"]);

    PlumeSourceProjection Projection;
    std::vector<double>   Inputs;
    size_t                LightOffset = 0, EmberOffset = 0, BurstOffset = 0;
    int                   CountMiss = 0, TyreMiss = 0, PopMiss = 0, HashMiss = 0, SeedMiss = 0, ElapsedMiss = 0, LightMiss = 0, EmberMiss = 0, BurstMiss = 0;
    int                   FirstHashMiss = -1;
    for (int Step = 0; Step < Steps; ++Step)
    {
        QueueBursts(Projection, Step);
        const DirectRefresh Refresh = ConstructDirect(Step);
        const std::vector<double> Flat = FlattenDirect(Refresh);
        Inputs.insert(Inputs.end(), Flat.begin(), Flat.end());
        Projection.Project(Refresh.Telemetry, Refresh.Seconds, Refresh.Options);
        CountMiss += Projection.QueryCount() != static_cast<uint32_t>(Count[Step]);
        TyreMiss  += Projection.QueryActiveTyres() != static_cast<uint32_t>(ActiveTyres[Step]);
        PopMiss   += Projection.QueryPopping() != Popping[Step];
        const bool HashSame = HashBytes(Projection.QueryRecords()) == Hashes[Step];
        HashMiss  += !HashSame;
        if (!HashSame && FirstHashMiss < 0) { FirstHashMiss = Step; }
        SeedMiss  += static_cast<int64_t>(Projection.QuerySeed()) != Seed[Step];
        ElapsedMiss += !Near(Projection.QueryElapsed(), Elapsed[Step]);
        LightMiss += !SliceNear(LightValues, LightOffset, static_cast<size_t>(LightCount[Step]) * 7, FlattenLights(Projection.QueryLights()));
        EmberMiss += !SliceNear(EmberValues, EmberOffset, static_cast<size_t>(EmberCount[Step]) * 12, FlattenEmbers(Projection.QueryEmbers()));
        std::vector<double> Remaining;
        for (const PlumeBurst& Burst : Projection.QueryBursts()) { Remaining.push_back(Burst.Remaining); }
        BurstMiss += !SliceNear(BurstValues, BurstOffset, static_cast<size_t>(BurstCount[Step]), Remaining);
    }
    Expect(HashDoubles(Inputs) == Table["InputHash"].value<std::string>().value_or(""), "the direct script's inputs equal the exporter's");
    Expect(CountMiss == 0, "source counts over 240 steps (" + std::to_string(CountMiss) + " differ)");
    Expect(TyreMiss == 0, "active tyres (" + std::to_string(TyreMiss) + " differ)");
    Expect(PopMiss == 0, "exhaust popping (" + std::to_string(PopMiss) + " differ)");
    Expect(HashMiss == 0, "the 288 float records, bit for bit (" + std::to_string(HashMiss) + " steps differ, first " + std::to_string(FirstHashMiss) + ")");
    Expect(SeedMiss == 0, "the xorshift seed after every step (" + std::to_string(SeedMiss) + " differ)");
    Expect(ElapsedMiss == 0, "elapsed seconds");
    Expect(LightMiss == 0, "fire lights, sorted brightest first (" + std::to_string(LightMiss) + " steps differ)");
    Expect(EmberMiss == 0, "ember emitters (" + std::to_string(EmberMiss) + " steps differ)");
    Expect(BurstMiss == 0, "the burst queue's remaining seconds (" + std::to_string(BurstMiss) + " steps differ)");
    Expect(LightOffset == LightValues.size() && EmberOffset == EmberValues.size() && BurstOffset == BurstValues.size(), "every reference light, ember and burst was compared");
    // ResolveBounds: the last step, and an empty projection.
    const PlumeBounds Bounds = Projection.ResolveBounds();
    ExpectNumbers({Bounds.Minimum[0], Bounds.Minimum[1], Bounds.Minimum[2]}, ReadNumbers(Table["BoundsMinimum"]), "ResolveBounds minimum");
    ExpectNumbers({Bounds.Maximum[0], Bounds.Maximum[1], Bounds.Maximum[2]}, ReadNumbers(Table["BoundsMaximum"]), "ResolveBounds maximum");
    const PlumeBounds Empty = PlumeSourceProjection().ResolveBounds();
    const auto        Finite = ReadFlags(Table["EmptyBoundsFinite"]);
    Expect(Finite.size() == 2 && !Finite[0] && !Finite[1] && std::isinf(Empty.Minimum[0]) && std::isinf(Empty.Maximum[0]), "an empty projection's bounds are infinite");
    // QueueBurst keeps the newest four.
    PlumeSourceProjection Queue;
    for (int Index = 0; Index < 6; ++Index)
    {
        PlumeBurst Burst;
        Burst.Seconds = 1.0 + Index;
        Queue.QueueBurst(Burst);
    }
    Expect(Queue.QueryBursts().size() == 4 && Queue.QueryBursts().front().Seconds == 3.0, "QueueBurst keeps the newest four");
}

void CheckSequence(const toml::table& Reference, const char* Section, uint32_t Seed, BurnoutRefresh (*Make)(int, const std::array<double, 8>&), std::string_view Grade)
{
    const std::string  Name  = Section;
    const toml::table& Table = *Reference[Section].as_table();
    const int          Steps = static_cast<int>(Table["Steps"].value<int64_t>().value_or(0));
    const auto         Count = ReadIntegers(Table["Count"]), ActiveTyres = ReadIntegers(Table["ActiveTyres"]);
    const auto         RecordsHash = ReadStrings(Table["RecordsHash"]), RecordHash = ReadStrings(Table["RecordHash"]), FireLightHash = ReadStrings(Table["FireLightHash"]);
    const auto         LightCount = ReadIntegers(Table["LightCount"]), EmberCount = ReadIntegers(Table["EmberCount"]);
    const auto         LightValues = ReadNumbers(Table["LightValues"]), EmberValues = ReadNumbers(Table["EmberValues"]);
    const auto         Resident = ReadFlags(Table["Resident"]), StepPending = ReadFlags(Table["StepPending"]);
    const auto         State = ReadIntegers(Table["State"]), StepOrdinal = ReadIntegers(Table["StepOrdinal"]), StepsTaken = ReadIntegers(Table["StepsTaken"]);
    const auto         Accumulator = ReadNumbers(Table["Accumulator"]), QuietSeconds = ReadNumbers(Table["QuietSeconds"]), ElapsedSeconds = ReadNumbers(Table["ElapsedSeconds"]);
    const auto         Origin = ReadIntegers(Table["Origin"]), PriorOrigin = ReadIntegers(Table["PriorOrigin"]);
    const auto         FireLightCount = ReadIntegers(Table["FireLightCount"]);
    const auto         MetricSources = ReadIntegers(Table["MetricSources"]), MetricTicks = ReadIntegers(Table["MetricTicks"]), MetricRelocations = ReadIntegers(Table["MetricRelocations"]);
    const auto         FireIntensity = ReadNumbers(Table["FireIntensity"]), FirePosition = ReadNumbers(Table["FirePosition"]);
    const auto         PressureSweeps = ReadIntegers(Table["PressureSweeps"]);
    const auto         RecordWords = ReadIntegers(Table["RecordWords"]);

    SmokeSequence       Sequence(Grade);
    Mulberry32          Rng(Seed);
    std::vector<double> Inputs;
    size_t              LightOffset = 0, EmberOffset = 0, WordOffset = 0;
    struct Miss
    {
        const char* Name;
        int         Count = 0;
        int         First = -1;
    };
    Miss Misses[] = {{"source count"}, {"active tyres"}, {"source records (288 floats, hash)"}, {"fire lights"}, {"ember emitters"}, {"residency"}, {"step pending"}, {"state parity"},
                     {"accumulator"}, {"quiet seconds"}, {"step ordinal"}, {"elapsed seconds"}, {"steps taken"}, {"window origin"}, {"prior origin"}, {"step record (256 bytes, hash)"},
                     {"fire-light record (144 bytes, hash)"}, {"fire-light count"}, {"metrics"}, {"fire-light stand-in"}, {"pressure sweeps"}, {"record words"}};
    const auto Note = [&Misses](size_t Which, bool Same, int Step)
    {
        if (!Same)
        {
            if (Misses[Which].First < 0) { Misses[Which].First = Step; }
            ++Misses[Which].Count;
        }
    };
    for (int Step = 0; Step < Steps; ++Step)
    {
        std::array<double, 8> Noise{};
        for (double& Value : Noise) { Value = Rng(); }
        const BurnoutRefresh Refresh = Make(Step, Noise);
        const std::vector<double> Flat = FlattenBurnout(Refresh);
        Inputs.insert(Inputs.end(), Flat.begin(), Flat.end());
        SmokeAdvanceInput Input;
        Input.Enabled        = Refresh.Enabled;
        Input.Vehicle        = &Refresh.Vehicle;
        Input.LightDirection = LightDirection;
        Input.Gas            = &Refresh.Gas;
        Input.Readings       = &Refresh.Readings;
        Input.Thermal        = &Refresh.Thermal;
        Input.Emissions      = &Refresh.Emissions;
        Sequence.Advance(Refresh.Seconds, Input);
        const PlumeSchedule&         Schedule = Sequence.QuerySchedule();
        const PlumeSourceProjection& Sources  = Sequence.QuerySources();
        Note(0, Sources.QueryCount() == static_cast<uint32_t>(Count[Step]), Step);
        Note(1, Sources.QueryActiveTyres() == static_cast<uint32_t>(ActiveTyres[Step]), Step);
        Note(2, HashBytes(Sources.QueryRecords()) == RecordsHash[Step], Step);
        Note(3, SliceNear(LightValues, LightOffset, static_cast<size_t>(LightCount[Step]) * 7, FlattenLights(Sources.QueryLights())), Step);
        Note(4, SliceNear(EmberValues, EmberOffset, static_cast<size_t>(EmberCount[Step]) * 12, FlattenEmbers(Sources.QueryEmbers())), Step);
        Note(5, Schedule.QueryResident() == Resident[Step], Step);
        Note(6, Schedule.QueryStepPending() == StepPending[Step], Step);
        Note(7, static_cast<int64_t>(Schedule.QueryState()) == State[Step], Step);
        Note(8, Near(Schedule.QueryAccumulator(), Accumulator[Step]), Step);
        Note(9, Near(Schedule.QueryQuietSeconds(), QuietSeconds[Step]), Step);
        Note(10, static_cast<int64_t>(Schedule.QueryStepOrdinal()) == StepOrdinal[Step], Step);
        Note(11, Near(Schedule.QueryElapsedSeconds(), ElapsedSeconds[Step]), Step);
        Note(12, static_cast<int64_t>(Schedule.QueryStepsTaken()) == StepsTaken[Step], Step);
        Note(13, Schedule.QueryOrigin()[0] == Origin[2 * Step] && Schedule.QueryOrigin()[1] == Origin[2 * Step + 1], Step);
        Note(14, Schedule.QueryPriorOrigin()[0] == PriorOrigin[2 * Step] && Schedule.QueryPriorOrigin()[1] == PriorOrigin[2 * Step + 1], Step);
        Note(15, HashBytes(Schedule.QueryRecordBytes()) == RecordHash[Step], Step);
        Note(16, HashBytes(Schedule.QueryFireLightBytes()) == FireLightHash[Step], Step);
        Note(17, static_cast<int64_t>(Schedule.QueryFireLightCount()) == FireLightCount[Step], Step);
        Note(18, Sequence.QueryMetrics().Sources == MetricSources[Step] && Sequence.QueryMetrics().Ticks == MetricTicks[Step] && Sequence.QueryMetrics().Relocations == MetricRelocations[Step], Step);
        Note(19, Near(Sequence.QueryFireLight().Intensity, FireIntensity[Step]) && Near(Sequence.QueryFireLight().Position[0], FirePosition[3 * Step])
                 && Near(Sequence.QueryFireLight().Position[1], FirePosition[3 * Step + 1]) && Near(Sequence.QueryFireLight().Position[2], FirePosition[3 * Step + 2]), Step);
        Note(20, static_cast<int64_t>(Schedule.QueryConfiguration().PressureSweeps) == PressureSweeps[Step], Step);
        if (Step % 60 == 59 && Schedule.QueryStepPending())
        {
            std::array<uint32_t, PlumeRecordBytes / 4> Words{};
            std::memcpy(Words.data(), Schedule.QueryRecordBytes().data(), PlumeRecordBytes);
            bool Same = true;
            for (size_t Word = 0; Word < Words.size(); ++Word)
            {
                Same = Same && WordOffset + Word < RecordWords.size() && static_cast<int64_t>(Words[Word]) == RecordWords[WordOffset + Word];
            }
            WordOffset += Words.size();
            Note(21, Same, Step);
        }
        // What the device half leaves behind after a step is recorded: the parity flips, the step is counted.
        if (Schedule.QueryStepPending())
        {
            Sequence.AccessSchedule().CompleteStep();
        }
    }
    Expect(HashDoubles(Inputs) == Table["InputHash"].value<std::string>().value_or(""), "the " + Name + " script's inputs equal the exporter's");
    for (const Miss& Entry : Misses)
    {
        Expect(Entry.Count == 0, std::string(Entry.Name) + " over " + std::to_string(Steps) + " refreshes of " + Name + " (" + std::to_string(Entry.Count) + " differ, first at " + std::to_string(Entry.First) + ")");
    }
    Expect(LightOffset == LightValues.size() && EmberOffset == EmberValues.size() && WordOffset == RecordWords.size(), "every reference light, ember and record word of " + Name + " was compared");
    Sequence.Clear();
    const auto Cleared = ReadFlags(Table["ClearedResident"]);
    Expect(Cleared.size() == 1 && Sequence.QuerySchedule().QueryResident() == Cleared[0] && Sequence.QueryFireLight().Intensity == Table["ClearedIntensity"].value<double>().value_or(-1),
           Name + ": Clear() stops the plume and the fire light");
    const auto Prior = ReadIntegers(Table["ClearedPrior"]);
    Expect(Prior.size() == 2 && Sequence.QuerySchedule().QueryPriorOrigin()[0] == Prior[0] && Sequence.QuerySchedule().QueryPriorOrigin()[1] == Prior[1], Name + ": Clear() sets the restart origin");
}

// 📝 Settings.Inspection 10 sets the record's debug word; the host's debug channel passes it (SmokeSequence.Advance in the page never does).
void CheckInspection(const toml::table& Reference)
{
    const toml::table& Table = *Reference["Inspection"].as_table();
    SmokeSequence       Sequence("low");
    Mulberry32          Rng(0x1A5BEC71u);
    std::vector<double> Inputs;
    BurnoutRefresh        Refresh;
    for (int Step = 60; Step < 68; ++Step)
    {
        std::array<double, 8> Noise{};
        for (double& Value : Noise) { Value = Rng(); }
        Refresh = ConstructBurnout(Step, Noise);
        const std::vector<double> Flat = FlattenBurnout(Refresh);
        Inputs.insert(Inputs.end(), Flat.begin(), Flat.end());
        SmokeAdvanceInput Input;
        Input.Enabled        = true;
        Input.Vehicle        = &Refresh.Vehicle;
        Input.LightDirection = LightDirection;
        Input.Gas            = &Refresh.Gas;
        Input.Readings       = &Refresh.Readings;
        Input.Thermal        = &Refresh.Thermal;
        Input.Emissions      = &Refresh.Emissions;
        Sequence.Advance(Refresh.Seconds, Input);
    }
    Expect(HashDoubles(Inputs) == Table["InputHash"].value<std::string>().value_or(""), "the inspection script's inputs equal the exporter's");
    const auto Expected = ReadIntegers(Table["RecordWords"]);
    bool       Same = Expected.size() == 4 * PlumeRecordBytes / 4;
    size_t     Offset = 0;
    for (int Variant = 0; Variant < 4; ++Variant)
    {
        PlumeSettings Settings = FluidDynamics::MapPlumeSettings(Refresh.Gas, true);
        if (Variant < 3) { Settings.Inspection = Variant == 0 ? 10 : Variant == 1 ? 0 : 7; }
        else { Settings.PlumeDissipation = 0.99; Settings.PlumeCooling = 0.99; }
        Sequence.AccessSchedule().Schedule(1.0 / 60, 1.0 / 60, Refresh.Vehicle.Position, Sequence.QuerySources(), Settings, LightDirection);
        std::array<uint32_t, PlumeRecordBytes / 4> Words{};
        std::memcpy(Words.data(), Sequence.QuerySchedule().QueryRecordBytes().data(), PlumeRecordBytes);
        for (size_t Word = 0; Same && Word < Words.size(); ++Word)
        {
            Same = Offset + Word < Expected.size() && static_cast<int64_t>(Words[Word]) == Expected[Offset + Word];
        }
        Offset += Words.size();
    }
    Expect(Same, "four step records (the debug channel at 10, 0 and 7; dissipation and cooling past their 0.95 cap), word for word");
}

