// 📝 How a vertex touched by blended edges is resolved (research § I; degree-3 vertices).
enum class VertexBlendCategory : uint8_t
{
    Cap          = 0,                                                                        // One blended edge: ends on the third face
    Mitre        = 1,                                                                        // Two blended + one sharp: blends meet on a mitre
    BallCorner   = 2,                                                                        // Three blended: sphere patch / chamfer apex
    Continuation = 3,                                                                        // Closed blended rim through its seam vertex
    Pinch        = 4,                                                                        // Every blend narrows to zero width at the vertex
    Setback      = 5,                                                                        // Blends cut back, hole filled by fair quads
};

enum class BlendFaceOrigin : uint8_t
{
    Modified = 0,                                                                            // Trimmed original face
    Edge     = 1,                                                                            // Blend face generated by an edge
    Vertex   = 2,                                                                            // Corner face generated by a vertex
};

struct BlendFaceHistory
{
    FaceToken       Result = {};                                                             // [-] - Face of the new body
    BlendFaceOrigin Origin = BlendFaceOrigin::Modified;                                      // [-] - What produced it
    FaceToken       Face   = {};                                                             // [-] - Source face (Modified)
    EdgeToken       Edge   = {};                                                             // [-] - Source edge (Edge)
    VertexToken     Vertex = {};                                                             // [-] - Source vertex (Vertex)
};

struct BlendStatistics
{
    int    BlendedEdges      = 0;                                                            // [-]   - Sheets resolved
    int    Vertices[6]       = { 0, 0, 0, 0, 0, 0 };                                         // [-]   - Per VertexBlendCategory
    int    CarrierPlanes     = 0;                                                            // [-]   - Exact carriers by type
    int    CarrierCylinders  = 0;                                                            // [-]
    int    CarrierCones      = 0;                                                            // [-]
    int    CarrierTori       = 0;                                                            // [-]
    int    CarrierProcedural = 0;                                                            // [-]   - Rolling-ball carriers (arc or chord section)
    int    CornerSpheres     = 0;                                                            // [-]   - Ball-corner patches
    int    EllipticalEdges   = 0;                                                            // [-]   - Mitres / caps that are ellipses
    int    TracedSections    = 0;                                                            // [-]   - Mitres / caps on exact intersection curves
    double MaxSheetResidual  = 0.0;                                                          // [len] - Worst rolling-ball residual
    double MaxVertexResidual = 0.0;                                                          // [len] - Worst corner / mitre agreement
    int    SetbackPatches    = 0;                                                            // [-]   - Fair quads in setback vertex blends
    double MaxTangentBreak   = 0.0;                                                          // [rad] - Worst G1 break of a setback quad to its neighbours
    double MaxSeamBreak      = 0.0;                                                          // [rad] - Worst G1 break across a spoke (quad to quad)
    double MaxRimGap         = 0.0;                                                          // [len] - Worst G0 gap of a setback quad to its rims
    int    CliffOverflows    = 0;                                                            // [-]   - Blend sides trimmed by a cliff face
    int    NotchOverflows    = 0;                                                            // [-]   - Blend sides trimmed by a face across a concave edge
    int    SmoothOverflows   = 0;                                                            // [-]   - Blend sides rolled over a tangent edge onto the next face
    int    MergedVertices    = 0;                                                            // [-]   - Vertices fused where blends meet
    int    MergedEdges       = 0;                                                            // [-]   - Rails fused into one edge where blends meet
    int    MergedFaces       = 0;                                                            // [-]   - Faces swept to zero area and dropped
    double Milliseconds      = 0.0;                                                          // [ms]  - Wall time
};

struct BlendOutcome
{
    BodyToken                     Body          = {};                                        // [-] - New body (input untouched)
    std::string                   Refusal       = {};                                        // [-] - Non-empty when refused (atomic)
    BlendStatistics               Statistics    = {};                                        // [-] - Counters and residuals
    std::vector<EdgeBlendSheet>   Sheets        = {};                                        // [-] - Per selected edge
    std::vector<BlendFaceHistory> FaceHistories = {};                                        // [-] - Result face provenance
    AuditReport                   Audit         = {};                                        // [-] - Audit of the new body
};

