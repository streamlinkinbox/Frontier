void ApplyRenderCharacter(const ReferencePresetParameters& Parameters, ParticleReferenceGeometryStorage& OutStorage) noexcept
{
    const uint32_t Shape = Parameters.Shape;
    const bool Boids = (Shape == 13u);
    const bool AdditiveShape = (Shape == 0u && Parameters.TrailMode == 0 && Parameters.BeamMode == 0 && Parameters.FerroMode == 0);

    OutStorage.RenderLiveBillboards     = true;
    OutStorage.RenderLiveStrands    = false;
    OutStorage.RenderLiveOrientedSolids = false;
    OutStorage.Silhouette           = ParticleGpuSilhouette::SoftDisc;
    OutStorage.BlendMode            = ParticleGpuBlendMode::Alpha;
    OutStorage.SolidProfile         = ParticleSolidProfile::Cube;
    OutStorage.SizeScale            = 1.0f;
    OutStorage.EmissiveBoost        = 0.92f;
    OutStorage.RibbonWidthMeters    = std::max(0.02f, Parameters.SizeStart * 0.45f);

    switch (Shape)
    {
        case 5u: // Coin disc fountain
            OutStorage.RenderLiveBillboards          = false;
            OutStorage.RenderLiveOrientedSolids  = true;
            OutStorage.SolidProfile              = ParticleSolidProfile::CoinDisc;
            OutStorage.SizeScale                 = 0.42f;
            break;
        case 4u: // MoGraph / derez cubes
            OutStorage.RenderLiveBillboards          = false;
            OutStorage.RenderLiveOrientedSolids  = true;
            OutStorage.SolidProfile              = ParticleSolidProfile::Cube;
            OutStorage.SizeScale                 = 0.50f;
            break;
        case 8u: // Hailstone shards
        case 18u: // Glass shards
            OutStorage.RenderLiveBillboards          = false;
            OutStorage.RenderLiveOrientedSolids  = true;
            OutStorage.SolidProfile              = ParticleSolidProfile::Shard;
            OutStorage.SizeScale                 = 0.55f;
            break;
        case 13u: // Winged boids
            OutStorage.RenderLiveBillboards          = false;
            OutStorage.RenderLiveOrientedSolids  = true;
            OutStorage.SolidProfile              = ParticleSolidProfile::WingedBoid;
            OutStorage.SizeScale                 = 0.70f;
            break;
        case 14u: // Viscous droplet filaments
            OutStorage.RenderLiveBillboards          = true;
            OutStorage.Silhouette                = ParticleGpuSilhouette::SparkStreak;
            OutStorage.RenderLiveStrands         = true;
            break;
        case 10u: // Shockwave ring: the reference solid covers the floor rings, live sparks add thin sweep rings
        case 15u: // Radar / sonar sweep
            OutStorage.Silhouette                = ParticleGpuSilhouette::ShockRing;
            OutStorage.BlendMode                 = ParticleGpuBlendMode::Additive;
            OutStorage.EmissiveBoost             = 0.85f;
            OutStorage.SizeScale                 = 0.34f;
            break;
        case 11u: // EMP dome
            OutStorage.Silhouette                = ParticleGpuSilhouette::GlowOrb;
            OutStorage.BlendMode                 = ParticleGpuBlendMode::Additive;
            OutStorage.EmissiveBoost             = 0.90f;
            OutStorage.SizeScale                 = 0.30f;
            break;
        case 16u: // Energy shield barrier
            OutStorage.Silhouette                = ParticleGpuSilhouette::GlowOrb;
            OutStorage.BlendMode                 = ParticleGpuBlendMode::Additive;
            OutStorage.EmissiveBoost             = 1.05f;
            break;
        case 17u: // Aurora curtain
            OutStorage.Silhouette                = ParticleGpuSilhouette::SparkStreak;
            OutStorage.BlendMode                 = ParticleGpuBlendMode::Additive;
            OutStorage.EmissiveBoost             = 1.10f;
            break;
        case 19u: // Volumetric water mist
            OutStorage.EmissiveBoost             = 0.85f;
            break;
        case 12u: // Hologram scanlines
        case 3u:  // Streaks
        case 0u:  // Sparks / tracers
            OutStorage.Silhouette                = ParticleGpuSilhouette::SparkStreak;
            break;
        case 9u: // Bokeh beads
            OutStorage.Silhouette                = ParticleGpuSilhouette::GlowOrb;
            break;
        case 2u: // Leaves / petals / paper
            OutStorage.RenderLiveBillboards          = false;
            OutStorage.RenderLiveOrientedSolids  = true;
            OutStorage.SolidProfile              = ParticleSolidProfile::CoinDisc;
            OutStorage.SizeScale                 = 0.42f;
            break;
        default:
            OutStorage.Silhouette                = AdditiveShape ? ParticleGpuSilhouette::SparkStreak : ParticleGpuSilhouette::SoftDisc;
            break;
    }

    if (Boids)
    {
        OutStorage.EmissiveBoost = 1.0f;
    }

    // Specimen assembly whose cloth / bead / chime / silk geometry IS the subject: the reference captures show
    // no loose spark spray around them, so the live spray is suppressed and the reference solid carries the look.
    const bool StageIsSubject = (Parameters.DynMode == 1) || (Parameters.DynMode == 3) ||
                                (Parameters.BeadsMode > 0) || (Parameters.SeedHeadMode > 0);
    if (StageIsSubject)
    {
        OutStorage.RenderLiveBillboards     = false;
        OutStorage.RenderLiveStrands        = false;
        OutStorage.RenderLiveOrientedSolids = false;
    }
}

// Specialty families that build their own multi-colour 3D props
void BuildSpecialtyStage(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    std::string_view Slug,
    const std::array<Col4, 3u>& Palette,
    float Time) noexcept
{
    const Col4 Primary = Palette[0];
    const Col4 Accent  = Palette[1];
    const Col4 Highlight = Palette[2];

    if (Parameters.WebMode == 1)
    {
        BuildOrbWeaveWeb(Acc, Parameters, Tint(Primary, 0.92f), Highlight, Time, 0.010f);
        return;
    }
    if (Parameters.WebMode == 2)
    {
        BuildCobwebTangle(Acc, Parameters, Tint(Primary, 0.85f), Highlight, Time, 0.009f);
        return;
    }
    if (Parameters.CrackMode > 0)
    {
        BuildFractureSheet(Acc, Parameters, Primary, Accent, Time);
        return;
    }
    if (Parameters.FerroMode == 1 || Parameters.FerroMode == 2)
    {
        BuildFerrofluidBase(Acc, Parameters, Primary, Time);
        return;
    }
    if (Parameters.BeadsMode > 0)
    {
        BuildBeadedCurtain(Acc, Parameters, Primary, Accent, Highlight, Time);
        return;
    }
    if (Parameters.SeedHeadMode > 0)
    {
        BuildSeedHeadPuffs(Acc, Parameters, Tint(Primary, 0.95f), Accent, Time);
        return;
    }
    if (Parameters.FlareMode > 0)
    {
        BuildFlareAircraft(Acc, Parameters, Time);
        return;
    }
    if (Parameters.FireworkMode > 0)
    {
        BuildFireworkRack(Acc, Parameters, Time);
        return;
    }
    if (Parameters.BeamMode > 0)
    {
        BuildLaserBeam(Acc, Parameters, Highlight, Accent, { 1.0f, 0.78f, 0.48f, 0.95f }, Time);
        return;
    }
    if (Parameters.ArcMode == 1 || (Parameters.ArcMode == 0 && Parameters.ArcCount > 0))
    {
        // arcMode 1 = held static strike, arcMode 0 with a strike count = the free-running Tesla pair
        BuildArcDischarge(Acc, Parameters, Primary, Accent, Time);
        return;
    }
    if (Parameters.ArcMode == 2 || Parameters.ArcMode == 3)
    {
        BuildPlasmaWeb(Acc, Parameters, Primary, Accent, Time);
        return;
    }
    if (Parameters.Shape == 16u)
    {
        BuildShieldBarrier(Acc, Parameters, Primary, Accent, Time);
        return;
    }
    if (Parameters.Shape == 17u)
    {
        BuildAuroraCurtain(Acc, Parameters, Accent, Primary, Highlight, Time);
        return;
    }
    if (Parameters.Shape == 11u)
    {
        BuildEmpDome(Acc, Parameters, Primary, Accent, Time);
        return;
    }
    if (Parameters.Shape == 10u || Parameters.Shape == 15u)
    {
        BuildGroundRings(Acc, Parameters, Primary, Accent, Time);
        return;
    }
    if (Slug == "black-hole")
    {
        BuildBlackHole(Acc, Parameters, Accent, Time);
        return;
    }
    if (Parameters.GridMode > 0)
    {
        BuildMoGraphSpecimen(Acc, Parameters, Primary, Accent);
        return;
    }
    if (Parameters.DynMode == 3)
    {
        if (Parameters.DynSub < 0.5f)
        {
            BuildFlagPole(Acc, Parameters, { 0.58f, 0.62f, 0.68f, 0.96f });
        }
        else
        {
            BuildShipMast(Acc, Parameters, { 0.46f, 0.32f, 0.20f, 0.96f });
        }
        BuildRiggingStrands(Acc, Parameters, Primary, Accent, Highlight, Time, 0.014f);
        return;
    }
    if (Parameters.DynMode == 1)
    {
        BuildCableStanchions(Acc, Parameters, { 0.34f, 0.37f, 0.42f, 0.94f });
        BuildRiggingStrands(Acc, Parameters, Primary, Accent, Highlight, Time, 0.012f);
        return;
    }
    if (Parameters.DynMode > 0)
    {
        // Botanical strands need their authored albedo lifted, since the palette entries are near-black
        // linear values that studio lighting cannot read at reference exposure.
        BuildRiggingStrands(Acc, Parameters, LiftAlbedo(Primary, 0.20f), LiftAlbedo(Accent, 0.18f), Highlight, Time, 0.012f);
        return;
    }
    if (Parameters.TrailMode > 0)
    {
        // Glowing projectile ribbon trails emit from the origin crosshair
        const Vec3 Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
        Acc.AddBoxWire({ Origin.X - 0.10f, Origin.Y - 0.10f, Origin.Z - 0.10f },
                       { Origin.X + 0.10f, Origin.Y + 0.10f, Origin.Z + 0.10f }, Tint(Primary, 0.42f), 0.008f);
    }
}

