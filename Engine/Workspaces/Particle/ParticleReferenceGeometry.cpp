void BuildFireworkRack(ReferenceAccumulator& Acc, const ReferencePresetParameters& Parameters, float Time) noexcept
{
    (void)Time;
    const Vec3  Origin{ Parameters.OriginX, 0.0f, Parameters.OriginZ };
    const float BaseY = std::max(0.02f, Origin.Y);
    const Col4  WoodColor{ 0.34f, 0.23f, 0.14f, 0.96f };
    const Col4  TubeColor{ 0.20f, 0.24f, 0.30f, 0.98f };
    const Col4  RimColor{ 0.76f, 0.80f, 0.86f, 0.85f };

    for (int Rail = -1; Rail <= 1; Rail += 2)
    {
        const float RailZ = Origin.Z + static_cast<float>(Rail) * 0.14f;
        Acc.AddCylinder({ Origin.X - 1.02f, BaseY + 0.05f, RailZ }, { Origin.X + 1.02f, BaseY + 0.05f, RailZ }, 0.045f, 0.045f, 8, WoodColor, 0.25f);
    }
    Acc.AddCylinder({ Origin.X - 1.02f, BaseY + 0.26f, Origin.Z - 0.12f }, { Origin.X + 1.02f, BaseY + 0.26f, Origin.Z - 0.12f }, 0.030f, 0.030f, 8, WoodColor, 0.25f);
    Acc.AddCylinder({ Origin.X - 1.02f, BaseY + 0.26f, Origin.Z + 0.12f }, { Origin.X + 1.02f, BaseY + 0.26f, Origin.Z + 0.12f }, 0.030f, 0.030f, 8, WoodColor, 0.25f);

    constexpr int TubeCount = 5;
    for (int Tube = 0; Tube < TubeCount; ++Tube)
    {
        const float TubeX = Origin.X + (static_cast<float>(Tube) - 2.0f) * 0.42f;
        const float Fan   = (static_cast<float>(Tube) - 2.0f) * 0.05f;
        Acc.AddCylinder({ TubeX, BaseY + 0.02f, Origin.Z }, { TubeX + Fan, BaseY + 0.44f, Origin.Z }, 0.068f, 0.058f, 10, TubeColor, 0.45f);
        Acc.AddRingXZ({ TubeX + Fan, BaseY + 0.44f, Origin.Z }, 0.072f, 14, RimColor, 0.010f);

        // Burst shell above each mortar. The reference captures several simultaneous chrysanthemum
        // shell bursts, so every tube carries a radial star fan of glowing tracers with bright tips.
        const float ShellStarZ = BaseY + 1.55f + static_cast<float>(Tube) * 0.42f;
        const float ShellStarReach = 0.82f + 0.30f * Hash01(static_cast<float>(Tube) * 19.0f, 3.0f);
        const Vec3  ShellStar{ TubeX + Fan * 2.0f, ShellStarZ, Origin.Z + (Hash01(static_cast<float>(Tube) * 23.0f, 4.0f) - 0.5f) * 0.55f };
        const Col4  ShellStarColor = (Tube % 2 == 0)
            ? Col4{ 1.0f, 0.72f, 0.32f, 1.0f }
            : Col4{ 0.62f, 0.86f, 1.0f, 1.0f };
        const Col4  CoreColor{ 1.0f, 0.96f, 0.86f, 1.0f };

        Acc.AddGlowLine(ShellStar, { ShellStar.X, ShellStarZ + 0.12f, ShellStar.Z }, CoreColor, 0.030f, 1.5f);
        constexpr int Tracers = 96;
        for (int Tracer = 0; Tracer < Tracers; ++Tracer)
        {
            const float Fan01 = static_cast<float>(Tracer) / static_cast<float>(Tracers);
            const float Az    = Fan01 * Pi * 2.0f * 3.0f;
            const float El    = std::acos(std::clamp(1.0f - 2.0f * std::fmod(Fan01 * 7.0f, 1.0f), -1.0f, 1.0f));
            const float Reach = ShellStarReach * (0.72f + 0.42f * Hash01(static_cast<float>(Tracer) * 11.0f, 5.0f));
            const Vec3  Tip{ ShellStar.X + std::sin(El) * std::cos(Az) * Reach,
                             ShellStar.Y + std::cos(El) * Reach,
                             ShellStar.Z + std::sin(El) * std::sin(Az) * Reach };
            Acc.AddGlowLine(ShellStar, Tip, ShellStarColor, 0.010f, 1.15f);
            Acc.AddRingXZ(Tip, 0.026f, 6, CoreColor, 0.009f, true, 1.45f);
        }
    }
}

// Propagating branching ground fracture network across the ice / basalt slab surface
void BuildFractureSheet(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 PrimaryColor,
    Col4 AccentColor,
    float Time) noexcept
{
    const Vec3  Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const bool  Glacial = (Parameters.CrackMode == 1);
    const float ExtX = std::max(1.2f, Parameters.BoxX);
    const float ExtY = std::max(0.08f, Parameters.BoxY);
    const float ExtZ = std::max(1.2f, Parameters.BoxZ);
    const float TopY = Origin.Y + ExtY;
    const float BottomY = std::max(0.004f, Origin.Y);
    const float Speed = std::max(0.25f, Parameters.CrackSpeed);
    const float Freq  = std::max(0.3f, Parameters.CurlFreq);
    const float MaxR  = std::hypot(ExtX, ExtZ) * 0.94f;
    const float Since = std::fmod(Time, 4.8f);
    const float WaveR = std::min(MaxR, Since * Speed);

    const Col4 SurfaceColor = Glacial ? Col4{ 0.46f, 0.78f, 0.92f, 0.92f } : Col4{ 0.16f, 0.14f, 0.13f, 1.0f };
    const Col4 SubColor     = Glacial ? Col4{ 0.10f, 0.30f, 0.48f, 0.98f } : Col4{ 0.09f, 0.08f, 0.075f, 1.0f };
    const Col4 WallColor    = Glacial ? Col4{ 0.28f, 0.60f, 0.80f, 0.96f } : Col4{ 0.12f, 0.10f, 0.095f, 1.0f };

    const float X0 = Origin.X - ExtX;
    const float X1 = Origin.X + ExtX;
    const float Z0 = Origin.Z - ExtZ;
    const float Z1 = Origin.Z + ExtZ;

    // Continuous slab volume: sub-surface backing, top plate and four beveled side walls
    Acc.AddQuad(false, true, { X0, BottomY, Z0 }, { X1, BottomY, Z0 }, { X1, BottomY, Z1 }, { X0, BottomY, Z1 }, SubColor, 0.0f, 0.10f);
    Acc.AddQuad(false, true, { X0, TopY, Z0 }, { X1, TopY, Z0 }, { X1, TopY, Z1 }, { X0, TopY, Z1 }, SurfaceColor, Glacial ? 0.10f : 0.0f, Glacial ? 0.55f : 0.20f);
    Acc.AddQuad(false, true, { X0, BottomY, Z1 }, { X1, BottomY, Z1 }, { X1, TopY, Z1 }, { X0, TopY, Z1 }, WallColor, 0.0f, 0.30f);
    Acc.AddQuad(false, true, { X1, BottomY, Z0 }, { X0, BottomY, Z0 }, { X0, TopY, Z0 }, { X1, TopY, Z0 }, WallColor, 0.0f, 0.30f);
    Acc.AddQuad(false, true, { X1, BottomY, Z1 }, { X1, BottomY, Z0 }, { X1, TopY, Z0 }, { X1, TopY, Z1 }, WallColor, 0.0f, 0.30f);
    Acc.AddQuad(false, true, { X0, BottomY, Z0 }, { X0, BottomY, Z1 }, { X0, TopY, Z1 }, { X0, TopY, Z0 }, WallColor, 0.0f, 0.30f);

    // Crisp frozen rim highlight around the sheet edge
    const Col4 RimColor = Glacial ? Col4{ 0.84f, 0.97f, 1.0f, 0.72f } : Col4{ 0.34f, 0.28f, 0.24f, 0.55f };
    Acc.AddLine({ X0, TopY + 0.004f, Z0 }, { X1, TopY + 0.004f, Z0 }, RimColor, 0.010f);
    Acc.AddLine({ X1, TopY + 0.004f, Z0 }, { X1, TopY + 0.004f, Z1 }, RimColor, 0.010f);
    Acc.AddLine({ X1, TopY + 0.004f, Z1 }, { X0, TopY + 0.004f, Z1 }, RimColor, 0.010f);
    Acc.AddLine({ X0, TopY + 0.004f, Z1 }, { X0, TopY + 0.004f, Z0 }, RimColor, 0.010f);

    if (WaveR <= 0.04f)
    {
        return;
    }

    const float HitX = Origin.X;
    const float HitZ = Origin.Z;
    auto CrackHash = [](float Seed, float Salt) noexcept { return Hash01(Seed, Salt); };

    struct CrackPoint { float X; float Z; };
    auto ClampToSheet = [&](float Px, float Pz) noexcept -> CrackPoint
    {
        return { std::clamp(Px, X0 + 0.02f, X1 - 0.02f), std::clamp(Pz, Z0 + 0.02f, Z1 - 0.02f) };
    };
    auto EvaluateBranch = [&](int Arm, bool Fork, float Distance) noexcept -> CrackPoint
    {
        const float BaseAngle = (static_cast<float>(Arm) / 8.0f) * Pi * 2.0f + (CrackHash(static_cast<float>(Arm * 19 + 3), 1.0f) - 0.5f) * 0.42f;
        const float U = std::clamp(Distance / std::max(0.35f, MaxR), 0.0f, 1.0f);
        const int   Seg = static_cast<int>(std::floor(U * 5.0f));
        const float Zig = (CrackHash(static_cast<float>(Arm * 31 + Seg * 7), 2.0f) - 0.5f) * 0.34f * std::sin(U * Pi)
                        + std::sin(U * 11.5f * Freq + static_cast<float>(Arm) * 2.1f) * 0.08f;
        if (!Fork)
        {
            const float Angle = BaseAngle + Zig;
            return { HitX + std::cos(Angle) * Distance, HitZ + std::sin(Angle) * Distance };
        }
        const float ForkStart = MaxR * (0.24f + 0.38f * CrackHash(static_cast<float>(Arm * 29 + 5), 3.0f));
        const float ForkSign = (Arm % 2 == 0) ? 1.0f : -1.0f;
        const float ForkAngle = BaseAngle + ForkSign * (0.52f + 0.38f * CrackHash(static_cast<float>(Arm * 41 + 7), 4.0f));
        const float TrunkR = std::min(Distance, ForkStart);
        const float TrunkZig = (CrackHash(static_cast<float>(Arm * 31 + static_cast<int>(std::floor((TrunkR / std::max(0.35f, MaxR)) * 5.0f)) * 7), 2.0f) - 0.5f) * 0.30f;
        const float JunctionX = HitX + std::cos(BaseAngle + TrunkZig) * TrunkR;
        const float JunctionZ = HitZ + std::sin(BaseAngle + TrunkZig) * TrunkR;
        const float BranchDist = std::max(0.0f, Distance - ForkStart);
        return { JunctionX + std::cos(ForkAngle) * BranchDist, JunctionZ + std::sin(ForkAngle) * BranchDist };
    };

    auto AddCrackSegment = [&](CrackPoint P0, CrackPoint P1, float W0, float W1, float DepthFraction) noexcept
    {
        const float Dx = P1.X - P0.X;
        const float Dz = P1.Z - P0.Z;
        const float Len = std::hypot(Dx, Dz);
        if (Len < 1.0e-4f)
        {
            return;
        }
        const float Nx = -Dz / Len;
        const float Nz = Dx / Len;
        const float SurfaceY = TopY + 0.008f;
        const float DeepY    = TopY + 0.004f;

        const Col4 CoreColor  = Glacial ? Col4{ 0.03f, 0.14f, 0.28f, 0.98f } : Col4{ 1.0f, 0.44f + 0.28f * DepthFraction, 0.08f + 0.18f * DepthFraction, 1.0f };
        const Col4 LipColor   = Glacial ? Col4{ 0.88f, 0.98f, 1.0f, 0.95f } : Col4{ 0.98f, 0.62f, 0.18f, 0.92f };
        const Col4 ShelfColor = Glacial ? Col4{ 0.68f, 0.92f, 1.0f, 0.52f } : Col4{ 0.55f, 0.16f, 0.04f, 0.72f };

        const float Sw0 = W0 * 2.4f;
        const float Sw1 = W1 * 2.4f;
        Acc.AddQuad(false, true, { P0.X - Nx * Sw0, DeepY, P0.Z - Nz * Sw0 }, { P0.X + Nx * Sw0, DeepY, P0.Z + Nz * Sw0 },
                    { P1.X + Nx * Sw1, DeepY, P1.Z + Nz * Sw1 }, { P1.X - Nx * Sw1, DeepY, P1.Z - Nz * Sw1 },
                    ShelfColor, Glacial ? 0.22f : 0.75f, 0.0f);
        Acc.AddQuad(false, true, { P0.X - Nx * W0, SurfaceY, P0.Z - Nz * W0 }, { P0.X + Nx * W0, SurfaceY, P0.Z + Nz * W0 },
                    { P1.X + Nx * W1, SurfaceY, P1.Z + Nz * W1 }, { P1.X - Nx * W1, SurfaceY, P1.Z - Nz * W1 },
                    CoreColor, Glacial ? 0.0f : 1.35f, 0.0f);
        Acc.AddLine({ P0.X - Nx * W0, SurfaceY + 0.005f, P0.Z - Nz * W0 }, { P1.X - Nx * W1, SurfaceY + 0.005f, P1.Z - Nz * W1 }, LipColor, 0.008f);
        Acc.AddLine({ P0.X + Nx * W0, SurfaceY + 0.005f, P0.Z + Nz * W0 }, { P1.X + Nx * W1, SurfaceY + 0.005f, P1.Z + Nz * W1 }, LipColor, 0.008f);
    };

    const float BaseWidth = (Glacial ? 0.048f : 0.072f) * (0.65f + 0.65f * std::clamp(Parameters.CrackDepth, 0.0f, 1.0f));
    constexpr int StepsPerArm = 10;
    for (int Arm = 0; Arm < 8; ++Arm)
    {
        CrackPoint Previous = ClampToSheet(HitX, HitZ);
        for (int Step = 1; Step <= StepsPerArm; ++Step)
        {
            const float Distance = (static_cast<float>(Step) / static_cast<float>(StepsPerArm)) * WaveR;
            const CrackPoint Raw = EvaluateBranch(Arm, false, Distance);
            const CrackPoint Current = ClampToSheet(Raw.X, Raw.Z);
            const float Fade0 = 1.0f - (static_cast<float>(Step - 1) / static_cast<float>(StepsPerArm)) * 0.86f;
            const float Fade1 = 1.0f - (static_cast<float>(Step) / static_cast<float>(StepsPerArm)) * 0.86f;
            AddCrackSegment(Previous, Current, BaseWidth * Fade0, BaseWidth * Fade1, Fade0);
            Previous = Current;
            if (std::abs(Raw.X - Origin.X) > ExtX || std::abs(Raw.Z - Origin.Z) > ExtZ)
            {
                break;
            }
        }
        const float ForkStart = MaxR * (0.24f + 0.38f * CrackHash(static_cast<float>(Arm * 29 + 5), 3.0f));
        if (WaveR > ForkStart + 0.05f)
        {
            constexpr int ForkSteps = 5;
            const float ForkMax = std::min(MaxR - ForkStart, WaveR - ForkStart);
            const CrackPoint RawStart = EvaluateBranch(Arm, true, ForkStart);
            CrackPoint ForkPrevious = ClampToSheet(RawStart.X, RawStart.Z);
            for (int Step = 1; Step <= ForkSteps; ++Step)
            {
                const float Distance = ForkStart + (static_cast<float>(Step) / static_cast<float>(ForkSteps)) * ForkMax;
                const CrackPoint RawFork = EvaluateBranch(Arm, true, Distance);
                const CrackPoint Current = ClampToSheet(RawFork.X, RawFork.Z);
                const float Fade0 = (1.0f - static_cast<float>(Step - 1) / static_cast<float>(ForkSteps)) * 0.62f;
                const float Fade1 = (1.0f - static_cast<float>(Step) / static_cast<float>(ForkSteps)) * 0.62f;
                AddCrackSegment(ForkPrevious, Current, BaseWidth * Fade0, BaseWidth * Fade1, Fade0);
                ForkPrevious = Current;
            }
        }
        if (WaveR > 0.42f)
        {
            const float RingRadius = std::min(WaveR * 0.52f, MaxR * (0.28f + 0.24f * CrackHash(static_cast<float>(Arm * 13 + 9), 5.0f)));
            const CrackPoint RawA = EvaluateBranch(Arm, false, RingRadius);
            const CrackPoint RawB = EvaluateBranch((Arm + 1) % 8, false, RingRadius * (0.86f + 0.28f * CrackHash(static_cast<float>(Arm * 17), 6.0f)));
            AddCrackSegment(ClampToSheet(RawA.X, RawA.Z), ClampToSheet(RawB.X, RawB.Z), BaseWidth * 0.28f, BaseWidth * 0.24f, 0.35f);
        }
    }

    // Epicenter impact shatter flash
    const float FlashAlpha = std::max(0.25f, 0.95f - Since * 0.22f);
    Acc.AddRingXZ({ HitX, TopY + 0.05f, HitZ }, Glacial ? 0.32f : 0.48f, 28,
                  Glacial ? Col4{ 0.78f, 0.96f, 1.0f, FlashAlpha } : Col4{ 1.0f, 0.48f, 0.12f, FlashAlpha },
                  0.014f, true, 1.4f);
    (void)AccentColor;
    (void)PrimaryColor;
}

