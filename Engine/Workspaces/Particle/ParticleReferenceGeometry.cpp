constexpr float Pi = 3.14159265358979323846f;

struct Vec3
{
    float X = 0.0f; // [m] - HTML +X
    float Y = 0.0f; // [m] - HTML +Y sky
    float Z = 0.0f; // [m] - HTML +Z
};

[[nodiscard]] constexpr Vec3 Add(Vec3 A, Vec3 B) noexcept { return { A.X + B.X, A.Y + B.Y, A.Z + B.Z }; }
[[nodiscard]] constexpr Vec3 Sub(Vec3 A, Vec3 B) noexcept { return { A.X - B.X, A.Y - B.Y, A.Z - B.Z }; }
[[nodiscard]] constexpr Vec3 Mul(Vec3 A, float S) noexcept { return { A.X * S, A.Y * S, A.Z * S }; }
[[nodiscard]] constexpr Vec3 Lerp(Vec3 A, Vec3 B, float T) noexcept { return { A.X + (B.X - A.X) * T, A.Y + (B.Y - A.Y) * T, A.Z + (B.Z - A.Z) * T }; }

[[nodiscard]] constexpr float Dot(Vec3 A, Vec3 B) noexcept { return A.X * B.X + A.Y * B.Y + A.Z * B.Z; }

[[nodiscard]] constexpr Vec3 Cross(Vec3 A, Vec3 B) noexcept
{
    return { A.Y * B.Z - A.Z * B.Y, A.Z * B.X - A.X * B.Z, A.X * B.Y - A.Y * B.X };
}

[[nodiscard]] float Length(Vec3 A) noexcept { return std::sqrt(Dot(A, A)); }

[[nodiscard]] Vec3 Normalize(Vec3 A) noexcept
{
    const float Len = Length(A);
    if (Len <= 1.0e-6f)
    {
        return { 0.0f, 1.0f, 0.0f };
    }
    return Mul(A, 1.0f / Len);
}

// HTML Y-Up ([x, y, z]) -> Frontier Z-Up ({x, z, y}) with finite guards
[[nodiscard]] Vec3 ToZUp(Vec3 Source) noexcept
{
    auto Safe = [](float V) noexcept { return std::isfinite(V) ? V : 0.0f; };
    return { Safe(Source.X), Safe(Source.Z), Safe(Source.Y) };
}

// Deterministic hash mirroring the HTML WebHash / ArcHash family (0..1)
[[nodiscard]] float Hash01(float Seed, float Salt) noexcept
{
    const float Raw = std::sin(Seed * 12.9898f + Salt * 78.233f) * 43758.5453123f;
    return Raw - std::floor(Raw);
}

[[nodiscard]] float SmoothStep01(float Edge0, float Edge1, float Sample) noexcept
{
    const float T = std::clamp((Sample - Edge0) / std::max(1.0e-5f, Edge1 - Edge0), 0.0f, 1.0f);
    return T * T * (3.0f - 2.0f * T);
}

using Col4 = std::array<float, 4u>;

[[nodiscard]] constexpr Col4 Tint(Col4 Color, float AlphaScale) noexcept
{
    return { Color[0], Color[1], Color[2], std::clamp(Color[3] * AlphaScale, 0.0f, 1.0f) };
}

// HTML direction basis: returns [Right, Up, Forward] matching SoftwarePreviewEngine BasisFrom()
struct AxisBasis
{
    Vec3 Right   { 1.0f, 0.0f, 0.0f };
    Vec3 Up      { 0.0f, 1.0f, 0.0f };
    Vec3 Forward { 0.0f, 0.0f, 1.0f };
};

[[nodiscard]] AxisBasis BasisFrom(Vec3 Direction) noexcept
{
    const Vec3   W  = Normalize(Direction);
    const Vec3   Reference = (std::abs(W.Y) < 0.99f) ? Vec3{ 0.0f, 1.0f, 0.0f } : Vec3{ 1.0f, 0.0f, 0.0f };
    const Vec3   U  = Normalize(Cross(Reference, W));
    const Vec3   V  = Normalize(Cross(W, U));
    return AxisBasis{ U, V, W };
}

