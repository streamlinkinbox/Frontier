void AddPolyline(
    ReferenceAccumulator& Acc,
    const std::vector<Vec3>& Points,
    Col4 ColorStart,
    Col4 ColorEnd,
    float HalfWidth,
    bool Additive,
    float Emissive) noexcept
{
    if (Points.size() < 2u)
    {
        return;
    }
    const std::size_t Last = Points.size() - 1u;
    for (std::size_t Idx = 0; Idx < Last; ++Idx)
    {
        const float T0 = static_cast<float>(Idx) / static_cast<float>(Last);
        const float T1 = static_cast<float>(Idx + 1u) / static_cast<float>(Last);
        const Col4 C0 = { ColorStart[0] + (ColorEnd[0] - ColorStart[0]) * T0,
                          ColorStart[1] + (ColorEnd[1] - ColorStart[1]) * T0,
                          ColorStart[2] + (ColorEnd[2] - ColorStart[2]) * T0,
                          ColorStart[3] + (ColorEnd[3] - ColorStart[3]) * T0 };
        const Col4 C1 = { ColorStart[0] + (ColorEnd[0] - ColorStart[0]) * T1,
                          ColorStart[1] + (ColorEnd[1] - ColorStart[1]) * T1,
                          ColorStart[2] + (ColorEnd[2] - ColorStart[2]) * T1,
                          ColorStart[3] + (ColorEnd[3] - ColorStart[3]) * T1 };
        Acc.AddSegment(Additive, Points[Idx], Points[Idx + 1u], HalfWidth, C0, C1, Emissive);
    }
}

// Catenary-style sagging span between two anchors (HTML silk / cable sag model)
void AddSaggingSpan(
    ReferenceAccumulator& Acc,
    Vec3 Start,
    Vec3 End,
    float SagMeters,
    int Segments,
    Col4 ColorStart,
    Col4 ColorEnd,
    float HalfWidth,
    bool Additive,
    float Emissive) noexcept
{
    const int Steps = std::max(2, Segments);
    std::vector<Vec3> Points;
    Points.reserve(static_cast<std::size_t>(Steps) + 1u);
    for (int Idx = 0; Idx <= Steps; ++Idx)
    {
        const float T = static_cast<float>(Idx) / static_cast<float>(Steps);
        Vec3 Point = Lerp(Start, End, T);
        Point.Y -= 4.0f * SagMeters * T * (1.0f - T);
        Points.push_back(Point);
    }
    AddPolyline(Acc, Points, ColorStart, ColorEnd, HalfWidth, Additive, Emissive);
}

