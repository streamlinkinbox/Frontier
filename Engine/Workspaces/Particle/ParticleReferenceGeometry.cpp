// Recursive midpoint-displacement lightning leader with acute-angle fork branching (SubdivideSpark port)
void SubdivideSpark(
    ReferenceAccumulator& Acc,
    Vec3 Start,
    Vec3 End,
    Vec3 SideDir,
    Vec3 UpDir,
    float Amplitude,
    float BaseHalfWidth,
    int Depth,
    float SeedBase,
    Col4 CoolColor,
    float Intensity,
    float ThermalLift,
    int ForkQuota,
    bool MainChain) noexcept
{
    const int Steps = 1 << std::max(0, std::min(Depth, 6));
    std::vector<Vec3> Points(static_cast<std::size_t>(Steps) + 1u);
    Points.front() = Start;
    Points.back()  = End;

    int   Stride = Steps;
    float Scale  = Amplitude;
    int   Rng    = 1;
    for (int Level = 0; Level < Depth; ++Level)
    {
        const int Half = Stride >> 1;
        for (int Index = 0; Index < Steps; Index += Stride)
        {
            const Vec3 P0 = Points[static_cast<std::size_t>(Index)];
            const Vec3 P1 = Points[static_cast<std::size_t>(Index + Stride)];
            const Vec3 Mid = Lerp(P0, P1, 0.5f);
            const float R1 = Hash01(SeedBase + static_cast<float>(Rng) * 1.73f, 11.3f) - 0.5f;
            const float R2 = Hash01(SeedBase + static_cast<float>(Rng) * 2.41f, 23.7f) - 0.5f;
            const float Kink = 0.65f + Hash01(SeedBase + static_cast<float>(Rng) * 3.19f, 37.1f) * 0.85f;
            const float Du = R1 * Scale * Kink;
            const float Dv = R2 * Scale * Kink;
            const float MidT = static_cast<float>(Index + Half) / static_cast<float>(Steps);
            const float Lift = std::sin(Pi * MidT) * (ThermalLift / static_cast<float>(std::max(1, Depth)));
            Points[static_cast<std::size_t>(Index + Half)] = {
                Mid.X + SideDir.X * Du + UpDir.X * Dv,
                Mid.Y + SideDir.Y * Du + UpDir.Y * Dv + Lift,
                Mid.Z + SideDir.Z * Du + UpDir.Z * Dv,
            };
            ++Rng;
        }
        Stride = Half;
        Scale *= 0.54f;
    }

    for (int Index = 0; Index < Steps; ++Index)
    {
        const float T0 = static_cast<float>(Index) / static_cast<float>(Steps);
        const float Taper0 = MainChain ? (0.85f + 0.30f * std::sin(Pi * T0)) : std::max(0.18f, 1.0f - T0 * 0.82f);
        const float SegmentFade = MainChain ? 1.0f : std::max(0.14f, 1.0f - T0 * 0.78f);
        const int   HotLevel = static_cast<int>((T0) * 3.0f);
        const Col4 SegmentColor = {
            std::min(1.0f, CoolColor[0] + static_cast<float>(HotLevel) * 0.14f),
            std::min(1.0f, CoolColor[1] + static_cast<float>(HotLevel) * 0.13f),
            std::min(1.0f, CoolColor[2]),
            CoolColor[3],
        };
        Acc.AddSegment(true, Points[static_cast<std::size_t>(Index)], Points[static_cast<std::size_t>(Index + 1)],
                       std::max(0.004f, BaseHalfWidth * Taper0), SegmentColor, SegmentColor, Intensity * SegmentFade);
    }

    if (ForkQuota > 0 && Steps >= 8)
    {
        const Vec3  Gap = Normalize(Sub(End, Start));
        const float SpanTotal = Length(Sub(End, Start));
        for (int Fork = 0; Fork < ForkQuota; ++Fork)
        {
            const float Ratio = 0.18f + ((static_cast<float>(Fork) + 0.45f * Hash01(SeedBase, 71.0f + static_cast<float>(Fork))) / static_cast<float>(ForkQuota)) * 0.64f;
            const int   Index = std::clamp(static_cast<int>(std::floor(Ratio * static_cast<float>(Steps))), 2, Steps - 2);
            const Vec3  Root = Points[static_cast<std::size_t>(Index)];
            const float SideSign = (Hash01(SeedBase, 91.0f + static_cast<float>(Fork)) > 0.5f ? 1.0f : -1.0f) * (0.48f + Hash01(SeedBase, 95.0f + static_cast<float>(Fork)) * 0.62f);
            const float VertSign = (Hash01(SeedBase, 103.0f + static_cast<float>(Fork)) - 0.44f) * 0.85f;
            const Vec3  ForkDir = Normalize({
                Gap.X * 0.78f + SideDir.X * SideSign + UpDir.X * VertSign,
                Gap.Y * 0.78f + SideDir.Y * SideSign + UpDir.Y * VertSign,
                Gap.Z * 0.78f + SideDir.Z * SideSign + UpDir.Z * VertSign,
            });
            const float ForkLen = std::min(1.6f, SpanTotal * (0.20f + Hash01(SeedBase, 113.0f + static_cast<float>(Fork)) * 0.24f));
            const Vec3  Tip = Add(Root, Mul(ForkDir, ForkLen));
            const AxisBasis ForkBasis = BasisFrom(ForkDir);
            SubdivideSpark(Acc, Root, Tip, ForkBasis.Right, ForkBasis.Up, ForkLen * 0.24f, BaseHalfWidth * 0.52f,
                           std::max(2, Depth - 2), SeedBase + 409.0f + static_cast<float>(Fork) * 67.0f, CoolColor, Intensity * 0.68f,
                           ThermalLift * 0.25f, (Fork % 2 == 0 && Depth >= 5) ? 1 : 0, false);
        }
    }
}

// Metallic electrode sphere with equatorial corona ring (DrawElectrodeSphere port)
void BuildElectrodeSphere(ReferenceAccumulator& Acc, Vec3 Centre, float Radius, Col4 BaseColor, Col4 RingColor, bool Lit) noexcept
{
    Acc.AddSphere(Centre, Radius, BaseColor, 0.92f, 16, 28, false, 0.0f);
    const Col4 CoronaColor = Lit ? Col4{ 0.98f, 0.84f, 0.38f, 0.92f } : Tint(RingColor, 0.62f);
    Acc.AddRingXZ(Centre, Radius * 1.015f, 32, CoronaColor, std::max(0.006f, Radius * 0.055f));
    Acc.AddRingXZ({ Centre.X, 0.02f, Centre.Z }, std::max(0.14f, Radius * 0.62f), 20, Tint(CoronaColor, Lit ? 0.45f : 0.16f), 0.008f);
}

// Twin-electrode spark discharge across Sphere A -> Sphere B with multi-strike dielectric envelopes
void BuildArcDischarge(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 PrimaryColor,
    Col4 AccentColor,
    float Time) noexcept
{
    (void)PrimaryColor;
    (void)AccentColor;
    const Vec3  PosA{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const Vec3  PosB{ Parameters.TargetX, Parameters.TargetY, Parameters.TargetZ };
    const bool  Static  = (Parameters.ArcMode == 1);
    const float RadA    = std::max(0.08f, Parameters.Radius);
    const float RadB    = std::max(0.08f, Parameters.TargetRadius);
    const float HoldDur = std::max(0.08f, Parameters.ArcHold > 0.0f ? Parameters.ArcHold : (Static ? 0.24f : 0.30f));

    BuildElectrodeSphere(Acc, PosA, RadA, { 0.16f, 0.20f, 0.26f, 0.94f }, Static ? Col4{ 0.42f, 0.88f, 1.0f, 0.90f } : Col4{ 0.46f, 0.80f, 1.0f, 0.90f }, false);
    BuildElectrodeSphere(Acc, PosB, RadB, { 0.20f, 0.19f, 0.28f, 0.94f }, Static ? Col4{ 0.76f, 0.56f, 1.0f, 0.90f } : Col4{ 0.60f, 0.72f, 1.0f, 0.90f }, false);

    const Vec3  Delta = Sub(PosB, PosA);
    const float CenterDist = std::max(0.001f, Length(Delta));
    const Vec3  Dir = Mul(Delta, 1.0f / CenterDist);
    const AxisBasis Basis = BasisFrom(Dir);
    const float SideU = 0.0f;
    (void)SideU;

    // Discharge window within the loop cycle. The reference capture nearly always shows an arc burning
    // between the electrodes, so the idle gap between strikes is kept short.
    const float Cycle = std::max(0.12f, HoldDur * 1.12f);
    const float StrikeAge = std::fmod(Time, Cycle);
    const bool  ActiveStrike = StrikeAge <= HoldDur;
    if (!ActiveStrike)
    {
        // Idle electrode rim corona flicker between discharges
        const float Flicker = 0.22f + 0.16f * std::sin(Time * 31.0f + 0.7f);
        Acc.AddRingXZ(Add(PosA, Mul(Dir, RadA * 0.98f)), 0.16f, 20, Tint(AccentColor, Flicker * 0.75f), 0.008f, true, 0.9f);
        Acc.AddRingXZ(Sub(PosB, Mul(Dir, RadB * 0.98f)), 0.16f, 20, Tint(PrimaryColor, Flicker * 0.75f), 0.008f, true, 0.9f);
        return;
    }

    const float UAge = StrikeAge / HoldDur;
    const float Snap = std::min(1.0f, StrikeAge / 0.012f);
    const float Decay = std::pow(std::max(0.0f, 1.0f - UAge), Static ? 1.25f : 1.45f);
    const float Restrike1 = std::exp(-std::pow((UAge - 0.38f) / 0.055f, 2.0f)) * 0.62f;
    const float Restrike2 = std::exp(-std::pow((UAge - 0.70f) / 0.045f, 2.0f)) * 0.34f;
    const float Envelope = Snap * std::min(1.25f, Decay * 1.15f + Restrike1 + Restrike2);

    // Temperature-mapped air-plasma cooling: blinding blue-white -> sapphire cyan -> violet afterglow
    const Col4 CoolColor = Static
        ? Col4{ 0.42f + 0.45f * Decay, 0.56f + 0.40f * Decay, 1.0f, 1.0f }
        : Col4{ 0.36f + 0.58f * Decay, 0.58f + 0.40f * Decay, 1.0f, 1.0f };

    const float ArchBow = Parameters.ArcBow > 0.0f ? Parameters.ArcBow : (Static ? 0.32f : 0.14f);
    const int   ArcCount = std::clamp(Parameters.ArcCount > 0 ? Parameters.ArcCount : (Static ? 3 : 1), 1, 6);
    const float Jitter = Parameters.ArcJitter > 0.0f ? Parameters.ArcJitter : (Static ? 0.42f : 0.62f);
    const float SeedBase = 97.0f + std::floor(UAge * 2.6f) * 7.13f;

    for (int Strand = 0; Strand < ArcCount; ++Strand)
    {
        const float StrandSeed = SeedBase + static_cast<float>(Strand) * 43.17f;
        const float Lx = (Hash01(StrandSeed, 1.1f) - 0.5f) * 0.54f;
        const float Ly = (Hash01(StrandSeed, 2.2f) - 0.5f) * 0.44f + (ArchBow > 0.0f ? 0.10f : -0.10f);
        const float Rx = (Hash01(StrandSeed, 3.3f) - 0.5f) * 0.52f;
        const float Ry = (Hash01(StrandSeed, 4.4f) - 0.5f) * 0.42f + (ArchBow > 0.0f ? 0.10f : -0.10f);
        const Vec3  CapA = Normalize({
            Dir.X + Basis.Right.X * Lx + Basis.Up.X * Ly,
            Dir.Y + Basis.Right.Y * Lx + Basis.Up.Y * Ly,
            Dir.Z + Basis.Right.Z * Lx + Basis.Up.Z * Ly,
        });
        const Vec3  CapB = Normalize({
            -Dir.X + Basis.Right.X * Rx + Basis.Up.X * Ry,
            -Dir.Y + Basis.Right.Y * Rx + Basis.Up.Y * Ry,
            -Dir.Z + Basis.Right.Z * Rx + Basis.Up.Z * Ry,
        });
        const Vec3 StartPt = Add(PosA, Mul(CapA, RadA));
        const Vec3 EndPt   = Add(PosB, Mul(CapB, RadB));
        const float SpanGap = std::max(0.25f, Length(Sub(EndPt, StartPt)));
        const float Amplitude = std::min(1.15f, SpanGap * 0.21f) * Jitter * (Strand == 0 ? 1.0f : 0.85f);
        const float BaseHalfWidth = (Strand == 0 ? 0.036f : 0.022f) * (0.65f + 0.55f * Envelope);
        const float BoltIntensity = (Strand == 0 ? 1.85f : 1.05f) * Envelope;
        const float ThermalLift = ArchBow + StrikeAge * 0.55f;
        const int   Depth = Static ? 4 : 5;
        const int   Forks = (Strand == 0) ? (Static ? 2 : 4) : (Static ? 1 : 2);

        SubdivideSpark(Acc, StartPt, EndPt, Basis.Right, Basis.Up, Amplitude, BaseHalfWidth, Depth, StrandSeed, CoolColor,
                       BoltIntensity, ThermalLift, Forks, true);

        Acc.AddRingXZ(StartPt, (Strand == 0 ? 0.24f : 0.14f) * (0.55f + 0.65f * Envelope), 18, CoolColor, 0.010f, true, (Strand == 0 ? 1.55f : 0.85f) * Envelope);
        Acc.AddRingXZ(EndPt, (Strand == 0 ? 0.30f : 0.17f) * (0.55f + 0.70f * Envelope), 18, CoolColor, 0.010f, true, (Strand == 0 ? 1.85f : 0.95f) * Envelope);
    }
}

// Plasma cage (arcMode 2) and storm web lattice (arcMode 3) with orbiting conductor junctions
void BuildPlasmaWeb(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 PrimaryColor,
    Col4 AccentColor,
    float Time) noexcept
{
    (void)PrimaryColor;
    (void)AccentColor;
    const Vec3  Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const float CageRadius = std::max(0.5f, Parameters.Radius);
    const float HoldDur = std::max(0.10f, Parameters.ArcHold > 0.0f ? Parameters.ArcHold : 0.22f);
    const float Cycle = std::max(0.14f, HoldDur * 2.8f);
    const float StrikeAge = std::fmod(Time, Cycle);
    const float Envelope = (StrikeAge <= HoldDur) ? std::max(0.45f, std::pow(1.0f - StrikeAge / HoldDur, 0.85f)) : 0.42f;
    const float SeedBase = 97.0f + std::floor(Time * 11.0f) * 13.7f;
    const Col4  CageColor = (Parameters.ArcMode == 2) ? Col4{ 0.52f, 0.68f, 1.0f, 1.0f } : Col4{ 0.46f, 0.82f, 1.0f, 1.0f };

    std::vector<Vec3> Junctions;
    Junctions.reserve(10u);

    if (Parameters.ArcMode == 2)
    {
        const float BaseY = Origin.Y + std::max(0.45f, CageRadius * 0.45f);
        const float Rot = Time * 0.16f;
        Junctions.push_back({ Origin.X, Origin.Y + 0.1f, Origin.Z });
        for (int Ring = 0; Ring < 8; ++Ring)
        {
            const float Angle = (static_cast<float>(Ring) / 8.0f) * Pi * 2.0f + Rot;
            const Vec3 Junction{ Origin.X + std::cos(Angle) * CageRadius,
                             BaseY + std::sin(Angle * 2.0f + Time * 1.4f) * 0.22f,
                             Origin.Z + std::sin(Angle) * CageRadius };
            Junctions.push_back(Junction);
            Acc.AddSphere(Junction, 0.11f, { 0.16f, 0.20f, 0.28f, 0.96f }, 0.90f, 10, 16, false, 0.0f);
            Acc.AddRingXZ(Junction, 0.113f, 20, { 0.48f, 0.84f, 1.0f, 0.92f }, 0.006f);
            Acc.AddLine({ Junction.X, 0.01f, Junction.Z }, Junction, { 0.22f, 0.26f, 0.34f, 0.72f }, 0.008f);
            if (Ring > 0)
            {
                Acc.AddLine(Junctions[static_cast<std::size_t>(Ring)], Junction, { 0.28f, 0.32f, 0.40f, 0.75f }, 0.009f);
            }
        }
        Acc.AddLine(Junctions.back(), Junctions[1], { 0.28f, 0.32f, 0.40f, 0.75f }, 0.009f);
        BuildElectrodeSphere(Acc, Junctions[0], 0.26f, { 0.35f, 0.62f, 1.0f, 0.96f }, { 0.75f, 0.92f, 1.0f, 0.98f }, true);
        Acc.AddRingXZ(Junctions[0], 0.42f, 28, { 0.58f, 0.88f, 1.0f, 0.85f }, 0.012f, true, 1.15f * Envelope);
    }
    else
    {
        const float ExtX = std::max(0.8f, Parameters.BoxX);
        const float ExtY = std::max(0.5f, Parameters.BoxY);
        const float ExtZ = std::max(0.8f, Parameters.BoxZ);
        for (int Junction = 0; Junction < 9; ++Junction)
        {
            const float Phase = Time * 0.55f + static_cast<float>(Junction) * 1.73f;
            const Vec3 Point{ Origin.X + std::sin(Phase * 0.9f + static_cast<float>(Junction)) * ExtX * 0.85f,
                              std::max(0.32f, Origin.Y + std::cos(Phase * 1.15f + static_cast<float>(Junction) * 2.1f) * ExtY * 0.78f),
                              Origin.Z + std::cos(Phase * 0.75f - static_cast<float>(Junction) * 1.3f) * ExtZ * 0.85f };
            Junctions.push_back(Point);
            Acc.AddSphere(Point, 0.085f, { 0.22f, 0.28f, 0.36f, 0.96f }, 0.90f, 10, 16, false, 0.0f);
            Acc.AddRingXZ(Point, 0.088f, 18, { 0.52f, 0.90f, 1.0f, 0.95f }, 0.006f);
        }
    }

    const float Jitter = Parameters.ArcJitter > 0.0f ? Parameters.ArcJitter : 0.64f;
    const int   LinkCount = (Parameters.ArcMode == 2) ? 9 : 11;
    for (int Link = 0; Link < LinkCount; ++Link)
    {
        const int NodeCount = static_cast<int>(Junctions.size());
        if (NodeCount < 2)
        {
            break;
        }
        const int IndexA = (Parameters.ArcMode == 2)
            ? ((Link % 2 == 0) ? 0 : 1 + (Link % (NodeCount - 1)))
            : (Link % NodeCount);
        const int IndexB = (Parameters.ArcMode == 2)
            ? (1 + ((Link * 3 + static_cast<int>(Hash01(SeedBase, static_cast<float>(Link)) * 3.0f)) % (NodeCount - 1)))
            : ((Link + 2 + static_cast<int>(Hash01(SeedBase, static_cast<float>(Link * 3)) * 3.0f)) % NodeCount);
        if (IndexA == IndexB)
        {
            continue;
        }
        const Vec3  A = Junctions[static_cast<std::size_t>(IndexA)];
        const Vec3  B = Junctions[static_cast<std::size_t>(IndexB)];
        const Vec3  Delta = Sub(B, A);
        const float Span = std::max(0.2f, Length(Delta));
        const AxisBasis Basis = BasisFrom(Mul(Delta, 1.0f / Span));
        SubdivideSpark(Acc, A, B, Basis.Right, Basis.Up, std::min(0.75f, Span * 0.22f) * Jitter, 0.024f, 4,
                       SeedBase + static_cast<float>(Link) * 31.7f, CageColor, 1.45f * Envelope, 0.08f,
                       (Link % 2 == 0) ? 2 : 1, true);
        Acc.AddRingXZ(A, 0.16f, 18, CageColor, 0.008f, true, 0.95f * Envelope);
        Acc.AddRingXZ(B, 0.18f, 18, CageColor, 0.008f, true, 1.05f * Envelope);
    }
}

// Continuous coherent laser / plasma beam with helical containment rib and impact flare
void BuildLaserBeam(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 CoreColor,
    Col4 MuzzleColor,
    Col4 ImpactColor,
    float Time) noexcept
{
    const Vec3  PosA{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const Vec3  PosB{ Parameters.TargetX, Parameters.TargetY, Parameters.TargetZ };
    const Vec3  Delta = Sub(PosB, PosA);
    const float Span = std::max(0.001f, Length(Delta));
    const AxisBasis Basis = BasisFrom(Mul(Delta, 1.0f / Span));
    const float BeamHalfWidth = std::max(0.012f, 0.048f * (Parameters.SizeStart / 0.036f));
    const float PulseSpeed = 6.0f;

    Acc.AddRingXZ(PosA, std::max(0.14f, Parameters.Radius), 20, Tint(MuzzleColor, 0.86f), 0.014f);
    Acc.AddRingXZ(PosB, std::max(0.14f, Parameters.TargetRadius), 20, Tint(ImpactColor, 0.88f), 0.014f);
    Acc.AddLine(PosA, { PosA.X, 0.02f, PosA.Z }, Tint(MuzzleColor, 0.28f), 0.008f);
    Acc.AddLine(PosB, { PosB.X, 0.02f, PosB.Z }, Tint(ImpactColor, 0.28f), 0.008f);

    constexpr int BeamSteps = 24;
    for (int Step = 0; Step < BeamSteps; ++Step)
    {
        const float U0 = static_cast<float>(Step) / static_cast<float>(BeamSteps);
        const float U1 = static_cast<float>(Step + 1) / static_cast<float>(BeamSteps);
        const float Wave0 = 0.84f + 0.32f * std::sin(U0 * 14.0f - Time * PulseSpeed * 3.0f);
        const Vec3 A0 = Add(PosA, Mul(Delta, U0));
        const Vec3 A1 = Add(PosA, Mul(Delta, U1));
        Acc.AddSegment(true, A0, A1, BeamHalfWidth * Wave0, CoreColor, CoreColor, 1.85f);

        // Helical plasma containment rib spiralling tightly around the beam core
        const float Phase0 = U0 * 12.0f - Time * PulseSpeed * 4.2f;
        const float Phase1 = U1 * 12.0f - Time * PulseSpeed * 4.2f;
        const float RibRadius = BeamHalfWidth * 1.65f;
        const auto RibPoint = [&](Vec3 AxisPoint, float Phase) noexcept -> Vec3
        {
            return Add(AxisPoint, Add(Mul(Basis.Right, std::cos(Phase) * RibRadius), Mul(Basis.Up, std::sin(Phase) * RibRadius)));
        };
        Acc.AddSegment(true, RibPoint(A0, Phase0), RibPoint(A1, Phase1), BeamHalfWidth * 0.42f, CoreColor, CoreColor, 0.92f);
    }

    const float Flicker = 0.92f + 0.18f * std::sin(Time * 37.0f);
    Acc.AddRingXZ(PosA, std::max(0.24f, BeamHalfWidth * 6.5f), 24, Tint(MuzzleColor, 0.95f), 0.016f, true, 1.45f * Flicker);
    Acc.AddRingXZ(PosB, std::max(0.32f, BeamHalfWidth * 8.5f), 28, { 1.0f, 0.78f, 0.48f, 0.95f }, 0.018f, true, 1.75f * Flicker);
}

