constexpr std::array<float, 6u> OrbAnchorAngles = { 0.14f, 1.12f, 2.28f, 3.32f, 4.34f, 5.42f };
constexpr std::array<float, 6u> OrbAnchorRadii  = { 1.28f, 1.14f, 1.32f, 1.16f, 1.26f, 1.18f };

// Ray-to-original-hexagon edge intersection in the web plane (SoftwarePreviewEngine OrbRimEdgeLocal)
[[nodiscard]] Vec3 OrbRimEdgeLocal(float Theta, float Radius) noexcept
{
    const float DirX = std::cos(Theta);
    const float DirY = std::sin(Theta);
    float       BestT = Radius * 1.15f;
    for (int Corner = 0; Corner < 6; ++Corner)
    {
        const int   Next = (Corner + 1) % 6;
        const float Ax = std::cos(OrbAnchorAngles[static_cast<std::size_t>(Corner)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Corner)];
        const float Ay = std::sin(OrbAnchorAngles[static_cast<std::size_t>(Corner)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Corner)];
        const float Bx = std::cos(OrbAnchorAngles[static_cast<std::size_t>(Next)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Next)];
        const float By = std::sin(OrbAnchorAngles[static_cast<std::size_t>(Next)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Next)];
        const float EdgeX = Bx - Ax;
        const float EdgeY = By - Ay;
        const float Den = DirX * EdgeY - DirY * EdgeX;
        if (std::abs(Den) > 1.0e-4f)
        {
            const float RayT  = (Ax * EdgeY - Ay * EdgeX) / Den;
            const float EdgeU = (Ax * DirY - Ay * DirX) / Den;
            if (RayT > 0.0f && EdgeU >= -0.02f && EdgeU <= 1.02f && RayT < BestT)
            {
                BestT = RayT;
            }
        }
    }
    return { DirX * BestT, DirY * BestT, 0.0f };
}

// Local web-plane offset -> HTML world position using the preset orientation basis
[[nodiscard]] Vec3 WebLocalToWorld(Vec3 Origin, const AxisBasis& Basis, Vec3 Local) noexcept
{
    return {
        Origin.X + Basis.Right.X * Local.X + Basis.Up.X * Local.Y + Basis.Forward.X * Local.Z,
        Origin.Y + Basis.Right.Y * Local.X + Basis.Up.Y * Local.Y + Basis.Forward.Y * Local.Z,
        Origin.Z + Basis.Right.Z * Local.X + Basis.Up.Z * Local.Y + Basis.Forward.Z * Local.Z,
    };
}

// Gentle aerodynamic silk sway (WebSwayAt simplified to its analytic curl component; wind coupling scales amplitude)
[[nodiscard]] Vec3 SilkSway(Vec3 Point, float Time, float WindScale, float Coupling, float CurlAmp, float CurlFreq) noexcept
{
    const float X = Point.X * CurlFreq * 0.45f + Time * 0.58f;
    const float Y = Point.Y * CurlFreq * 0.45f - Time * 0.36f;
    const float Z = Point.Z * CurlFreq * 0.45f + Time * 0.46f;

    const float DAzDy = 1.15f * std::cos(X * 1.1f + Y * 1.15f) - 1.1f * std::sin(Y * 2.2f - Z * 1.6f);
    const float DAyDz = 1.2f * std::cos(Z * 1.2f + X * 0.95f);
    const float DAxDz = 0.9f * std::cos(Y * 1.3f + Z * 0.9f) - 1.2f * std::sin(Z * 2.4f - X * 1.7f);
    const float DAzDx = 1.1f * std::cos(X * 1.1f + Y * 1.15f);
    const float DAyDx = 0.95f * std::cos(Z * 1.2f + X * 0.95f) - 1.15f * std::sin(X * 2.3f - Y * 1.8f);
    const float DAxDy = 1.3f * std::cos(Y * 1.3f + Z * 0.9f);

    const float Scale = CurlAmp * 0.16f * WindScale * std::max(0.0f, Coupling) * 0.42f;
    Vec3 Sway{ (DAzDy - DAyDz) * Scale, (DAxDz - DAzDx) * Scale, (DAyDx - DAxDy) * Scale };
    const float Magnitude = Length(Sway);
    constexpr float ClampSpeed = 0.30f;
    if (Magnitude > ClampSpeed)
    {
        Sway = Mul(Sway, ClampSpeed / Magnitude);
    }
    return Sway;
}

void BuildOrbWeaveWeb(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 SilkColor,
    Col4 DewColor,
    float Time,
    float Thickness) noexcept
{
    const Vec3        Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const AxisBasis   Basis = BasisFrom({ Parameters.DirX, Parameters.DirY, Parameters.DirZ });
    const float       Radius = std::max(0.45f, Parameters.Radius);
    const int         Spokes = std::clamp(Parameters.WebSpokes, 8, 32);
    const int         Rings  = std::clamp(Parameters.WebRings, 6, 22);
    const float       SagBase = std::max(0.0f, Parameters.WebSag);
    const float       Coupling = Parameters.WindCoupling;

    // BodyJunction anchor sits just behind the orb centre along the local normal
    const Vec3 BodyJunctionBase = WebLocalToWorld(Origin, Basis, { 0.0f, -0.05f * Radius, 0.0f });
    const Vec3 BodyJunction = Add(BodyJunctionBase, SilkSway(BodyJunctionBase, Time, 0.24f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));

    // 1) Six silk anchor spars spanning the hexagonal orb rim
    for (int Slot = 0; Slot < 6; ++Slot)
    {
        const int   Next  = (Slot + 1) % 6;
        const float Ax = std::cos(OrbAnchorAngles[static_cast<std::size_t>(Slot)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Slot)];
        const float Ay = std::sin(OrbAnchorAngles[static_cast<std::size_t>(Slot)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Slot)];
        const float Bx = std::cos(OrbAnchorAngles[static_cast<std::size_t>(Next)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Next)];
        const float By = std::sin(OrbAnchorAngles[static_cast<std::size_t>(Next)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Next)];
        const Vec3  RawA = WebLocalToWorld(Origin, Basis, { Ax, Ay, 0.0f });
        const Vec3  RawB = WebLocalToWorld(Origin, Basis, { Bx, By, 0.0f });
        const Vec3  PA   = Add(RawA, SilkSway(RawA, Time, 0.08f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));
        const Vec3  PB   = Add(RawB, SilkSway(RawB, Time, 0.08f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));
        AddSaggingSpan(Acc, PA, PB, SagBase * 0.42f, 10, SilkColor, SilkColor, Thickness * 1.35f, false, 0.0f);
    }

    // 2) Twelve anchor stay lines tying the rim outward into the scene
    for (int Group = 0; Group < 6; ++Group)
    {
        const float Ax = std::cos(OrbAnchorAngles[static_cast<std::size_t>(Group)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Group)];
        const float Ay = std::sin(OrbAnchorAngles[static_cast<std::size_t>(Group)]) * Radius * OrbAnchorRadii[static_cast<std::size_t>(Group)];
        const Vec3  RawA = WebLocalToWorld(Origin, Basis, { Ax, Ay, 0.0f });
        const Vec3  PA   = Add(RawA, SilkSway(RawA, Time, 0.08f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));
        const Vec3  PB   = WebLocalToWorld(Origin, Basis, { Ax * 1.18f, Ay * 1.18f, 0.0f });
        AddSaggingSpan(Acc, PA, PB, SagBase * 0.15f, 6, SilkColor, Tint(SilkColor, 0.65f), Thickness, false, 0.0f);
    }

    // 3) Radial spokes from the junction out to the hexagonal rim
    for (int Index = 0; Index < Spokes; ++Index)
    {
        const float Jitter = (Hash01(static_cast<float>(Index * 19 + 3), 1.0f) - 0.5f) * 0.032f;
        const float Theta  = (static_cast<float>(Index) / static_cast<float>(Spokes)) * Pi * 2.0f + Jitter;
        const Vec3  Local  = OrbRimEdgeLocal(Theta, Radius);
        const Vec3  RawB   = WebLocalToWorld(Origin, Basis, Local);
        const Vec3  PB     = Add(RawB, SilkSway(RawB, Time, 0.08f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));
        AddSaggingSpan(Acc, BodyJunction, PB, SagBase * 0.20f, 8, SilkColor, SilkColor, Thickness, false, 0.0f);
    }

    // 4) Logarithmic capture spiral: junction loops then expanding rings that sag between spokes
    const int   TotalSegments = Spokes * Rings;
    const int   BodyJunctionSegments   = Spokes * 2;
    for (int SpiralSegment = 0; SpiralSegment < TotalSegments; ++SpiralSegment)
    {
        const int   S0 = SpiralSegment % Spokes;
        const int   S1 = (SpiralSegment + 1) % Spokes;
        const float U0 = std::min(1.0f, static_cast<float>(SpiralSegment) / static_cast<float>(TotalSegments));
        const float RF0 = (SpiralSegment < BodyJunctionSegments)
            ? (0.035f + 0.07f * (static_cast<float>(SpiralSegment) / static_cast<float>(std::max(1, BodyJunctionSegments))))
            : (0.20f + 0.72f * std::pow(std::max(0.0f, static_cast<float>(SpiralSegment - BodyJunctionSegments) / static_cast<float>(std::max(1, TotalSegments - BodyJunctionSegments))), 0.92f));
        const float RF1 = ((SpiralSegment + 1) < BodyJunctionSegments)
            ? (0.035f + 0.07f * (static_cast<float>(SpiralSegment + 1) / static_cast<float>(std::max(1, BodyJunctionSegments))))
            : (0.20f + 0.72f * std::pow(std::max(0.0f, static_cast<float>(SpiralSegment + 1 - BodyJunctionSegments) / static_cast<float>(std::max(1, TotalSegments - BodyJunctionSegments))), 0.92f));

        const float Th0 = (static_cast<float>(S0) / static_cast<float>(Spokes)) * Pi * 2.0f + (Hash01(static_cast<float>(S0 * 19 + 3), 1.0f) - 0.5f) * 0.032f;
        const float Th1 = (static_cast<float>(S1) / static_cast<float>(Spokes)) * Pi * 2.0f + (Hash01(static_cast<float>(S1 * 19 + 3), 1.0f) - 0.5f) * 0.032f;
        const Vec3  Rim0 = WebLocalToWorld(Origin, Basis, OrbRimEdgeLocal(Th0, Radius));
        const Vec3  Rim1 = WebLocalToWorld(Origin, Basis, OrbRimEdgeLocal(Th1, Radius));
        const Vec3  E0   = Add(Rim0, SilkSway(Rim0, Time, 0.08f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));
        const Vec3  E1   = Add(Rim1, SilkSway(Rim1, Time, 0.08f, Coupling, Parameters.CurlAmp, Parameters.CurlFreq));

        const float SpLen0 = std::max(1.0e-4f, Length(Sub(E0, BodyJunction)));
        const float SpLen1 = std::max(1.0e-4f, Length(Sub(E1, BodyJunction)));
        const Vec3  Perp0{ E0.X - BodyJunction.X, 0.0f, E0.Z - BodyJunction.Z };
        const Vec3  Perp1{ E1.X - BodyJunction.X, 0.0f, E1.Z - BodyJunction.Z };
        const float SpH0 = std::clamp(Length(Perp0) / SpLen0, 0.12f, 1.0f);
        const float SpH1 = std::clamp(Length(Perp1) / SpLen1, 0.12f, 1.0f);

        const Vec3 PA = {
            BodyJunction.X + (E0.X - BodyJunction.X) * RF0,
            BodyJunction.Y + (E0.Y - BodyJunction.Y) * RF0 - 4.0f * SagBase * 0.20f * SpH0 * RF0 * (1.0f - RF0),
            BodyJunction.Z + (E0.Z - BodyJunction.Z) * RF0,
        };
        const Vec3 PB = {
            BodyJunction.X + (E1.X - BodyJunction.X) * RF1,
            BodyJunction.Y + (E1.Y - BodyJunction.Y) * RF1 - 4.0f * SagBase * 0.20f * SpH1 * RF1 * (1.0f - RF1),
            BodyJunction.Z + (E1.Z - BodyJunction.Z) * RF1,
        };

        const float SegmentLength = Length(Sub(PB, PA));
        const Vec3  SegmentPerp{ PB.X - PA.X, 0.0f, PB.Z - PA.Z };
        const float SegmentH = std::clamp(Length(SegmentPerp) / std::max(1.0e-4f, SegmentLength), 0.12f, 1.0f);
        const float SegmentSag = SagBase * (0.22f + 0.55f * U0) * SegmentH
            * std::clamp(SegmentLength / std::max(0.28f, Radius * 0.36f), 0.35f, 1.25f);

        AddSaggingSpan(Acc, PA, PB, SegmentSag, 4, SilkColor, SilkColor, Thickness * 0.85f, false, 0.0f);

        // Morning dew glints crystallise on every third capture-spiral joint
        if ((SpiralSegment % 3) == 0)
        {
            Acc.AddRingXZ(PA, Thickness * 3.6f, 6, Tint(DewColor, 0.85f), Thickness * 0.9f, false, 0.0f);
        }
    }
}

void BuildCobwebTangle(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 SilkColor,
    Col4 DewColor,
    float Time,
    float Thickness) noexcept
{
    const Vec3      Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const AxisBasis Basis = BasisFrom({ Parameters.DirX, Parameters.DirY, Parameters.DirZ });
    const std::array<float, 3u> Ext = {
        std::max(0.65f, Parameters.BoxX),
        std::max(0.65f, Parameters.BoxY),
        std::max(0.65f, Parameters.BoxZ),
    };
    const float SagBase = std::max(0.0f, Parameters.WebSag);
    const int   Chords  = std::clamp(Parameters.WebSpokes * 2, 16, 40);
    const int   Tangles = Chords + std::clamp(Parameters.WebRings * 2, 8, 34);

    // Deterministic pocket anchors: three attic corner clusters, each holding silk chords
    const std::array<std::array<float, 3u>, 3u> PocketAnchors = {{
        { -Ext[0] * 0.52f, Ext[1] * 0.36f, -Ext[2] * 0.28f },
        {  Ext[0] * 0.08f, Ext[1] * 0.46f,  Ext[2] * 0.08f },
        {  Ext[0] * 0.56f, Ext[1] * 0.22f, -Ext[2] * 0.20f },
    }};

    auto PocketPoint = [&](float Seed, int Pocket, int Role) noexcept -> Vec3
    {
        const std::array<float, 3u>& PocketRoot = PocketAnchors[static_cast<std::size_t>(std::clamp(Pocket, 0, 2))];
        const float U0 = Hash01(Seed, 1.0f);
        const float U1 = Hash01(Seed, 2.0f);
        const float U2 = Hash01(Seed, 3.0f);
        Vec3 Local{ PocketRoot[0], PocketRoot[1], PocketRoot[2] };
        if (Role == 0)
        {
            Local.X += (U0 - 0.5f) * Ext[0] * 0.88f;
            Local.Y += Ext[1] * (0.42f + 0.28f * U1);
            Local.Z += (U2 - 0.5f) * Ext[2] * 0.65f;
        }
        else if (Role == 1)
        {
            Local.X -= Ext[0] * (0.38f + 0.38f * U0);
            Local.Y += (U1 * 1.15f - 0.68f) * Ext[1];
            Local.Z += (U2 - 0.5f) * Ext[2] * 0.72f;
        }
        else
        {
            Local.X += Ext[0] * (0.28f + 0.44f * U0);
            Local.Y += (U1 * 1.05f - 0.58f) * Ext[1];
            Local.Z += (U2 - 0.5f) * Ext[2] * 0.72f;
        }
        return WebLocalToWorld(Origin, Basis, Local);
    };

    struct Chord { Vec3 Start; Vec3 End; float Sag; };
    auto ChordOf = [&](int ChordIndex) noexcept -> Chord
    {
        const float Seed   = static_cast<float>(ChordIndex) * 37.0f + 13.0f;
        const int   Pocket = ChordIndex % 3;
        const int   RoleA  = static_cast<int>(std::floor(Hash01(Seed, 5.0f) * 3.0f)) % 3;
        const int   RoleB  = (RoleA + 1 + static_cast<int>(std::floor(Hash01(Seed, 6.0f) * 2.0f))) % 3;
        const Vec3  A = PocketPoint(Seed + 1.1f, Pocket, RoleA);
        const Vec3  B = PocketPoint(Seed + 7.9f, Pocket, RoleB);
        const float Span = Length(Sub(B, A));
        const float Sag = SagBase * (0.55f + 1.25f * Hash01(Seed, 8.0f)) * std::clamp(Span / 2.2f, 0.45f, 1.55f);
        return Chord{ A, B, Sag };
    };

    // 1) Primary silk chords slung across every pocket
    for (int Index = 0; Index < Chords; ++Index)
    {
        const Chord Line = ChordOf(Index);
        AddSaggingSpan(Acc, Line.Start, Line.End, Line.Sag, 8, SilkColor, SilkColor, Thickness, false, 0.0f);
    }

    // 2) Cross tangles binding random chord midpoints together with extra sag
    for (int Index = 0; Index < Tangles; ++Index)
    {
        const float Seed = static_cast<float>(Index) * 53.0f + 19.0f;
        const int   ChordA = static_cast<int>(std::floor(Hash01(Seed, 1.0f) * static_cast<float>(Chords))) % std::max(1, Chords);
        const int   Pocket = ChordA % 3;
        const int   Step   = 1 + static_cast<int>(std::floor(Hash01(Seed, 2.0f) * std::max(2.0f, static_cast<float>(Chords) / 4.0f)));
        const int   ChordB = (Pocket + (static_cast<int>(std::floor(static_cast<float>(ChordA - Pocket) / 3.0f)) + Step) * 3) % std::max(1, Chords);
        const float UA = 0.10f + 0.80f * Hash01(Seed, 3.0f);
        const float UB = 0.10f + 0.80f * Hash01(Seed, 4.0f);
        const Chord LineA = ChordOf(ChordA);
        const Chord LineB = ChordOf(ChordB);
        const Vec3 PA = {
            LineA.Start.X + (LineA.End.X - LineA.Start.X) * UA,
            LineA.Start.Y + (LineA.End.Y - LineA.Start.Y) * UA - 4.0f * LineA.Sag * UA * (1.0f - UA),
            LineA.Start.Z + (LineA.End.Z - LineA.Start.Z) * UA,
        };
        const Vec3 PB = {
            LineB.Start.X + (LineB.End.X - LineB.Start.X) * UB,
            LineB.Start.Y + (LineB.End.Y - LineB.Start.Y) * UB - 4.0f * LineB.Sag * UB * (1.0f - UB),
            LineB.Start.Z + (LineB.End.Z - LineB.Start.Z) * UB,
        };
        const float Span = Length(Sub(PB, PA));
        const float Sag = SagBase * (0.45f + 0.95f * Hash01(Seed, 5.0f)) * std::clamp(Span / 1.8f, 0.3f, 1.4f);
        AddSaggingSpan(Acc, PA, PB, Sag, 6, SilkColor, Tint(SilkColor, 0.8f), Thickness * 0.8f, false, 0.0f);
    }

    // 3) Gossamer dust drapes falling from the chords
    const int Drapes = std::max(4, Parameters.WebRings / 2);
    for (int Index = 0; Index < Drapes; ++Index)
    {
        const float Seed    = static_cast<float>(Index) * 71.0f + 41.0f;
        const int   ChordIn = static_cast<int>(std::floor(Hash01(Seed, 1.0f) * static_cast<float>(Chords))) % std::max(1, Chords);
        const float U       = 0.16f + 0.68f * Hash01(Seed, 2.0f);
        const Chord Line    = ChordOf(ChordIn);
        const Vec3 PA = {
            Line.Start.X + (Line.End.X - Line.Start.X) * U,
            Line.Start.Y + (Line.End.Y - Line.Start.Y) * U - 4.0f * Line.Sag * U * (1.0f - U),
            Line.Start.Z + (Line.End.Z - Line.Start.Z) * U,
        };
        const float DropLen = 0.55f + 0.90f * Hash01(Seed, 3.0f);
        const Vec3 PB = {
            PA.X + (Hash01(Seed, 4.0f) - 0.5f) * 0.26f,
            PA.Y - DropLen,
            PA.Z + (Hash01(Seed, 5.0f) - 0.5f) * 0.26f,
        };
        const Vec3 SwayPoint = Add(PB, SilkSway(PB, Time, 0.85f, Parameters.WindCoupling, Parameters.CurlAmp * 1.25f, Parameters.CurlFreq * 1.2f));
        AddSaggingSpan(Acc, PA, SwayPoint, 0.05f * DropLen, 5, SilkColor, Tint(DewColor, 0.55f), Thickness * 0.7f, false, 0.0f);
    }
}

