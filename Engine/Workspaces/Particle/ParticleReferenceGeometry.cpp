//                                        BEADS, SEED HEADS & HANGING CURTAINS
//------------------------------------------------------------------------------------------------------------------------

void BuildVelvetDrapes(ReferenceAccumulator& Acc, const ReferencePresetParameters& Parameters, Col4 VelvetColor, Col4 SheenColor) noexcept;

void BuildBeadedCurtain(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 PrimaryColor,
    Col4 AccentColor,
    Col4 HighlightColor,
    float Time) noexcept
{
    const Vec3  Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const float TopY = Origin.Y + std::max(0.85f, Parameters.DynHeight);
    const Col4  RailColor{ 0.36f, 0.24f, 0.16f, 0.95f };
    const Col4  PostColor{ 0.28f, 0.19f, 0.13f, 0.82f };
    // The reference curtain is a dense forest of bead strings, so the string count follows box width
    // far more aggressively than a sparse rail would.
    const int   Strands = std::max(24, std::min(52, static_cast<int>(Parameters.BoxX * 22.0f)));

    if (Parameters.BeadsMode == 3)
    {
        BuildVelvetDrapes(Acc, Parameters, PrimaryColor, HighlightColor);
        return;
    }

    for (int Mode = 0; Mode < 1; ++Mode)
    {
        if (Parameters.BeadsMode == 1)
        {
            const float ExtX = std::max(0.45f, Parameters.BoxX);
            BuildHangingRail(Acc, Origin, ExtX, TopY, RailColor, PostColor);
        }
        else if (Parameters.BeadsMode == 2)
        {
            BuildChimeCrown(Acc, Origin, std::max(0.52f, Parameters.Radius * 1.15f), TopY, { 0.92f, 0.74f, 0.38f, 0.96f });
        }
        else
        {
            const float ExtX = std::max(0.45f, Parameters.BoxX);
            BuildHangingRail(Acc, Origin, ExtX, TopY, RailColor, PostColor);
        }
    }

    // Chime tubes are bamboo: warm amber shafts with pale tips, matching the reference capture.
    const Col4 LeadColor = (Parameters.BeadsMode == 2)
        ? Col4{ 0.72f, 0.44f, 0.14f, 1.0f }
        : Tint(PrimaryColor, 1.0f);

    // Individual hanging bead strands with alternating pastel / metallic tints
    for (int Strand = 0; Strand < Strands; ++Strand)
    {
        const float U = (static_cast<float>(Strand) + 0.5f) / static_cast<float>(Strands);
        const float StrandX = Origin.X + (U - 0.5f) * 2.0f * Parameters.BoxX * 1.02f;
        const float StrandLen = std::max(0.5f, Parameters.DynHeight * (0.72f + 0.24f * Hash01(static_cast<float>(Strand) * 17.0f, 3.0f)));
        const float Sway = std::sin(Time * 1.4f + static_cast<float>(Strand) * 0.62f) * 0.045f;
        const int   BeadCount = 24;
        for (int Bead = 0; Bead < BeadCount; ++Bead)
        {
            const float BeadU = (static_cast<float>(Bead) + 0.5f) / static_cast<float>(BeadCount);
            const Vec3 Point{ StrandX + Sway * BeadU, TopY - StrandLen * BeadU, Origin.Z };
            const float Tint01 = Hash01(static_cast<float>(Strand * 31 + Bead), 5.0f);
            const Col4 BeadColor = (Tint01 > 0.55f) || (Bead % 4 == 0)
                ? Tint(HighlightColor, 0.92f)
                : Tint((Parameters.BeadsMode == 2) ? LeadColor : AccentColor, (Tint01 > 0.28f) ? 1.0f : 0.86f);
            // Dense reference bead strands: beads are ~0.75x the authored bead size and use lifted albedo so
            // the pastel / metallic alternation is visible instead of vanishing into the dark backdrop.
            Acc.AddSphere(Point, std::max(0.055f, Parameters.SizeStart * 0.75f), LiftAlbedo(BeadColor, 0.30f), 0.45f, 6, 10, false, 0.18f);
        }
        Acc.AddLine({ StrandX, TopY, Origin.Z }, { StrandX + Sway, TopY - StrandLen, Origin.Z }, Tint(PrimaryColor, 0.55f), 0.006f);
    }
}

// Dandelion seed-head puffs on green stems (seedHeadMode 1)
void BuildSeedHeadPuffs(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 StemColor,
    Col4 PuffColor,
    float Time) noexcept
{
    const Vec3  Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const int   Stalks = std::max(3, static_cast<int>(Parameters.DynRows));
    const float StemHeight = std::max(0.6f, Parameters.DynHeight);
    for (int Stalk = 0; Stalk < Stalks; ++Stalk)
    {
        const float Seed = static_cast<float>(Stalk) * 23.0f + 7.0f;
        const float OffsetX = (Hash01(Seed, 1.0f) * 2.0f - 1.0f) * Parameters.BoxX * 0.62f;
        const float OffsetZ = (Hash01(Seed, 2.0f) * 2.0f - 1.0f) * Parameters.BoxZ * 0.62f;
        const float Height = StemHeight * (0.62f + 0.44f * Hash01(Seed, 3.0f));
        const Vec3 Base{ Origin.X + OffsetX, 0.0f, Origin.Z + OffsetZ };
        const Vec3 Crown{ Base.X + 0.05f * std::sin(Time * 1.1f + Seed), Height, Base.Z + 0.05f * std::cos(Time * 0.9f + Seed) };
        Acc.AddCylinder(Base, Crown, 0.014f, 0.009f, 6, StemColor, 0.10f);

        // The reference puffs are large white seed-head orbs built from a dense radial filament fan, so the
        // radius follows the authored seed-head extent and the filament count is high enough to read as fluff.
        const float PuffRadius = std::max(0.30f, Parameters.SizeStart * 4.4f);
        Acc.AddSphere(Crown, PuffRadius * 0.86f, Tint(PuffColor, 0.34f), 0.0f, 12, 20, false, 0.26f);
        constexpr int Filaments = 150;
        for (int Filament = 0; Filament < Filaments; ++Filament)
        {
            const float Fan     = static_cast<float>(Filament) / static_cast<float>(Filaments);
            const float Theta   = Fan * Pi * 2.0f * 7.0f;
            const float Phi     = std::acos(std::clamp(1.0f - 2.0f * std::fmod(Fan * 11.0f, 1.0f), -1.0f, 1.0f));
            const float FilRad  = PuffRadius * (0.90f + 0.22f * Hash01(static_cast<float>(Filament) * 13.0f, 2.0f));
            const Vec3 Tip{ Crown.X + std::sin(Phi) * std::cos(Theta) * FilRad,
                            Crown.Y + std::cos(Phi) * FilRad,
                            Crown.Z + std::sin(Phi) * std::sin(Theta) * FilRad };
            Acc.AddLine(Crown, Tip, Tint(PuffColor, 0.86f), 0.0055f);
            Acc.AddRingXZ(Tip, 0.018f, 6, Tint(PuffColor, 1.0f), 0.006f);
        }
    }
}

// Pleated velvet theater drapes flanking the proscenium opening
void BuildVelvetDrapes(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 VelvetColor,
    Col4 SheenColor) noexcept
{
    const Vec3  Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const float TopY = Origin.Y + std::max(0.85f, Parameters.DynHeight);
    const float HalfWidth = std::max(0.5f, Parameters.BoxX);
    const int   Pleats = 18;
    const Col4  RailColor{ 0.42f, 0.30f, 0.18f, 0.96f };
    Acc.AddCylinder({ Origin.X - HalfWidth * 1.06f, TopY + 0.04f, Origin.Z }, { Origin.X + HalfWidth * 1.06f, TopY + 0.04f, Origin.Z }, 0.036f, 0.036f, 8, RailColor, 0.35f);

    for (int Pleat = 0; Pleat < Pleats; ++Pleat)
    {
        const float U0 = static_cast<float>(Pleat) / static_cast<float>(Pleats);
        const float U1 = static_cast<float>(Pleat + 1) / static_cast<float>(Pleats);
        const float X0 = Origin.X - HalfWidth + HalfWidth * 2.0f * U0;
        const float X1 = Origin.X - HalfWidth + HalfWidth * 2.0f * U1;
        const float Fold0 = std::sin(U0 * Pi * 7.0f) * 0.16f;
        const float Fold1 = std::sin(U1 * Pi * 7.0f) * 0.16f;
        const float Depth0 = 0.10f + 0.07f * std::cos(U0 * Pi * 7.0f);
        const float Depth1 = 0.10f + 0.07f * std::cos(U1 * Pi * 7.0f);
        const float BottomY = 0.03f;
        const Vec3 T0{ X0, TopY, Origin.Z + Fold0 * 0.30f };
        const Vec3 T1{ X1, TopY, Origin.Z + Fold1 * 0.30f };
        const Vec3 B0{ X0 + Fold0 * 0.55f, BottomY, Origin.Z + Fold0 + Depth0 * 0.30f };
        const Vec3 B1{ X1 + Fold1 * 0.55f, BottomY, Origin.Z + Fold1 + Depth1 * 0.30f };
        // The reference drape reads as a saturated crimson wall with a dimmer sheen per pleat: the authored
        // velvet albedo is very dark, so lift it toward the lit crimson the reference capture shows while
        // keeping the alternating pleat rhythm.
        const Col4 LitVelvet  = LiftAlbedo(VelvetColor, 0.30f);
        const Col4 LitSheen   = LiftAlbedo(SheenColor, 0.24f);
        const Col4 FaceColor = (Pleat % 2 == 0)
            ? LitVelvet
            : Tint(LitSheen, 0.42f + 0.40f * SmoothStep01(0.0f, 1.0f, U0));
        Acc.AddQuad(false, false, T0, T1, B1, B0, FaceColor, 0.0f, 0.06f);
        Acc.AddLine(T0, B0, Tint(LitSheen, 0.85f), 0.008f);
    }
}

