// Rotate a local specimen vector by XYZ Euler degrees (RotateEulerXYZ port)
[[nodiscard]] Vec3 RotateEulerDegrees(Vec3 Source, Vec3 EulerDegrees) noexcept
{
    const float Rx = EulerDegrees.X * Pi / 180.0f;
    const float Ry = EulerDegrees.Y * Pi / 180.0f;
    const float Rz = EulerDegrees.Z * Pi / 180.0f;

    const float Cx = std::cos(Rx), Sx = std::sin(Rx);
    const float Cy = std::cos(Ry), Sy = std::sin(Ry);
    const float Cz = std::cos(Rz), Sz = std::sin(Rz);

    const Vec3 AfterX{ Source.X, Source.Y * Cx - Source.Z * Sx, Source.Y * Sx + Source.Z * Cx };
    const Vec3 AfterY{ AfterX.X * Cy + AfterX.Z * Sy, AfterX.Y, -AfterX.X * Sy + AfterX.Z * Cy };
    return { AfterY.X * Cz - AfterY.Y * Sz, AfterY.X * Sz + AfterY.Y * Cz, AfterY.Z };
}

// Sculpted forearm + palm + five cupped fingers holding a chrome sphere (MoGraph hand specimen)
void BuildHandSpecimen(ReferenceAccumulator& Acc, Vec3 Origin, float Scale, Col4 SkinColor) noexcept
{
    struct HandSegment
    {
        Vec3  Start, Mid, End;
        float RadiusX0, RadiusX1, RadiusZ0, RadiusZ1;
        bool  Palm, Capped;
    };
    const std::array<HandSegment, 7u> Segments = {{
        { { 0.00f,  1.15f, -0.14f }, { 0.00f,  0.72f, -0.06f }, { 0.00f,  0.28f, -0.01f }, 0.273f, 0.234f, 0.205f, 0.136f, false, false },
        { { 0.00f,  0.30f, -0.01f }, { -0.01f, 0.00f,  0.03f }, { -0.01f, -0.34f,  0.05f }, 0.263f, 0.332f, 0.136f, 0.112f, true,  false },
        { { -0.22f, 0.04f,  0.04f }, { -0.44f, -0.36f, 0.14f }, { -0.33f, -0.82f,  0.25f }, 0.112f, 0.063f, 0.102f, 0.058f, false, true  },
        { { -0.21f, -0.30f, 0.04f }, { -0.26f, -0.66f, 0.17f }, { -0.18f, -0.94f,  0.26f }, 0.078f, 0.052f, 0.073f, 0.049f, false, true  },
        { { -0.05f, -0.33f, 0.04f }, { -0.06f, -0.72f, 0.16f }, { -0.02f, -0.95f,  0.23f }, 0.080f, 0.054f, 0.075f, 0.051f, false, true  },
        { { 0.11f,  -0.32f, 0.03f }, { 0.12f,  -0.68f, 0.13f }, { 0.12f,  -0.87f,  0.17f }, 0.074f, 0.050f, 0.069f, 0.047f, false, true  },
        { { 0.25f,  -0.28f, 0.01f }, { 0.28f,  -0.56f, 0.08f }, { 0.25f,  -0.74f,  0.12f }, 0.064f, 0.044f, 0.060f, 0.041f, false, true  },
    }};

    constexpr int RingCount = 8;
    constexpr int SideCount = 14;
    for (const HandSegment& Segment : Segments)
    {
        std::array<std::array<Vec3, SideCount>, RingCount + 1> Rings{};
        for (int Ring = 0; Ring <= RingCount; ++Ring)
        {
            const float T = static_cast<float>(Ring) / static_cast<float>(RingCount);
            const float IT = 1.0f - T;
            const Vec3 Centre{
                Segment.Start.X * IT * IT + Segment.Mid.X * 2.0f * IT * T + Segment.End.X * T * T,
                Segment.Start.Y * IT * IT + Segment.Mid.Y * 2.0f * IT * T + Segment.End.Y * T * T,
                Segment.Start.Z * IT * IT + Segment.Mid.Z * 2.0f * IT * T + Segment.End.Z * T * T,
            };
            const Vec3 Derivative{
                (Segment.Mid.X - Segment.Start.X) * 2.0f * IT + (Segment.End.X - Segment.Mid.X) * 2.0f * T,
                (Segment.Mid.Y - Segment.Start.Y) * 2.0f * IT + (Segment.End.Y - Segment.Mid.Y) * 2.0f * T,
                (Segment.Mid.Z - Segment.Start.Z) * 2.0f * IT + (Segment.End.Z - Segment.Mid.Z) * 2.0f * T,
            };
            const Vec3 Tangent = Normalize({ Derivative.X, Derivative.Y - 0.001f, Derivative.Z });
            const Vec3 UAxis = Normalize(Cross(Tangent, { 0.0f, 0.0f, 1.0f }));
            const Vec3 WAxis = Normalize(Cross(UAxis, Tangent));

            float RadiusX = Segment.Palm
                ? (0.254f + (0.342f - 0.254f) * std::sin(std::min(Pi, T * 2.2f)))
                : (Segment.RadiusX0 + (Segment.RadiusX1 - Segment.RadiusX0) * T);
            float RadiusZ = Segment.RadiusZ0 + (Segment.RadiusZ1 - Segment.RadiusZ0) * T;
            float CapLift = 0.0f;
            if (Segment.Capped && T > 0.88f)
            {
                const float CapAngle = ((T - 0.88f) / 0.12f) * 1.38f;
                RadiusX *= std::cos(CapAngle);
                RadiusZ *= std::cos(CapAngle);
                CapLift = std::sin(CapAngle) * Segment.RadiusX1;
            }
            for (int Side = 0; Side < SideCount; ++Side)
            {
                const float Phi = (static_cast<float>(Side) / static_cast<float>(SideCount)) * Pi * 2.0f;
                const float Cp = std::cos(Phi);
                const float Sp = std::sin(Phi);
                Rings[static_cast<std::size_t>(Ring)][static_cast<std::size_t>(Side)] = {
                    Origin.X + (Centre.X + Tangent.X * CapLift + UAxis.X * (RadiusX * Cp) + WAxis.X * (RadiusZ * Sp)) * Scale,
                    Origin.Y + (Centre.Y + Tangent.Y * CapLift + UAxis.Y * (RadiusX * Cp) + WAxis.Y * (RadiusZ * Sp)) * Scale,
                    Origin.Z + (Centre.Z + Tangent.Z * CapLift + UAxis.Z * (RadiusX * Cp) + WAxis.Z * (RadiusZ * Sp)) * Scale,
                };
            }
        }
        for (int Ring = 0; Ring < RingCount; ++Ring)
        {
            for (int Side = 0; Side < SideCount; ++Side)
            {
                const int NextSide = (Side + 1) % SideCount;
                Acc.AddTriangle(false, false, Rings[static_cast<std::size_t>(Ring)][static_cast<std::size_t>(Side)],
                                Rings[static_cast<std::size_t>(Ring)][static_cast<std::size_t>(NextSide)],
                                Rings[static_cast<std::size_t>(Ring + 1)][static_cast<std::size_t>(NextSide)], SkinColor, 0.0f, 0.25f);
                Acc.AddTriangle(false, false, Rings[static_cast<std::size_t>(Ring)][static_cast<std::size_t>(Side)],
                                Rings[static_cast<std::size_t>(Ring + 1)][static_cast<std::size_t>(NextSide)],
                                Rings[static_cast<std::size_t>(Ring + 1)][static_cast<std::size_t>(Side)], SkinColor, 0.0f, 0.25f);
            }
        }
    }

    // Glossy chrome sphere cradled by the downward-cupped obsidian fingers
    BuildElectrodeSphere(Acc, { Origin.X - 0.04f * Scale, Origin.Y - 0.64f * Scale, Origin.Z - 0.02f * Scale },
                         0.31f * Scale, { 0.36f, 0.41f, 0.48f, 0.99f }, { 0.88f, 0.94f, 1.0f, 0.72f }, true);
}

// Truncated-icosahedral Utah Teapot specimen: lathed body, S-curved spout and swept D-handle
void BuildTeapotSpecimen(ReferenceAccumulator& Acc, Vec3 Origin, float Scale, Vec3 EulerDegrees, Col4 BodyColor) noexcept
{
    auto EmitTriangle = [&](Vec3 A, Vec3 B, Vec3 C) noexcept
    {
        const Vec3 LocalA = RotateEulerDegrees(Mul(A, Scale * 0.972f), EulerDegrees);
        const Vec3 LocalB = RotateEulerDegrees(Mul(B, Scale * 0.972f), EulerDegrees);
        const Vec3 LocalC = RotateEulerDegrees(Mul(C, Scale * 0.972f), EulerDegrees);
        Acc.AddTriangle(false, false, Add(Origin, LocalA), Add(Origin, LocalB), Add(Origin, LocalC), BodyColor, 0.06f, 0.72f);
    };

    // Lathed silhouette body, lid and finial knob
    const std::array<std::array<float, 2u>, 15u> Body = {{
        { 0.00f, -0.58f }, { 0.46f, -0.58f }, { 0.58f, -0.45f }, { 0.76f, -0.18f }, { 0.78f, 0.08f },
        { 0.64f, 0.34f }, { 0.46f, 0.48f }, { 0.50f, 0.54f }, { 0.38f, 0.55f }, { 0.36f, 0.62f },
        { 0.14f, 0.69f }, { 0.06f, 0.72f }, { 0.11f, 0.80f }, { 0.08f, 0.87f }, { 0.00f, 0.89f },
    }};
    constexpr int LatheSegments = 26;
    for (std::size_t Ring = 0; Ring + 1u < Body.size(); ++Ring)
    {
        const float R0 = Body[Ring][0], Y0 = Body[Ring][1];
        const float R1 = Body[Ring + 1u][0], Y1 = Body[Ring + 1u][1];
        for (int Seg = 0; Seg < LatheSegments; ++Seg)
        {
            const float T0 = (static_cast<float>(Seg) / static_cast<float>(LatheSegments)) * Pi * 2.0f;
            const float T1 = (static_cast<float>(Seg + 1) / static_cast<float>(LatheSegments)) * Pi * 2.0f;
            const Vec3 A{ std::cos(T0) * R0, Y0, std::sin(T0) * R0 };
            const Vec3 B{ std::cos(T1) * R0, Y0, std::sin(T1) * R0 };
            const Vec3 C{ std::cos(T1) * R1, Y1, std::sin(T1) * R1 };
            const Vec3 D{ std::cos(T0) * R1, Y1, std::sin(T0) * R1 };
            EmitTriangle(A, B, C);
            EmitTriangle(A, C, D);
        }
    }

    // S-curved pouring spout on +X
    auto EmitTube = [&](const auto& CurveFn, int Steps, int Sides, const auto& RadiusFn, bool Paired) noexcept
    {
        std::array<Vec3, 40> Previous{};
        bool HasPrevious = false;
        for (int Step = 0; Step <= Steps; ++Step)
        {
            const float U = static_cast<float>(Step) / static_cast<float>(Steps);
            const Vec3 Centre = CurveFn(U);
            const Vec3 Next = CurveFn(std::min(1.0f, U + 0.01f));
            const Vec3 Tangent = Normalize(Sub(Next, Centre));
            const AxisBasis Basis = BasisFrom(Tangent);
            const float Radius = Paired ? RadiusFn(U) : RadiusFn(U);
            std::array<Vec3, 40> Ring{};
            for (int Side = 0; Side < Sides; ++Side)
            {
                const float Phi = (static_cast<float>(Side) / static_cast<float>(Sides)) * Pi * 2.0f;
                Ring[static_cast<std::size_t>(Side)] = Add(Centre, Add(Mul(Basis.Right, std::cos(Phi) * Radius), Mul(Basis.Up, std::sin(Phi) * Radius)));
            }
            if (HasPrevious)
            {
                for (int Side = 0; Side < Sides; ++Side)
                {
                    const int NextSide = (Side + 1) % Sides;
                    EmitTriangle(Previous[static_cast<std::size_t>(Side)], Previous[static_cast<std::size_t>(NextSide)], Ring[static_cast<std::size_t>(NextSide)]);
                    EmitTriangle(Previous[static_cast<std::size_t>(Side)], Ring[static_cast<std::size_t>(NextSide)], Ring[static_cast<std::size_t>(Side)]);
                }
            }
            Previous = Ring;
            HasPrevious = true;
        }
    };

    EmitTube([](float U) noexcept -> Vec3
    {
        const float X = 0.64f + U * 0.58f + std::sin(U * Pi) * 0.08f;
        const float Y = -0.22f + U * 0.78f - std::sin(U * Pi * 1.15f) * 0.14f;
        return { X, Y, 0.0f };
    }, 14, 10, [](float U) noexcept { return 0.16f * (1.0f - U * 0.56f); }, false);

    // Swept D-handle on -X
    EmitTube([](float U) noexcept -> Vec3
    {
        const float A = -Pi * 0.52f + U * Pi * 1.18f;
        const float X = -0.64f - std::cos(A) * 0.44f;
        const float Y = 0.06f + std::sin(A) * 0.42f;
        return { X, Y, 0.0f };
    }, 16, 10, [](float U) noexcept { return 0.072f - 0.020f * U; }, false);
}

// Levitated ferrofluid dish / crown base plus magnet pole beacon
void BuildFerrofluidBase(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 PoolColor,
    float Time) noexcept
{
    const Vec3  Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const bool  Dish   = (Parameters.FerroMode == 1);
    const float DishRadius = std::max(0.8f, Parameters.Radius);

    if (Dish)
    {
        constexpr int ShellSegments = 36;
        const float RimOuter = DishRadius * 1.07f;
        for (int Seg = 0; Seg < ShellSegments; ++Seg)
        {
            const float A0 = (static_cast<float>(Seg) / static_cast<float>(ShellSegments)) * Pi * 2.0f;
            const float A1 = (static_cast<float>(Seg + 1) / static_cast<float>(ShellSegments)) * Pi * 2.0f;
            const float Sheen = 0.5f + 0.5f * std::cos(A0 - 0.85f);
            const Col4 SheenPool{ 0.014f + 0.024f * Sheen, 0.018f + 0.032f * Sheen, 0.028f + 0.048f * Sheen, 0.99f };
            const Vec3 Centre{ Origin.X, Origin.Y + 0.018f, Origin.Z };
            const Vec3 Inner0{ Origin.X + std::cos(A0) * DishRadius, Origin.Y + 0.014f, Origin.Z + std::sin(A0) * DishRadius };
            const Vec3 Inner1{ Origin.X + std::cos(A1) * DishRadius, Origin.Y + 0.014f, Origin.Z + std::sin(A1) * DishRadius };
            Acc.AddTriangle(false, false, Centre, Inner0, Inner1, SheenPool, 0.0f, 0.95f);

            const Col4 SheenRim{ 0.24f + 0.22f * Sheen, 0.27f + 0.24f * Sheen, 0.32f + 0.26f * Sheen, 0.98f };
            const Vec3 Outer0{ Origin.X + std::cos(A0) * RimOuter, Origin.Y + 0.056f, Origin.Z + std::sin(A0) * RimOuter };
            const Vec3 Outer1{ Origin.X + std::cos(A1) * RimOuter, Origin.Y + 0.056f, Origin.Z + std::sin(A1) * RimOuter };
            Acc.AddQuad(false, false, Inner0, Outer0, Outer1, Inner1, SheenRim, 0.0f, 0.92f);
        }
        Acc.AddRingXZ({ Origin.X, Origin.Y + 0.058f, Origin.Z }, RimOuter, 36, { 0.76f, 0.84f, 0.94f, 0.72f }, 0.012f);

        // Rosensweig instability: the reference pool is covered in a regular hexagonal array of sharp
        // magnetic cusps, tallest at the centre and tapering toward the dish rim.
        constexpr int CuspRings = 5;
        for (int Ring = 0; Ring < CuspRings; ++Ring)
        {
            const float RingU = static_cast<float>(Ring) / static_cast<float>(CuspRings);
            const float RingR = DishRadius * (0.10f + 0.78f * RingU);
            const int   Count = std::max(1, static_cast<int>(6.0f * static_cast<float>(Ring)));
            for (int Cusp = 0; Cusp < Count; ++Cusp)
            {
                const float Az = (static_cast<float>(Cusp) + 0.5f * static_cast<float>(Ring % 2)) * (Pi * 2.0f / static_cast<float>(Count));
                const float CuspX = Origin.X + std::cos(Az) * RingR;
                const float CuspZ = Origin.Z + std::sin(Az) * RingR;
                const float Seed  = static_cast<float>(Ring * 37 + Cusp) * 13.0f + 5.0f;
                const float Taper = 1.0f - 0.55f * RingU;
                const float CuspH = DishRadius * (0.30f + 0.26f * Hash01(Seed, 1.0f)) * Taper;
                const float BaseR = DishRadius * (0.052f + 0.020f * Hash01(Seed, 2.0f)) * Taper;
                const Vec3  CuspBase{ CuspX, Origin.Y + 0.020f, CuspZ };
                const Vec3  CuspTip { CuspX + (Hash01(Seed, 3.0f) - 0.5f) * BaseR * 0.9f,
                                      Origin.Y + 0.020f + CuspH,
                                      CuspZ + (Hash01(Seed, 4.0f) - 0.5f) * BaseR * 0.9f };
                Acc.AddCylinder(CuspBase, CuspTip, BaseR, BaseR * 0.10f, 8, { 0.020f, 0.026f, 0.038f, 0.99f }, 0.85f);
                Acc.AddSphere(CuspTip, BaseR * 0.16f, { 0.42f, 0.56f, 0.72f, 0.95f }, 0.60f, 5, 8, false, 0.35f);
            }
        }
        (void)PoolColor;
    }
    else
    {
        Acc.AddSphere(Origin, DishRadius * 0.62f, { 0.015f, 0.020f, 0.030f, 0.99f }, 0.95f, 16, 28, false, 0.0f);
    }

    // Magnet pole beacon orbiting the vessel rim
    const float OrbitPhase = Time * std::max(0.2f, 1.35f);
    const Vec3 Magnet{ Origin.X + std::cos(OrbitPhase) * DishRadius * 0.55f,
                       Origin.Y + (Dish ? 0.34f : 0.10f) + 0.22f * std::sin(OrbitPhase * 1.7f),
                       Origin.Z + std::sin(OrbitPhase) * DishRadius * 0.55f };
    BuildElectrodeSphere(Acc, Magnet, 0.17f, { 0.72f, 0.78f, 0.86f, 0.98f }, { 0.55f, 0.72f, 0.94f, 0.55f }, false);
}

