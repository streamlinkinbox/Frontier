// Exact port of EvalDynStrandCPU anchor geometry (dynMode 1..9) evaluated once per strand slot
struct StrandSpan
{
    bool  Visible    = false;
    Vec3  Start      { 0.0f, 0.0f, 0.0f };
    Vec3  End        { 0.0f, 0.0f, 0.0f };
    float Sag        = 0.0f;   // [m] - Catenary belly depth
    float HalfWidth  = 0.012f; // [m] - Silk / stalk radius
    std::string_view Role{};
};

[[nodiscard]] StrandSpan EvaluateStrandSpan(const ReferencePresetParameters& Parameters, int Slot, int Capacity) noexcept
{
    const Vec3      Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const float     Height = std::max(0.35f, Parameters.DynHeight);
    const float     Sag    = Parameters.DynSag;
    const int       Rows   = std::max(4, Parameters.DynRows);
    const int       Mode   = std::clamp(Parameters.DynMode, 1, 9);
    const std::array<float, 3u> Ext = {
        std::max(0.5f, Parameters.BoxX),
        std::max(0.5f, Parameters.BoxY),
        std::max(0.5f, Parameters.BoxZ),
    };
    StrandSpan Span{};

    if (Mode == 1)
    {
        // Three tiers of catenary suspension cables strung between stanchions
        const int Strands = std::min(Capacity, std::max(12, Rows * 2));
        if (Slot >= Strands)
        {
            return Span;
        }
        const int   Tier = Slot % 3;
        const float Lane = static_cast<float>(Slot / 3) / static_cast<float>(std::max(1, Strands / 3 - 1));
        const float TierY = Origin.Y + Height * (0.56f + 0.19f * static_cast<float>(Tier));
        const float ZOff  = (-Ext[2] + 2.0f * Ext[2] * Lane) + (Hash01(static_cast<float>(Slot * 41 + 19), 1.0f) - 0.5f) * 0.22f;
        const float XJit  = (Hash01(static_cast<float>(Slot * 41 + 19), 2.0f) - 0.5f) * 0.18f;
        Span.Visible   = true;
        Span.Start     = { Origin.X - Ext[0] + XJit, TierY, Origin.Z + ZOff };
        Span.End       = { Origin.X + Ext[0] - XJit,
                           TierY + (Hash01(static_cast<float>(Slot * 41 + 19), 3.0f) - 0.5f) * 0.18f,
                           Origin.Z + ZOff + (Hash01(static_cast<float>(Slot * 41 + 19), 4.0f) - 0.5f) * 0.16f };
        // The reference rig hangs in deep catenary bowls that drop well below the stanchion tops, so the
        // sag is anchored to the mast height rather than to the small authored sag value alone.
        Span.Sag       = (Sag * 0.55f + Height * 0.42f) * (0.72f + 0.46f * Hash01(static_cast<float>(Slot * 41 + 19), 5.0f));
        Span.HalfWidth = Parameters.SizeStart * (Parameters.DynSub > 0 ? 1.3f : 1.0f) * 0.55f;
        Span.Role      = "cable";
        return Span;
    }
    if (Mode == 2)
    {
        // Hanging vine stipes with offset leaf blades
        const int Vines = std::min(Capacity / 2, std::max(8, Rows));
        if (Slot < Vines)
        {
            const float Seed  = static_cast<float>(Slot) * 41.0f + 19.0f;
            const float UX    = Hash01(Seed, 1.0f) * 2.0f - 1.0f;
            const float UZ    = Hash01(Seed, 2.0f) * 2.0f - 1.0f;
            const float TopY  = Origin.Y + Height * (0.86f + 0.18f * Hash01(Seed, 3.0f));
            const float Len   = std::max(0.75f, std::min(std::max(0.95f, TopY - 0.25f), Sag * (0.62f + 0.53f * Hash01(Seed, 4.0f))));
            Span.Visible   = true;
            Span.Start     = { Origin.X + UX * Ext[0], TopY, Origin.Z + UZ * Ext[2] };
            Span.End       = { Span.Start.X + (Hash01(Seed, 5.0f) - 0.5f) * 0.28f,
                               std::max(0.25f, Span.Start.Y - Len),
                               Span.Start.Z + (Hash01(Seed, 6.0f) - 0.5f) * 0.28f };
            Span.Sag       = Sag * 0.04f;
            Span.HalfWidth = Parameters.SizeStart * 0.5f;
            Span.Role      = "vine";
            return Span;
        }
        const int   LeafIndex = Slot - Vines;
        const int   VineIndex = LeafIndex % std::max(1, Vines);
        const float Seed      = static_cast<float>(VineIndex) * 41.0f + 19.0f;
        const float TopY      = Origin.Y + Height * (0.86f + 0.18f * Hash01(Seed, 3.0f));
        const float TopLen    = std::max(0.75f, std::min(std::max(0.95f, TopY - 0.25f), Sag * (0.62f + 0.53f * Hash01(Seed, 4.0f))));
        const Vec3  VineTop{ Origin.X + (Hash01(Seed, 1.0f) * 2.0f - 1.0f) * Ext[0], TopY, Origin.Z + (Hash01(Seed, 2.0f) * 2.0f - 1.0f) * Ext[2] };
        const Vec3  VineTip{ VineTop.X + (Hash01(Seed, 5.0f) - 0.5f) * 0.28f, std::max(0.25f, VineTop.Y - TopLen), VineTop.Z + (Hash01(Seed, 6.0f) - 0.5f) * 0.28f };
        const float UPin      = 0.14f + 0.80f * Hash01(static_cast<float>(Slot * 31 + 3), 2.0f);
        const float OffAngle  = Hash01(static_cast<float>(Slot * 31), 4.0f) * Pi * 2.0f;
        const Vec3  Anchor    = Lerp(VineTop, VineTip, UPin);
        const float LeafLen   = 0.20f + 0.12f * Hash01(static_cast<float>(Slot * 31), 5.0f);
        Span.Visible   = true;
        Span.Start     = Anchor;
        Span.End       = { Anchor.X + std::cos(OffAngle) * LeafLen, Anchor.Y - LeafLen * 0.55f, Anchor.Z + std::sin(OffAngle) * LeafLen };
        Span.Sag       = LeafLen * 0.30f;
        Span.HalfWidth = Parameters.SizeStart * 1.30f;
        Span.Role      = "leaf";
        return Span;
    }
    if (Mode == 3)
    {
        // Cloth banners (sub 0) and square-rigged sails (sub 1)
        const int RowsClamped = std::clamp(Rows, 10, 44);
        if (Slot >= std::min(Capacity, RowsClamped))
        {
            return Span;
        }
        const float RowV = (RowsClamped > 1) ? static_cast<float>(Slot) / static_cast<float>(RowsClamped - 1) : 0.5f;
        const float TopY = Origin.Y + Height;
        Span.Visible = true;
        if (Parameters.DynSub < 0.5f)
        {
            const float MastX = Origin.X - Ext[0];
            const float FlagH = std::max(0.65f, Ext[1] * 1.75f);
            const float RowY  = std::max(0.35f, TopY - FlagH) + (TopY - std::max(0.35f, TopY - FlagH)) * RowV;
            const float DirLen = std::max(1.0e-4f, std::hypot(Parameters.DirX, Parameters.DirZ));
            const float DirX  = Parameters.DirX / DirLen;
            const float DirZ  = Parameters.DirZ / DirLen;
            const float FlagLen = std::max(0.8f, Ext[0] * 2.0f);
            Span.Start     = { MastX, RowY, Origin.Z };
            Span.End       = { MastX + DirX * FlagLen, RowY, Origin.Z + DirZ * FlagLen };
            Span.Sag       = std::max(0.02f, Sag * 0.28f);
            Span.HalfWidth = (FlagH / static_cast<float>(std::max(1, RowsClamped - 1))) * 0.60f;
            Span.Role      = "banner";
        }
        else
        {
            const float SailH  = std::max(0.8f, Ext[1] * 1.85f);
            const float RowY   = std::max(0.45f, TopY - SailH) + (TopY - std::max(0.45f, TopY - SailH)) * RowV;
            const float HalfW  = Ext[0] * (1.06f - 0.16f * RowV);
            Span.Start     = { Origin.X - HalfW, RowY, Origin.Z };
            Span.End       = { Origin.X + HalfW, RowY, Origin.Z };
            Span.Sag       = -Sag * std::sin(RowV * Pi);
            Span.HalfWidth = (SailH / static_cast<float>(std::max(1, RowsClamped - 1))) * 0.60f;
            Span.Role      = "sail";
        }
        return Span;
    }
    if (Mode == 4 || Mode == 5)
    {
        const int Limit = (Mode == 4) ? std::max(24, std::min(Capacity, Parameters.GridRows * 6)) : std::max(20, std::min(Capacity, Parameters.GridRows * 5));
        const int BladeLimit = (Mode == 4) ? std::clamp(Parameters.WebSpokes * 14, 24, 210) : std::clamp(Parameters.WebSpokes * 12, 20, 180);
        if (Slot >= std::min(Limit == 0 ? BladeLimit : Limit, BladeLimit))
        {
            return Span;
        }
        const float Seed = static_cast<float>(Slot) * 41.0f + 17.0f;
        const float Ax   = (Hash01(Seed, 1.0f) * 2.0f - 1.0f) * Ext[0];
        const float Az   = (Hash01(Seed, 2.0f) * 2.0f - 1.0f) * Ext[2];
        const float BladeH = Height * (0.62f + 0.58f * Hash01(Seed, 3.0f));
        const float LeanSpread = (Mode == 5) ? 0.28f : 0.45f;
        const float Lean   = (Hash01(Seed, 4.0f) - 0.5f) * LeanSpread * BladeH;
        const float LeanZ  = (Hash01(Seed, 5.0f) - 0.5f) * LeanSpread * BladeH;
        const float Bend   = (Mode == 4) ? (0.18f + 0.14f * Hash01(Seed, 6.0f)) : 0.05f;
        Span.Visible   = true;
        Span.Start     = { Origin.X + Ax, std::max(0.0f, Origin.Y), Origin.Z + Az };
        Span.End       = { Span.Start.X + Lean, Span.Start.Y + BladeH * (1.0f - Bend * 0.35f), Span.Start.Z + LeanZ };
        Span.Sag       = (Mode == 4) ? -std::max(0.03f, Sag * 0.35f) * BladeH : -std::max(0.08f, Sag * 0.40f) * BladeH;
        Span.HalfWidth = Parameters.SizeStart * (0.75f + 0.55f * Hash01(Seed, 7.0f)) * 0.55f;
        Span.Role      = (Mode == 4) ? "wheat" : "reed";
        return Span;
    }
    if (Mode == 6)
    {
        // Radiating fern frond rosette
        const int Fronds = std::min(Capacity, std::max(10, Rows));
        if (Slot >= Fronds)
        {
            return Span;
        }
        const int   Ring  = (Slot < static_cast<int>(static_cast<float>(Fronds) * 0.35f)) ? 0 : ((Slot < static_cast<int>(static_cast<float>(Fronds) * 0.72f)) ? 1 : 2);
        const float Az    = (static_cast<float>(Slot) / static_cast<float>(Fronds)) * Pi * 2.0f + Hash01(static_cast<float>(Slot * 29), 1.0f) * 0.22f;
        const float Elev  = (Ring == 0) ? 1.05f : ((Ring == 1) ? 0.62f : 0.28f);
        const float FrondLen = Height * ((Ring == 0) ? 0.78f : ((Ring == 1) ? 1.05f : 1.18f)) * (0.85f + 0.28f * Hash01(static_cast<float>(Slot * 29), 2.0f));
        const float Clump = (static_cast<float>(Slot % 3) - 1.0f) * 0.12f;
        const float RadR  = std::cos(Elev) * FrondLen;
        const float TopY  = std::sin(Elev) * FrondLen;
        Span.Visible   = true;
        Span.Start     = { Origin.X + Clump, std::max(0.05f, Origin.Y), Origin.Z + (Hash01(static_cast<float>(Slot * 29), 3.0f) - 0.5f) * 0.14f };
        Span.End       = { Span.Start.X + std::cos(Az) * RadR,
                           std::max(0.18f, Span.Start.Y + TopY - Sag * FrondLen * 0.18f),
                           Span.Start.Z + std::sin(Az) * RadR };
        Span.Sag       = -Sag * FrondLen * 0.32f;
        Span.HalfWidth = Parameters.SizeStart * (0.85f + 0.30f * Hash01(static_cast<float>(Slot * 29), 4.0f)) * 0.34f;
        Span.Role      = "frond";
        return Span;
    }
    if (Mode == 7)
    {
        // Trunk, branching limbs and canopy leaf clusters
        const int Limbs = std::clamp(Rows, 8, 28);
        const Vec3 TrunkBase{ Origin.X, std::max(0.0f, Origin.Y), Origin.Z };
        const Vec3 TrunkTop{ Origin.X + 0.08f, TrunkBase.Y + Height * 0.62f, Origin.Z - 0.05f };
        Span.Visible = true;
        if (Slot == 0)
        {
            Span.Start     = TrunkBase;
            Span.End       = TrunkTop;
            Span.Sag       = 0.04f;
            Span.HalfWidth = std::max(0.14f, Parameters.SizeStart * 1.4f) * 0.5f;
            Span.Role      = "trunk";
            return Span;
        }
        if (Slot <= Limbs)
        {
            const int   LimbIndex = Slot - 1;
            const float Tier      = static_cast<float>(LimbIndex) / static_cast<float>(std::max(1, Limbs - 1));
            const float Az        = static_cast<float>(LimbIndex) * 2.39996f + Hash01(static_cast<float>(Slot * 37), 1.0f) * 0.35f;
            const float AnchorU   = 0.42f + 0.56f * Tier;
            const Vec3  Anchor    = Lerp(TrunkBase, TrunkTop, AnchorU);
            const float Reach     = Height * (0.58f - 0.24f * Tier) * (0.82f + 0.35f * Hash01(static_cast<float>(Slot * 37), 2.0f));
            const float Lift      = Height * (0.18f + 0.34f * Tier);
            Span.Start     = Anchor;
            Span.End       = { Anchor.X + std::cos(Az) * Reach, Anchor.Y + Lift, Anchor.Z + std::sin(Az) * Reach };
            Span.Sag       = -std::max(0.04f, Sag * 0.35f) * Reach;
            Span.HalfWidth = std::max(0.032f, Parameters.SizeStart * (0.55f - 0.28f * Tier)) * 0.5f;
            Span.Role      = "limb";
            return Span;
        }
        const int   LeafIndex = Slot - 1 - Limbs;
        const int   LimbSlot  = 1 + (LeafIndex % Limbs);
        const float Tier      = static_cast<float>(LimbSlot - 1) / static_cast<float>(std::max(1, Limbs - 1));
        const float Az        = static_cast<float>(LimbSlot - 1) * 2.39996f + Hash01(static_cast<float>(LimbSlot * 37), 1.0f) * 0.35f;
        const float AnchorU   = 0.42f + 0.56f * Tier;
        const Vec3  Anchor    = Lerp(TrunkBase, TrunkTop, AnchorU);
        const float Reach     = Height * (0.58f - 0.24f * Tier) * (0.82f + 0.35f * Hash01(static_cast<float>(LimbSlot * 37), 2.0f));
        const float Lift      = Height * (0.18f + 0.34f * Tier);
        const Vec3  LimbTip   = { Anchor.X + std::cos(Az) * Reach, Anchor.Y + Lift, Anchor.Z + std::sin(Az) * Reach };
        const float BranchU   = 0.38f + 0.62f * Hash01(static_cast<float>(Slot * 43), 1.0f);
        const float OffAngle  = Hash01(static_cast<float>(Slot * 43), 2.0f) * Pi * 2.0f;
        const float OffRadius = 0.18f + 0.55f * Hash01(static_cast<float>(Slot * 43), 3.0f);
        const float OffLift   = (Hash01(static_cast<float>(Slot * 43), 4.0f) - 0.32f) * 0.52f;
        const Vec3  LeafBase  = Lerp(Anchor, LimbTip, BranchU);
        Span.Start     = LeafBase;
        Span.End       = { LeafBase.X + std::cos(OffAngle) * OffRadius, LeafBase.Y + OffLift - OffRadius * 0.35f, LeafBase.Z + std::sin(OffAngle) * OffRadius };
        Span.Sag       = OffRadius * 0.25f;
        Span.HalfWidth = std::max(0.055f, Parameters.SizeStart * (0.34f + 0.22f * Hash01(static_cast<float>(Slot * 43), 5.0f))) * 0.5f;
        Span.Role      = "leaf";
        return Span;
    }
    if (Mode == 8)
    {
        // Kelp forest: tall stalks plus offset blades
        const int Stalks = std::max(10, std::min(Rows, Capacity / 2));
        const int StalkIndex = Slot % Stalks;
        const bool Side      = Slot >= Stalks;
        const float Seed     = static_cast<float>(StalkIndex) * 41.0f + 19.0f;
        const float Gx       = (Hash01(Seed, 1.0f) * 2.0f - 1.0f) * Ext[0];
        const float Gz       = (Hash01(Seed, 2.0f) * 2.0f - 1.0f) * Ext[2];
        const float KelpHeight = Height * (0.62f + 0.46f * Hash01(Seed, 3.0f));
        Span.Visible = true;
        if (!Side)
        {
            const float LeanX = (Hash01(Seed, 4.0f) - 0.5f) * 0.25f;
            const float LeanZ = (Hash01(Seed, 5.0f) - 0.5f) * 0.25f;
            Span.Start     = { Origin.X + Gx, std::max(0.02f, Origin.Y), Origin.Z + Gz };
            Span.End       = { Span.Start.X + LeanX, KelpHeight, Span.Start.Z + LeanZ };
            Span.Sag       = -Sag * 0.30f;
            Span.HalfWidth = Parameters.SizeStart * (Parameters.DynSub > 0 ? 1.35f : 1.05f);
            Span.Role      = "kelp";
            return Span;
        }
        const float BladeU   = 0.24f + 0.70f * Hash01(static_cast<float>(Slot * 23), 7.0f);
        const float BladeAz  = Hash01(static_cast<float>(Slot * 23), 8.0f) * Pi * 2.0f;
        const float BladeLen = 0.34f + 0.36f * Hash01(static_cast<float>(Slot * 23), 9.0f);
        Span.Start     = { Origin.X + Gx, std::max(0.08f, Origin.Y + KelpHeight * BladeU), Origin.Z + Gz };
        Span.End       = { Span.Start.X + std::cos(BladeAz) * BladeLen, Span.Start.Y + BladeLen * 0.4f, Span.Start.Z + std::sin(BladeAz) * BladeLen };
        Span.Sag       = -0.08f;
        Span.HalfWidth = Parameters.SizeStart * 1.25f;
        Span.Role      = "blade";
        return Span;
    }

    // Mode 9: sea anemone tentacle crowns
    const int Tentacles = std::max(18, std::min(Capacity, Rows * 3));
    if (Slot >= Tentacles)
    {
        return Span;
    }
    const int   Cluster = Slot % 3;
    const float ClusterPhi = static_cast<float>(Cluster) * 2.0943951f + 0.4f;
    const float ClusterRadius = (Cluster == 0) ? 0.0f : 0.55f * std::max(0.4f, Parameters.Radius);
    const float MX = Origin.X + std::cos(ClusterPhi) * ClusterRadius;
    const float MY = Origin.Y + 0.08f;
    const float MZ = Origin.Z + std::sin(ClusterPhi) * ClusterRadius;
    const float RingRadius = 0.05f + std::sqrt(Hash01(static_cast<float>(Slot * 31), 1.0f)) * ((Cluster == 0) ? 0.34f : 0.24f) * std::max(0.6f, Parameters.Radius * 0.65f);
    const float Az         = static_cast<float>(Slot) * 2.3999632f + Hash01(static_cast<float>(Slot * 31), 2.0f) * 0.4f;
    const float TentacleLen = Height * (0.65f + 0.48f * Hash01(static_cast<float>(Slot * 31), 3.0f));
    const float Flare      = RingRadius * 1.45f + 0.42f * TentacleLen;
    Span.Visible   = true;
    Span.Start     = { MX + std::cos(Az) * RingRadius, MY + 0.06f + (0.28f - std::min(RingRadius, 0.25f)) * 0.5f, MZ + std::sin(Az) * RingRadius };
    Span.End       = { MX + std::cos(Az) * Flare, MY + TentacleLen, MZ + std::sin(Az) * Flare };
    Span.Sag       = -std::max(0.14f, Sag * 0.65f);
    Span.HalfWidth = Parameters.SizeStart * 0.92f * std::max(0.1f, 1.0f) * 0.42f;
    Span.Role      = "tentacle";
    return Span;
}

// Rigging strand rendering: textiles, cables, vines, botanical blades and canopy clusters
void BuildRiggingStrands(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 PrimaryColor,
    Col4 AccentColor,
    Col4 HighlightColor,
    float Time,
    float Thickness) noexcept
{
    const int Mode = std::clamp(Parameters.DynMode, 1, 9);
    const int Capacity = 512;
    for (int Slot = 0; Slot < Capacity; ++Slot)
    {
        const StrandSpan Span = EvaluateStrandSpan(Parameters, Slot, Capacity);
        if (!Span.Visible)
        {
            continue;
        }
        const Vec3 SwayTip = Add(Span.End, SilkSway(Span.End, Time, 0.90f / std::max(0.2f, Parameters.DynStiff), Parameters.WindCoupling, Parameters.CurlAmp, Parameters.CurlFreq));
        const Vec3 FixedStart = Span.Start;

        // Textile rows render as thin cloth ribbons; stalks render as tapered round segments
        const bool ClothRow = (Mode == 3);
        const Col4 RowColor = ClothRow ? Tint(PrimaryColor, 0.95f) : PrimaryColor;

        if (ClothRow)
        {
            // Textile rows read as a cloth sheet, so the ribbon spans the whole row height (adjacent rows
            // overlap into fabric) and carries the authored primary -> highlight gradient the reference shows.
            const Vec3 SpanVector = Sub(SwayTip, FixedStart);
            const Vec3 RibbonRight = Normalize(Cross(SpanVector, { 0.0f, 0.0f, 1.0f }));
            const float RowV = static_cast<float>(Slot) / static_cast<float>(std::max(1, Parameters.DynRows - 1));
            const Col4 FabricTop = LiftAlbedo(PrimaryColor, 0.26f);
            const Col4 FabricBottom = LiftAlbedo(HighlightColor, 0.20f);
            const Col4 Fabric = {
                FabricTop[0] + (FabricBottom[0] - FabricTop[0]) * RowV,
                FabricTop[1] + (FabricBottom[1] - FabricTop[1]) * RowV,
                FabricTop[2] + (FabricBottom[2] - FabricTop[2]) * RowV,
                FabricTop[3],
            };
            // Billow: the free edge of the cloth bows out of the sheet plane like folded fabric.
            const Vec3 Billow = Mul(Normalize(Cross({ 0.0f, 1.0f, 0.0f }, SpanVector)), std::sin(RowV * Pi) * Parameters.DynSag * 0.55f);
            const Vec3 FreeMid = Add(Lerp(FixedStart, SwayTip, 0.62f), Billow);
            const float W0 = Span.HalfWidth * 1.55f;
            const float W1 = Span.HalfWidth * 1.42f;
            const Vec3 A0 = Sub(FixedStart, Mul(RibbonRight, W0));
            const Vec3 A1 = Add(FixedStart, Mul(RibbonRight, W0));
            const Vec3 M0 = Sub(FreeMid, Mul(RibbonRight, (W0 + W1) * 0.5f));
            const Vec3 M1 = Add(FreeMid, Mul(RibbonRight, (W0 + W1) * 0.5f));
            const Vec3 B0 = Sub(SwayTip, Mul(RibbonRight, W1));
            const Vec3 B1 = Add(SwayTip, Mul(RibbonRight, W1));
            Acc.AddQuad(false, true, A0, A1, M1, M0, Fabric, 0.0f, 0.04f);
            Acc.AddQuad(false, true, M0, M1, B1, B0, Tint(Fabric, 0.92f), 0.0f, 0.04f);
            Acc.AddLine(A0, M0, Tint(AccentColor, 0.85f), Thickness * 0.55f);
            Acc.AddLine(A1, M1, Tint(AccentColor, 0.85f), Thickness * 0.55f);
        }
        else
        {
            const Col4 TipColor = (Span.Role == "leaf") ? AccentColor : Tint(PrimaryColor, 0.9f);
            AddSaggingSpan(Acc, FixedStart, SwayTip, Span.Sag, 8, RowColor, TipColor, std::max(Thickness, Span.HalfWidth), false, 0.0f);
        }

        // Botany accents: wheat ears, seed heads, canopy leaf clusters, kelp bladders
        if (Span.Role == "wheat")
        {
            const Vec3 Ear = Lerp(FixedStart, SwayTip, 0.62f);
            for (int Kernel = 0; Kernel < 5; ++Kernel)
            {
                const float U = 0.62f + static_cast<float>(Kernel) * 0.075f;
                const Vec3 Point = Lerp(FixedStart, SwayTip, U);
                Acc.AddRingXZ(Point, 0.045f, 6, HighlightColor, Thickness * 0.85f, false, 0.0f);
            }
            Acc.AddRingXZ(Ear, 0.05f, 6, HighlightColor, Thickness, false, 0.0f);
        }
        else if (Span.Role == "leaf")
        {
            Acc.AddTriangle(false, true, FixedStart, SwayTip, Add(Lerp(FixedStart, SwayTip, 0.5f), { 0.0f, 0.0f, Span.HalfWidth * 2.6f }), Tint(AccentColor, 0.92f));
        }
        else if (Span.Role == "kelp" || Span.Role == "blade")
        {
            // Macro-algae fronds read as flat blades, so each strand renders as a tapering ribbon with a
            // veined mid-rib highlight instead of a round tube.
            const Vec3 SpanVector = Sub(SwayTip, FixedStart);
            const Vec3 FrondRight = Normalize(Cross(SpanVector, { 0.0f, 0.0f, 1.0f }));
            const Vec3 Mid = Lerp(FixedStart, SwayTip, 0.55f);
            const float W0 = Span.HalfWidth * 0.55f;
            const float W1 = Span.HalfWidth * 1.15f;
            const float W2 = Span.HalfWidth * 0.42f;
            const Vec3 A0 = Sub(FixedStart, Mul(FrondRight, W0));
            const Vec3 A1 = Add(FixedStart, Mul(FrondRight, W0));
            const Vec3 M0 = Sub(Mid, Mul(FrondRight, W1));
            const Vec3 M1 = Add(Mid, Mul(FrondRight, W1));
            const Vec3 B0 = Sub(SwayTip, Mul(FrondRight, W2));
            const Vec3 B1 = Add(SwayTip, Mul(FrondRight, W2));
            // Macro-algae fronds keep the authored green body colour; amber is reserved for the air bladders.
            const Col4 FrondColor = Tint(PrimaryColor, (Span.Role == "kelp") ? 1.0f : 0.94f);
            Acc.AddQuad(false, true, A0, A1, M1, M0, FrondColor, 0.0f, 0.02f);
            Acc.AddQuad(false, true, M0, M1, B1, B0, Tint(FrondColor, 0.88f), 0.0f, 0.02f);
            Acc.AddLine(FixedStart, SwayTip, Tint(HighlightColor, 0.90f), Thickness * 0.45f);
        }
        else if (Span.Role == "tentacle")
        {
            Acc.AddRingXZ(SwayTip, 0.045f, 6, HighlightColor, Thickness * 1.1f, false, 0.0f);
        }
    }
}

