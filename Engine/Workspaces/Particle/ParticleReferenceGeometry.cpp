void BuildMoGraphSpecimen(
    ReferenceAccumulator& Acc,
    const ReferencePresetParameters& Parameters,
    Col4 BaseColor,
    Col4 AccentColor) noexcept
{
    const Vec3 Origin{ Parameters.OriginX, Parameters.OriginY, Parameters.OriginZ };
    const float ExtX = std::max(0.35f, Parameters.BoxX);
    const float ExtY = std::max(0.35f, Parameters.BoxY);
    const float ExtZ = std::max(0.35f, Parameters.BoxZ);
    const float Scale = std::max(0.35f, Parameters.Radius);
    const int   Surface = std::clamp(Parameters.GridSurface, 0, 16);
    const Col4  SlateColor{ 0.038f, 0.042f, 0.050f, 0.92f };

    if (Surface >= 6)
    {
        // Placeable specimen: Utah Teapot surfacing with a chrome mirror finish
        BuildTeapotSpecimen(Acc, Origin, Scale, { 0.0f, -28.0f, 0.0f }, { 0.68f, 0.60f, 0.32f, 0.98f });
        return;
    }
    if (Surface == 2)
    {
        Acc.AddSphere(Origin, Scale * 0.985f, { 0.042f, 0.048f, 0.058f, 0.99f }, 0.92f, 18, 30, false, 0.0f);
        Acc.AddRingXZ(Origin, Scale * 1.0f, 48, Tint(AccentColor, 0.42f), 0.010f);
        return;
    }
    if (Surface == 3)
    {
        BuildHandSpecimen(Acc, Origin, Scale, { 0.042f, 0.045f, 0.054f, 0.99f });
        return;
    }
    if (Surface == 4)
    {
        // Horizontal hex torus ring
        constexpr int SegU = 28;
        constexpr int SegV = 14;
        const float MajorRadius = Scale;
        const float MinorRadius = MajorRadius * 0.365f;
        const Col4 TorusColor{ 0.045f, 0.050f, 0.060f, 0.98f };
        for (int Iu = 0; Iu < SegU; ++Iu)
        {
            const float Phi0 = (static_cast<float>(Iu) / static_cast<float>(SegU)) * Pi * 2.0f;
            const float Phi1 = (static_cast<float>(Iu + 1) / static_cast<float>(SegU)) * Pi * 2.0f;
            for (int Iv = 0; Iv < SegV; ++Iv)
            {
                const float Theta0 = (static_cast<float>(Iv) / static_cast<float>(SegV)) * Pi * 2.0f;
                const float Theta1 = (static_cast<float>(Iv + 1) / static_cast<float>(SegV)) * Pi * 2.0f;
                const auto TorusPoint = [&](float Phi, float Theta) noexcept -> Vec3
                {
                    const float Radius = MajorRadius + MinorRadius * std::cos(Theta);
                    return { Origin.X + std::cos(Phi) * Radius, Origin.Y + std::sin(Theta) * MinorRadius, Origin.Z + std::sin(Phi) * Radius };
                };
                const Vec3 A = TorusPoint(Phi0, Theta0);
                const Vec3 B = TorusPoint(Phi1, Theta0);
                const Vec3 C = TorusPoint(Phi1, Theta1);
                const Vec3 D = TorusPoint(Phi0, Theta1);
                Acc.AddQuad(false, false, A, B, C, D, TorusColor, 0.0f, 0.86f);
            }
        }
        return;
    }
    if (Surface == 0)
    {
        // XZ floor matrix plate
        const float Y0 = Origin.Y - 0.012f;
        Acc.AddQuad(false, true, { Origin.X - ExtX, Y0, Origin.Z - ExtZ }, { Origin.X + ExtX, Y0, Origin.Z - ExtZ },
                    { Origin.X + ExtX, Y0, Origin.Z + ExtZ }, { Origin.X - ExtX, Y0, Origin.Z + ExtZ }, SlateColor, 0.0f, 0.20f);
        return;
    }
    if (Surface == 1)
    {
        // XY wall matrix plate
        const float Z0 = Origin.Z - 0.015f;
        Acc.AddQuad(false, true, { Origin.X - ExtX, Origin.Y - ExtY, Z0 }, { Origin.X + ExtX, Origin.Y - ExtY, Z0 },
                    { Origin.X + ExtX, Origin.Y + ExtY, Z0 }, { Origin.X - ExtX, Origin.Y + ExtY, Z0 }, SlateColor, 0.0f, 0.20f);
        return;
    }

    (void)BaseColor;
}

