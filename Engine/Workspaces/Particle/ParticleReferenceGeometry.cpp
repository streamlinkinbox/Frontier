class ReferenceAccumulator
{
public:
    explicit ReferenceAccumulator(ParticleReferenceGeometryStorage& Target) noexcept : Sink(Target) {}

    void AddSegment(bool Additive, Vec3 Start, Vec3 End, float HalfWidth, Col4 ColorStart, Col4 ColorEnd, float Emissive) noexcept
    {
        ParticleGpuSegmentPrimitive Segment{};
        const Vec3 A = ToZUp(Start);
        const Vec3 B = ToZUp(End);
        Segment.StartPosWidth  = { A.X, A.Y, A.Z, std::max(HalfWidth, 0.0015f) };
        Segment.EndPosEmissive = { B.X, B.Y, B.Z, std::max(Emissive, 0.0f) };
        Segment.ColorStartRgba = ColorStart;
        Segment.ColorEndRgba   = ColorEnd;
        (Additive ? Sink.AdditiveSegments : Sink.AlphaSegments).push_back(Segment);
    }

    void AddLine(Vec3 Start, Vec3 End, Col4 Color, float HalfWidth = 0.012f) noexcept
    {
        AddSegment(false, Start, End, HalfWidth, Color, Color, 0.0f);
    }

    void AddGlowLine(Vec3 Start, Vec3 End, Col4 Color, float HalfWidth = 0.014f, float Emissive = 1.0f) noexcept
    {
        AddSegment(true, Start, End, HalfWidth, Color, Color, Emissive);
    }

    void AddTriangle(bool Additive, bool Translucent, Vec3 A, Vec3 B, Vec3 C, Col4 Color, float Emissive = 0.0f, float Metallic = 0.0f) noexcept
    {
        const Vec3 Normal = Normalize(Cross(Sub(B, A), Sub(C, A)));
        const std::array<Vec3, 3u> Corners = { A, B, C };
        for (const Vec3& Corner : Corners)
        {
            ParticleGpuSurfaceVertex Vert{};
            const Vec3 P = ToZUp(Corner);
            Vert.PosMetersEmissive = { P.X, P.Y, P.Z, std::max(Emissive, 0.0f) };
            Vert.NormalMetallic    = { Normal.X, Normal.Z, Normal.Y, std::clamp(Metallic, 0.0f, 1.0f) };
            Vert.ColorRgba         = Color;
            (Additive ? Sink.AdditiveSurfaceVertices : (Translucent ? Sink.TranslucentSurfaceVertices : Sink.OpaqueSurfaceVertices)).push_back(Vert);
        }
    }

    void AddQuad(bool Additive, bool Translucent, Vec3 A, Vec3 B, Vec3 C, Vec3 D, Col4 Color, float Emissive = 0.0f, float Metallic = 0.0f) noexcept
    {
        AddTriangle(Additive, Translucent, A, B, C, Color, Emissive, Metallic);
        AddTriangle(Additive, Translucent, A, C, D, Color, Emissive, Metallic);
    }

        // Reference captures expose faint albedo with emissive-adjacent sheen, so very dark authored colours
    // (velvet crimson, deep indigo) are lifted toward their hue before studio lighting is applied.
    [[nodiscard]] static Col4 LiftAlbedo(Col4 Source, float Lift) noexcept
    {
        const float Peak = std::max({ Source[0], Source[1], Source[2] });
        if (Peak <= 1.0e-4f)
        {
            return { Lift, Lift, Lift, Source[3] };
        }
        const float Gain = 1.0f + Lift / Peak;
        return {
            std::min(1.0f, Source[0] * Gain),
            std::min(1.0f, Source[1] * Gain),
            std::min(1.0f, Source[2] * Gain),
            Source[3],
        };
    }

    void AddRingXZ(Vec3 Centre, float Radius, int Segments, Col4 Color, float HalfWidth = 0.012f, bool Additive = false, float Emissive = 1.0f) noexcept
    {
        const int Count = std::max(3, Segments);
        for (int Idx = 0; Idx < Count; ++Idx)
        {
            const float A0 = (static_cast<float>(Idx) / static_cast<float>(Count)) * Pi * 2.0f;
            const float A1 = (static_cast<float>(Idx + 1) / static_cast<float>(Count)) * Pi * 2.0f;
            const Vec3  P0{ Centre.X + std::cos(A0) * Radius, Centre.Y, Centre.Z + std::sin(A0) * Radius };
            const Vec3  P1{ Centre.X + std::cos(A1) * Radius, Centre.Y, Centre.Z + std::sin(A1) * Radius };
            AddSegment(Additive, P0, P1, HalfWidth, Color, Color, Additive ? Emissive : 0.0f);
        }
    }

    void AddCylinder(Vec3 Bottom, Vec3 Top, float RadiusBottom, float RadiusTop, int Sides, Col4 Color, float Metallic = 0.25f, bool Translucent = false) noexcept
    {
        const int Count = std::max(3, Sides);
        const Vec3 Axis = Normalize(Sub(Top, Bottom));
        const AxisBasis Basis = BasisFrom(Axis);
        for (int Idx = 0; Idx < Count; ++Idx)
        {
            const float A0 = (static_cast<float>(Idx) / static_cast<float>(Count)) * Pi * 2.0f;
            const float A1 = (static_cast<float>(Idx + 1) / static_cast<float>(Count)) * Pi * 2.0f;
            const Vec3 B0 = Add(Bottom, Add(Mul(Basis.Right, std::cos(A0) * RadiusBottom), Mul(Basis.Forward, std::sin(A0) * RadiusBottom)));
            const Vec3 B1 = Add(Bottom, Add(Mul(Basis.Right, std::cos(A1) * RadiusBottom), Mul(Basis.Forward, std::sin(A1) * RadiusBottom)));
            const Vec3 T0 = Add(Top, Add(Mul(Basis.Right, std::cos(A0) * RadiusTop), Mul(Basis.Forward, std::sin(A0) * RadiusTop)));
            const Vec3 T1 = Add(Top, Add(Mul(Basis.Right, std::cos(A1) * RadiusTop), Mul(Basis.Forward, std::sin(A1) * RadiusTop)));
            AddTriangle(false, Translucent, B0, B1, T1, Color, 0.0f, Metallic);
            AddTriangle(false, Translucent, B0, T1, T0, Color, 0.0f, Metallic);
        }
    }

    void AddSphere(Vec3 Centre, float Radius, Col4 Color, float Metallic, int Latitudes, int Longitudes, bool AdditiveDome, float Emissive) noexcept
    {
        const int Lats = std::max(4, Latitudes);
        const int Lons = std::max(6, Longitudes);
        for (int Ia = 0; Ia < Lats; ++Ia)
        {
            const float P0 = -Pi * 0.5f + (static_cast<float>(Ia) / static_cast<float>(Lats)) * Pi;
            const float P1 = -Pi * 0.5f + (static_cast<float>(Ia + 1) / static_cast<float>(Lats)) * Pi;
            const float Y0 = std::sin(P0) * Radius;
            const float R0 = std::cos(P0) * Radius;
            const float Y1 = std::sin(P1) * Radius;
            const float R1 = std::cos(P1) * Radius;
            const float Shade = std::min(1.0f, std::max(0.0f, std::sin((static_cast<float>(Ia) / static_cast<float>(Lats)) * Pi) * 0.30f));
            const Col4 FaceColor = { std::min(1.0f, Color[0] + Shade * 0.26f), std::min(1.0f, Color[1] + Shade * 0.30f), std::min(1.0f, Color[2] + Shade * 0.38f), Color[3] };
            for (int Io = 0; Io < Lons; ++Io)
            {
                const float T0 = (static_cast<float>(Io) / static_cast<float>(Lons)) * Pi * 2.0f;
                const float T1 = (static_cast<float>(Io + 1) / static_cast<float>(Lons)) * Pi * 2.0f;
                const Vec3 A00{ Centre.X + std::cos(T0) * R0, Centre.Y + Y0, Centre.Z + std::sin(T0) * R0 };
                const Vec3 A10{ Centre.X + std::cos(T1) * R0, Centre.Y + Y0, Centre.Z + std::sin(T1) * R0 };
                const Vec3 A01{ Centre.X + std::cos(T0) * R1, Centre.Y + Y1, Centre.Z + std::sin(T0) * R1 };
                const Vec3 A11{ Centre.X + std::cos(T1) * R1, Centre.Y + Y1, Centre.Z + std::sin(T1) * R1 };
                if (Ia > 0)
                {
                    AddTriangle(AdditiveDome, false, A00, A10, A11, FaceColor, Emissive, Metallic);
                }
                if (Ia < Lats - 1)
                {
                    AddTriangle(AdditiveDome, false, A00, A11, A01, FaceColor, Emissive, Metallic);
                }
            }
        }
    }

    void AddCuboid(Vec3 Low, Vec3 High, Col4 Color, float Metallic, bool Translucent, float Emissive = 0.0f) noexcept
    {
        const Vec3 C000{ Low.X,  Low.Y,  Low.Z };
        const Vec3 C100{ High.X, Low.Y,  Low.Z };
        const Vec3 C110{ High.X, High.Y, Low.Z };
        const Vec3 C010{ Low.X,  High.Y, Low.Z };
        const Vec3 C001{ Low.X,  Low.Y,  High.Z };
        const Vec3 C101{ High.X, Low.Y,  High.Z };
        const Vec3 C111{ High.X, High.Y, High.Z };
        const Vec3 C011{ Low.X,  High.Y, High.Z };
        AddQuad(false, Translucent, C000, C100, C110, C010, Color, Emissive, Metallic);
        AddQuad(false, Translucent, C001, C011, C111, C101, Color, Emissive, Metallic);
        AddQuad(false, Translucent, C010, C110, C111, C011, Color, Emissive, Metallic);
        AddQuad(false, Translucent, C000, C001, C101, C100, Color, Emissive, Metallic);
        AddQuad(false, Translucent, C100, C101, C111, C110, Color, Emissive, Metallic);
        AddQuad(false, Translucent, C000, C010, C011, C001, Color, Emissive, Metallic);
    }

    void AddBoxWire(Vec3 Low, Vec3 High, Col4 Color, float HalfWidth = 0.008f) noexcept
    {
        const std::array<Vec3, 8u> Points = {{
            { Low.X, Low.Y, Low.Z }, { High.X, Low.Y, Low.Z }, { High.X, Low.Y, High.Z }, { Low.X, Low.Y, High.Z },
            { Low.X, High.Y, Low.Z }, { High.X, High.Y, Low.Z }, { High.X, High.Y, High.Z }, { Low.X, High.Y, High.Z },
        }};
        constexpr std::array<std::array<int, 2u>, 12u> Links = {{
            { 0, 1 }, { 1, 2 }, { 2, 3 }, { 3, 0 }, { 4, 5 }, { 5, 6 }, { 6, 7 }, { 7, 4 }, { 0, 4 }, { 1, 5 }, { 2, 6 }, { 3, 7 },
        }};
        for (const auto& Link : Links)
        {
            AddLine(Points[static_cast<std::size_t>(Link[0])], Points[static_cast<std::size_t>(Link[1])], Color, HalfWidth);
        }
    }

    [[nodiscard]] ParticleReferenceGeometryStorage& QuerySink() noexcept { return Sink; }

private:
    ParticleReferenceGeometryStorage& Sink;
};

