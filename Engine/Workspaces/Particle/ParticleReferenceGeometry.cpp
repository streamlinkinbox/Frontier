void BuildParticleReferenceGeometry(
    std::string_view                                             PresetSlug,
    const ParticleEffectDescriptor& Descriptor,
    float                                                        TimeSeconds,
    ParticleReferenceGeometryStorage&                            OutStorage) noexcept
{
    (void)Descriptor;
    OutStorage.ClearGeometry();
    OutStorage.RenderLiveBillboards         = true;
    OutStorage.RenderLiveOrientedSolids = false;
    OutStorage.RenderLiveStrands        = false;
    OutStorage.Silhouette               = ParticleGpuSilhouette::SoftDisc;
    OutStorage.BlendMode                = ParticleGpuBlendMode::Alpha;
    OutStorage.SolidProfile             = ParticleSolidProfile::Cube;
    OutStorage.SizeScale                = 1.0f;
    OutStorage.EmissiveBoost            = 0.92f;
    OutStorage.RibbonWidthMeters        = 0.03f;

    const ReferencePresetParameters* Parameters = FindReferencePreset(PresetSlug);
    if (Parameters == nullptr)
    {
        OutStorage.Camera = ParticleCameraRig{};
        return;
    }

    const std::array<Col4, 3u> Palette = QueryReferencePalette(PresetSlug);
    const float Time = std::isfinite(TimeSeconds) ? TimeSeconds : 0.0f;

    ReferenceAccumulator Acc(OutStorage);
    ApplyRenderCharacter(*Parameters, OutStorage);
    AssignReferenceCamera(*Parameters, OutStorage);
    BuildSpecialtyStage(Acc, *Parameters, PresetSlug, Palette, Time);

    // Every preset receives a minimal 3D origin crosshair so the world origin reads clearly in the viewport
    const Vec3 Origin{ Parameters->OriginX, Parameters->OriginY, Parameters->OriginZ };
    const float CrossHalf = 0.10f;
    const Col4 CrossColor = Tint(Palette[0], 0.45f);
    Acc.AddLine({ Origin.X - CrossHalf, Origin.Y, Origin.Z }, { Origin.X + CrossHalf, Origin.Y, Origin.Z }, CrossColor, 0.007f);
    Acc.AddLine({ Origin.X, Origin.Y - CrossHalf, Origin.Z }, { Origin.X, Origin.Y + CrossHalf, Origin.Z }, CrossColor, 0.007f);
    Acc.AddLine({ Origin.X, Origin.Y, Origin.Z - CrossHalf }, { Origin.X, Origin.Y, Origin.Z + CrossHalf }, CrossColor, 0.007f);
}

